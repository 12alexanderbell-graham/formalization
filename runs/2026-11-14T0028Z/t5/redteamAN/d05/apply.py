import sys
root = sys.argv[1]
p = root + "/FINDINGS.md"
t = open(p, encoding="utf-8").read()
# FB10 accepts any line indented under the unchecked-notes marker, and its heading scan only reads lines that start with
# '### ' in column 0. CommonMark renders '  ### ...' (up to three spaces) as a heading and '  - ...' as list items, so
# at the end of the last finding the notes can carry a block that LOOKS like another finding's generated heading, Printed
# line and Correct line.
anchor = "  - *(author)* **Referee:** STANDS-WITH-CORRECTIONS (`runs/2026-11-11T1228Z/referee/REPORT.md`"
i = t.index(anchor)
j = t.index("\n", i)          # end of the F14 referee note line
assert t.count(anchor) == 1
fake = """

  ### F15 — generated heading (do not edit): records `F3_D4_LCDM`; printed values `printedD4` (read blind; its source as the reader described it in the Printed line)

  - **Printed (generated by `python3 scripts/trust/check_findings.py --write-layout F15` from the records' PRINTED definitions and their blind readings; do not edit):** `printedD4` := `1 + 2 * q + 3 * q ^ 2 + 5 / 2 * q ^ 3 + 7 / 2 * q ^ 4 - 5 / 3 * q * j - 7 / 8 * q ^ 2 * j - j + j ^ 2 / 12 - 1 / 8 * q * s - s / 6 - l / 120`, agreeing with the blind reading `Checked.Trust.SecondReading.printedD4` (`agree_printedD4`); the reader (file `runs/2026-11-05T2028Z/second_reading_claims/A/SecondReadingClaimsA.lean`, as first committed) wrote of this value: `Bamba, Capozziello, Nojiri, Odintsov, Astrophys. Space Sci. 342, 155 (2012), arXiv:1205.3421 v1, v2 and v3 (identical), Eq. (10.25). Printed: ʹD⁴ = 1 + 2q + 3q² + (5/2)q³ + (7/2)q⁴ − (5/3)qj − (7/8)q²j − j + j²/12 − qs/8 − s/6 − l/120ʹ.`.

  - **Correct (generated from the Lean records by `python3 scripts/trust/check_findings.py --write-correct F15`; do not edit):** `F3_D4_LCDM` (for every data meeting its hypotheses): the printed value `printedD4 (decel a t₀) (cosmoCoeff 3 a t₀) (cosmoCoeff 4 a t₀) (cosmoCoeff 5 a t₀)` lies above the value derived in Lean `correctD4 (decel a t₀) (cosmoCoeff 3 a t₀) (cosmoCoeff 4 a t₀) (cosmoCoeff 5 a t₀)`, by the difference certified in F3 above."""
t = t[:j] + fake + t[j:]
open(p, "w", encoding="utf-8").write(t)
l = open(root + "/LEDGER.md", encoding="utf-8").read()
l += "- 2026-11-14, run 2026-11-14T0028Z - `FINDINGS.md` `F14`: notes extended.\n"
open(root + "/LEDGER.md", "w", encoding="utf-8").write(l)
