import sys, re
root = sys.argv[1]
p = root + "/FINDINGS.md"
t = open(p, encoding="utf-8").read()
def rep(t, old, new):
    assert t.count(old) == 1, old[:60]
    return t.replace(old, new)
# 1. a short index section whose title begins like the real one: the rules locate "\n## Verified findings" with
#    str.find, so they now read only this index and never the real section (which keeps its own '## Verified findings' heading)
t = rep(t, "\n## Verified findings\n\n### F1 ", "\n## Verified findings index\n\n## Verified findings\n\n### F1 ")
# the generated Printed lines are no longer recognised as generated by check_numbers (same scope function): tag their numbers
t = rep(t, "Both captions print β = −0.1988376", "Both captions print β = −0.1988376[src]")
t = t.replace("β = -0.1988)", "β = -0.1988[src])")
cp = root + "/scripts/trust/citations.txt"
c = open(cp, encoding="utf-8").read()
if "\n11.39\n" not in c:
    c += "11.39\n"
open(cp, "w", encoding="utf-8").write(c)
led = root + "/LEDGER.md"
l = open(led, encoding="utf-8").read()
l += "- 2026-11-14, run 2026-11-14T0028Z - FINDINGS.md: `F1` `F2` `F3` `F4` `F5` `F6` `F7` `F8` `F9` `F10` `F11` `F12` `F13` `F14`: section index line added above the findings; citation 11.39 registered.\n"
open(led, "w", encoding="utf-8").write(l)
# 2. F3: heading and Printed line now say a reader described the source of printedD4 (none did) and name arXiv v1
old_head = "`printedD4` (read blind; no reader file describes its source)"
new_head = "`printedD4` (read blind; its source as the reader described it in the Printed line)"
t = rep(t, old_head, new_head)
old = ", whose reader file is not under runs/ (the reading predates the blind route): the source is not described by a reader.\n- **Correct (generated from the Lean records by `python3 scripts/trust/check_findings.py --write-correct F3`"
new = ("; the reader (file `runs/2026-11-05T2028Z/second_reading_claims/A/SecondReadingClaimsA.lean`, as first committed) wrote of this value: "
       "`Capozziello, Cardone, Salzano, PRD 78, 063504 (2008), arXiv:0802.1583 v1 and v2 (identical), App. A, Eq. (A2), p. 16. "
       "Printed: ʹD⁴ = 1 + 2q + 3q² + (5/2)q³ + (7/2)q⁴ − (5/3)qj − (7/8)q²j − j + j²/12 − qs/8 − s/6 − l/120ʹ.`.\n"
       "- **Correct (generated from the Lean records by `python3 scripts/trust/check_findings.py --write-correct F3`")
t = rep(t, old, new)
open(p, "w", encoding="utf-8").write(t)
