"""Run 2026-11-25T1828Z: step bounds for the witness of hypothesis 1 of the curved pair (closed model, matter density
m = 121/10000, curvature term k = -1/10, total density 11/10). The radicand y(v) = m + k v^2 + (1 - m - k) v^6
increases on [21/50, 1], so 2/sqrt(y) decreases there: lower sums use right ends, upper sums left ends.
Exact rationals; each cell's square-root bound s is a rational with s^2 >= y(right end) (lower sum) or
s^2 <= y(left end) (upper sum). Prints the bounds and writes the Lean data module."""
from fractions import Fraction as F
import math, sys
m = F(121, 10000); k = F(-1, 10); c = 1 - m - k
def y(v): return m + k*v**2 + c*v**6
D = 10**7
def sq_up(x):   # rational s, denominator D, s^2 >= x
    s = F(math.ceil(math.sqrt(float(x))*D) + 1, D)
    while s*s < x: s += F(1, D)
    return s
def sq_dn(x):
    s = F(math.floor(math.sqrt(float(x))*D) - 1, D)
    while s*s > x: s -= F(1, D)
    assert s > 0
    return s
def breakpoints(a, n_geo, d0, ratio, n_lin):
    pts = [a]; d = d0
    for _ in range(n_geo):
        nxt = pts[-1] + d
        nxt = F(math.floor(nxt*D), D)
        pts.append(nxt); d *= ratio
        if pts[-1] >= F(7, 10): break
    last = pts[-1]
    for j in range(1, n_lin + 1):
        pts.append(last + (1 - last)*F(j, n_lin))
    pts = [F(math.floor(p*D), D) if p != 1 else F(1) for p in pts]
    return pts
def lower(pts):
    ss = [sq_up(y(b)) for b in pts[1:]]
    return sum(2/s*(pts[i+1]-pts[i]) for i, s in enumerate(ss)), ss
def upper(pts):
    ss = [sq_dn(y(a)) for a in pts[:-1]]
    return sum(2/s*(pts[i+1]-pts[i]) for i, s in enumerate(ss)), ss
