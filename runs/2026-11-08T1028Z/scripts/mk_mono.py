#!/usr/bin/env python3
"""Run 2026-11-08T1028Z: emit Work/<Flow>/<P>ExMono.lean from the Checked shooting construction:
`no_event_pos` = `no_event` with `q > 0 on [0, ∞)` (its internal `key`) added to the conclusion,
`exists_bvp_pos` = `exists_bvp` with that conjunct. Every replacement must match exactly once."""
import re, sys
def one(s, old, new):
    assert s.count(old) == 1, (old[:60], s.count(old)); return s.replace(old, new)
def theorem(txt, name):
    i = txt.index(f"theorem {name}")
    j = txt.find("\ntheorem ", i + 1)
    k = txt.find("\nend ", i + 1)
    e = min(x for x in (j, k) if x != -1)
    return txt[i:e].rstrip() + "\n"
for flow, P, base, mod in (("Hiemenz", "H", "Checked.Hiemenz", "HEx"), ("Homann", "Hm", "Checked.Homann", "HmEx")):
    lim = open(f"Checked/{flow}/{mod}Limit.lean").read()
    asm = open(f"Checked/{flow}/{mod}Assemble.lean").read()
    ne = theorem(lim, "no_event")
    ne = one(ne, "theorem no_event ", "theorem no_event_pos ")
    ne = one(ne, "    Filter.Tendsto (fun s => (Y s).2.1) Filter.atTop (nhds 1) := by",
             "    Filter.Tendsto (fun s => (Y s).2.1) Filter.atTop (nhds 1) ∧\n    (∀ t ∈ Ici (0 : ℝ), 0 < (Y t).2.2) := by")
    ne = one(ne, "fun t ht => (hq' t ht).congr_deriv (by rw [clf t ht, clq t ht, clp t ht]), ?_⟩",
             "fun t ht => (hq' t ht).congr_deriv (by rw [clf t ht, clq t ht, clp t ht]), ?_,\n    fun t ht => (key t ht).2⟩")
    eb = theorem(asm, "exists_bvp")
    eb = one(eb, "theorem exists_bvp ", "theorem exists_bvp_pos ")
    eb = one(eb, "f 0 = 0 ∧ p 0 = 0 ∧ Tendsto p atTop (𝓝 1) ∧\n", "f 0 = 0 ∧ p 0 = 0 ∧ Tendsto p atTop (𝓝 1) ∧ (∀ η ∈ Ici (0 : ℝ), 0 < q η) ∧\n")
    eb = one(eb, f"obtain ⟨d1, d2, d3, hlim⟩ := {base}.{mod}Limit.no_event ", f"obtain ⟨d1, d2, d3, hlim, hposq⟩ := no_event_pos ")
    eb = one(eb, "d1, d2, d3, ?_, ?_, hlim, ?_, ?_⟩", "d1, d2, d3, ?_, ?_, hlim, hposq, ?_, ?_⟩")
    hdr = lim[lim.index("import"):lim.index("/-!")]
    out = (f"import {base}.{mod}Limit\nimport {base}.{mod}Assemble\n\n"
           f"/-! {flow}, `{P}ExMono` (run 2026-11-08T1028Z, generated by `runs/2026-11-08T1028Z/scripts/mk_mono.py`):\n"
           f"the shooting construction of `{base}.{mod}Assemble.exists_bvp` with the positivity of q that\n"
           f"`{base}.{mod}Limit.no_event` proves internally added to its conclusion. -/\n\n"
           f"namespace Work.{flow}.{P}ExMono\n"
           f"open Set Filter Topology {base}.{mod}Base {base}.{mod}Flow {base}.{mod}Limit {base}.{mod}Assemble\n\n"
           f"/-- No shooting event: the trajectory solves the {flow} system on [0, ∞), p → 1, and q > 0. -/\n"
           + ne + "\n" + eb + f"\nend Work.{flow}.{P}ExMono\n")
    open(f"Work/{flow}/{P}ExMono.lean", "w").write(out)
    print("wrote", f"Work/{flow}/{P}ExMono.lean")
