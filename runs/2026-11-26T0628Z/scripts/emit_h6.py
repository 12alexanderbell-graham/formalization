#!/usr/bin/env python3
"""Run 2026-11-26T0628Z: emit the certificate modules of the hypothesis-6 witness at beta = -19/200 (K = 200/19)
from the exact generator output in runs/2026-11-26T0628Z/cells (make_h6_chains.sh):
  Checked/FSRev/RNinetyFive{Over,Slow,Tube}.lean  (runs/2026-11-11T1228Z/scripts/emit_rev.py, reversed-flow branch)
  Checked/FSRev/RNinetyFiveZero.lean              (the tube's cells again with side sideZ (5/8) (53/50), Φ PhiZ)
  Checked/FSAtt/RNinetyFive{Lo,Hi}.lean           (runs/2026-11-11T1028Z/scripts/emit_att_wc.py, attached branch)
Work.* names are renamed to Checked.* and module docs replaced (as runs/2026-11-12T2228Z/scripts/emit_rows.py)."""
import json, subprocess, re, pathlib
from fractions import Fraction as Fr
R = pathlib.Path(__file__).resolve().parents[3]
r = json.load(open(R / 'runs/2026-11-26T0628Z/scripts/rows_h6.json'))['095']; cd = R / 'runs/2026-11-26T0628Z/cells'
def lean(x):
    x = Fr(x); return f"({x.numerator} / {x.denominator})"
def fix(out, doc):
    s = out.read_text()
    for a in ('FSAtt', 'FSRev', 'FSSep', 'FSNeg'):
        s = s.replace(f'Work.{a}.', f'Checked.{a}.')
    assert 'import Mathlib\n' not in s and 'sorry' not in s and 'Work.' not in s, out
    s = re.sub(r'/-!.*?-/', '/-! ' + doc + ' -/', s, count=1, flags=re.S)
    out.write_text(s); return s
GEN = 'Every numeric side condition is checked by kernel evaluation over the rationals. Generated by `runs/2026-11-26T0628Z/scripts/emit_h6.py`'
for side, fn in (('Over', 'over'), ('Slow', 'slow'), ('Tube', 'tube')):
    mod = f'RNinetyFive{side}'; out = R / f'Checked/FSRev/{mod}.lean'
    A = {'over': r['Aover'], 'slow': r['Aslow'], 'tube': r['Ac']}[fn]
    args = ['python3', str(R / 'runs/2026-11-11T1228Z/scripts/emit_rev.py'), str(cd / f'rev_{fn}.json'), '8', str(out), mod, r['K'], lean(A)]
    if fn == 'tube': args += [r['R0'], lean(r['Aover']), lean(r['Aslow'])]
    subprocess.run(args, check=True)
    what = {'Over': 'below the window: every solution overshoots', 'Slow': 'above the window: every solution shows the lower slow-approach event', 'Tube': 'the tube around the window'}[side]
    s = fix(out, f'Generated weighted one-sided cells for the clamped adverse-sign field at the scaled coefficient of the hypothesis-six witness of the largest-wall-shear statement, reversed-flow branch, {what}. {GEN} (emitter `emit_rev.py`). Module `{mod}`.')
    if fn == 'tube':
        # the same cells with the side condition sideZ: every `sideP` of a segment check and of the chain proof replaced
        z = s.replace(f'namespace Checked.FSRev.{mod}', 'namespace Checked.FSRev.RNinetyFiveZero').replace(f'end Checked.FSRev.{mod}', 'end Checked.FSRev.RNinetyFiveZero')
        z = z.replace('import Checked.FSRev.RIdent', 'import Checked.FSRev.RIdent\nimport Checked.FSRev.RZero', 1)
        z = re.sub(r'^(open .*)$', r'\1 Checked.FSRev.RZero', z, count=1, flags=re.M)
        nseg = len(re.findall(r' sideP ', z))
        z = z.replace(' sideP ', ' (sideZ (5/8 : ℚ) (53/50 : ℚ)) ')
        n1 = z.count('(Φ := PhiT) (fun c hok hsd => sideP_spec c hok hsd)')
        z = z.replace('(Φ := PhiT) (fun c hok hsd => sideP_spec c hok hsd)', '(Φ := PhiZ ((5/8 : ℚ) : ℝ) ((53/50 : ℚ) : ℝ)) (fun c hok hsd => sideZ_spec (5/8 : ℚ) (53/50 : ℚ) c hok hsd)')
        n2 = z.count('PhiT (fun t => (Y t).1)')
        z = z.replace('PhiT (fun t => (Y t).1)', 'PhiZ ((5/8 : ℚ) : ℝ) ((53/50 : ℚ) : ℝ) (fun t => (Y t).1)')
        assert nseg >= 2 and n1 == nseg and n2 == 1, (nseg, n1, n2)
        z = z.split('/-- The certified tube', 1)[0].rstrip() + '\n\nend Checked.FSRev.RNinetyFiveZero\n'
        z = re.sub(r'/-!.*?-/', '/-! The cells of `RNinetyFiveTube` checked again with the side condition `sideZ` of `RZero` (from a time on: q positive, and below a bound where g is not positive; g negative at that time). ' + GEN + '. Module `RNinetyFiveZero`. -/', z, count=1, flags=re.S)
        (R / 'Checked/FSRev/RNinetyFiveZero.lean').write_text(z)
    print('wrote', mod)
for side, fn in (('Lo', 'slow'), ('Hi', 'over')):
    mod = f'RNinetyFive{side}'; out = R / f'Checked/FSAtt/{mod}.lean'
    subprocess.run(['python3', str(R / 'runs/2026-11-11T1028Z/scripts/emit_att_wc.py'), str(cd / f'att_{fn}.json'), '8', str(out), mod, r['K']], check=True)
    what = {'Lo': 'below the wall-shear window: every solution shows the slow-approach event', 'Hi': 'above the wall-shear window: every solution overshoots'}[side]
    fix(out, f'Generated weighted one-sided cells for the clamped adverse-sign field at the scaled coefficient of the hypothesis-six witness of the largest-wall-shear statement, attached branch, {what}. {GEN} (emitter `emit_att_wc.py`). Module `{mod}`.')
    print('wrote', mod)
