"""Emit the Lean data and chain modules of the Lane-Emden enclosure of index 3/2 (run 2026-11-19T1028Z)
from gen_le32.run().  usage: emit_le32.py <prefix Work|Checked>
Writes <prefix>/Math/LE32QData.lean and <prefix>/Math/LE32Chain.lean."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_le32 as G
from fractions import Fraction as F

PFX = sys.argv[1] if len(sys.argv) > 1 else 'Work'
SEG = 15


def q(x):
    x = F(x)
    return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"


def r(x):
    x = F(x)
    return f"({x.numerator}/{x.denominator} : ℝ)" if x.denominator != 1 else f"({x.numerator} : ℝ)"


def ql(p):
    return "[" + ", ".join(q(c) for c in p) + "]"


out = G.run(verbose=False)
st, sb, cells = out['st'], out['sb'], out['cells']
ns = f"{PFX}.Math.LE32QData"
glue = "Work.Math.LE32Glue" if PFX == 'Work' else "Checked.Math.LE32Glue"
cq = "Work.Math.LE32CellQ" if PFX == 'Work' else "Checked.Math.LE32CellQ"
L = []
L.append(f"import {'Work' if PFX == 'Work' else 'Checked'}.Math.LE32Glue\n")
L.append("/-! Generated by `runs/2026-11-19T1028Z/scripts/emit_le32.py` (do not edit by hand): the "
         "singular start and the validated cells of the Lane–Emden chain of index three halves as "
         "data; every side condition, defect bound and link decided by kernel evaluation over the "
         "rationals, one declaration per segment of cells. -/\n")
L.append(f"namespace {ns}")
L.append(f"open Set Checked.Sim.QPoly {cq} {glue}\n")
Pdt = G.deriv(st['P'])[1:]
assert G.deriv(st['P'])[0] == 0
L.append("def sd : StartData := ⟨" + ql(st['P']) + ",\n  " + ql(st['Pw']) + ",\n  " + ql(st['W2']) +
         ",\n  " + ql(Pdt) + ",\n  " + ", ".join(q(v) for v in [G.XI0, sb['eta'], st['R'], sb['L'], st['Mp'],
         sb['S0'], st['c0'], st['P0'], st['eta0'], st['gam0'], st['Rp']]) + "⟩\n")
L.append("theorem sd_ok : startOK sd = true := by\n  decide +kernel\n")
for c in cells:
    L.append(f"def c{c['i']} : Cell := ⟨" + ", ".join(q(c[k]) for k in
             ['t0', 'h', 'delta', 'eps', 'B', 'TH', 'K', 'S', 'c', 'P', 'eta', 'gam']) +
             ",\n  " + ql(c['pt']) + ",\n  " + ql(c['pp']) + ",\n  " + ql(c['pw']) + "⟩")
L.append("")
n = len(cells)
last = cells[-1]
body = list(range(n - 1))
segs = [body[i:i + SEG] for i in range(0, len(body), SEG)]
for k, sg in enumerate(segs):
    d = sg[-1] + 1
    L.append(f"theorem seg{k}_ok : segOK (183 / 50 : ℚ) false true c{d} [" + ", ".join(f"c{i}" for i in sg) +
             "] = true := by\n  decide +kernel\n")
L.append(f"theorem last_cell_ok : cellOK (183 / 50 : ℚ) c{last['i']} = true := by\n  decide +kernel\n")
L.append(f"theorem last_ok : lastOK c{last['i']} {q(G.W_LO)} {q(G.W_HI)} = true := by\n  decide +kernel\n")
L.append("theorem link0 : |qeval sd.P sd.ξ0 - c0.pt.headD 0| + sd.ξ0 ^ 2 / 6 * (sd.L * sd.η + sd.R) ≤ c0.δ ∧\n"
         "    |qeval (Checked.Sim.QPoly.qderiv sd.P) sd.ξ0 - c0.pp.headD 0| + sd.ξ0 / 3 * (sd.L * sd.η + sd.R) ≤ c0.δ := by\n  decide +kernel\n")
L.append(f"theorem sd_ξ0 : sd.ξ0 = {q(G.XI0)} := rfl")
L.append(f"theorem c0_t0 : c0.t0 = sd.ξ0 := rfl")
L.append(f"theorem last_t0 : c{last['i']}.t0 = {q(last['t0'])} := rfl")
L.append(f"theorem last_h : c{last['i']}.h = {q(last['h'])} := rfl\n")
L.append(f"end {ns}\n")
data = "\n".join(L)
data = data.replace("Checked.Sim.QPoly.qderiv", "Checked.Sim.QPoly.qderiv")
open(f"{PFX}/Math/LE32QData.lean", "w").write(data)

# ---- chain ----
D = ns
C = []
C.append(f"import {PFX}.Math.LE32QData\n")
C.append("/-! Generated by `runs/2026-11-19T1028Z/scripts/emit_le32.py`: chaining of the singular "
         "start, the kernel-checked segments and the last cell of the Lane–Emden chain of index "
         "three halves. -/\n")
C.append(f"namespace {PFX}.Math.LE32Certs")
C.append(f"open Set Checked.Sim Checked.Sim.QPoly {cq} {glue} {'Work' if PFX == 'Work' else 'Checked'}.Math.LE32Cell\n")
lo, hi = last['t0'], last['t0'] + last['h']
C.append("/-- Chaining of the start and all cells. -/")
C.append("theorem chain {θ φ : ℝ → ℝ}")
C.append("    (hθ : ∀ ξ ∈ Icc (0 : ℝ) (183 / 50), HasDerivWithinAt θ (φ ξ) (Icc 0 (183 / 50)) ξ)")
C.append("    (hφ0 : ContinuousWithinAt φ (Icc 0 (183 / 50)) 0)")
C.append("    (hφ : ∀ ξ ∈ Ioc (0 : ℝ) (183 / 50), HasDerivWithinAt φ (-(2 / ξ * φ ξ) - g32 (θ ξ)) (Icc 0 (183 / 50)) ξ)")
C.append("    (h0 : θ 0 = 1) :")
C.append(f"    (∀ t ∈ Ioc (0 : ℝ) {r(hi)}, φ t < 0) ∧ 0 < θ {r(lo)} ∧ θ {r(hi)} < 0 ∧")
C.append(f"      ∀ t ∈ Icc {r(lo)} {r(hi)}, ({r(G.W_LO)}) ≤ -(t ^ 2 * φ t) ∧ -(t ^ 2 * φ t) ≤ {r(G.W_HI)} := by")
C.append(f"""  have hX : ((183 / 50 : ℚ) : ℝ) = 183 / 50 := by norm_num
  have hθ' : ∀ t ∈ Icc (0 : ℝ) ((183 / 50 : ℚ) : ℝ), HasDerivWithinAt θ (φ t) (Icc 0 ((183 / 50 : ℚ) : ℝ)) t := by
    rw [hX]; exact hθ
  have hφ' : ∀ t ∈ Ioc (0 : ℝ) ((183 / 50 : ℚ) : ℝ),
      HasDerivWithinAt φ (-(2 / t * φ t) - g32 (θ t)) (Icc 0 ((183 / 50 : ℚ) : ℝ)) t := by
    rw [hX]; exact hφ
  have hξX : ((({D}.sd.ξ0 : ℚ)) : ℝ) ≤ 183 / 50 := by rw [{D}.sd_ξ0]; norm_num
  obtain ⟨n0, a0', b0'⟩ := start32 {D}.sd {D}.sd_ok hξX hθ hφ0 hφ h0
  obtain ⟨l1, l2⟩ := {D}.link0
  have l1' : |((qeval {D}.sd.P {D}.sd.ξ0 : ℚ) : ℝ) - (({D}.c0.pt.headD 0 : ℚ) : ℝ)| +
      ({D}.sd.ξ0 : ℝ) ^ 2 / 6 * ({D}.sd.L * {D}.sd.η + {D}.sd.R) ≤ {D}.c0.δ := by
    exact_mod_cast l1
  have l2' : |((qeval (qderiv {D}.sd.P) {D}.sd.ξ0 : ℚ) : ℝ) - (({D}.c0.pp.headD 0 : ℚ) : ℝ)| +
      ({D}.sd.ξ0 : ℝ) / 3 * ({D}.sd.L * {D}.sd.η + {D}.sd.R) ≤ {D}.c0.δ := by
    exact_mod_cast l2
  have p0 : (0 : ℝ) < ({D}.c0.t0 : ℝ) := by rw [{D}.c0_t0, {D}.sd_ξ0]; norm_num
  have a0 : |θ ({D}.c0.t0 : ℝ) - (({D}.c0.pt.headD 0 : ℚ) : ℝ)| ≤ ({D}.c0.δ : ℝ) := by
    rw [{D}.c0_t0]; exact abs_link a0' l1'
  have b0 : |φ ({D}.c0.t0 : ℝ) - (({D}.c0.pp.headD 0 : ℚ) : ℝ)| ≤ ({D}.c0.δ : ℝ) := by
    rw [{D}.c0_t0]; exact abs_link b0' l2'
  have g0 : ∀ t ∈ Ioc (0 : ℝ) ({D}.c0.t0 : ℝ), φ t < 0 := by
    rw [{D}.c0_t0]; exact n0""")
for k, sg in enumerate(segs):
    C.append(f"""  obtain ⟨o{k+1}, -, sn{k+1}, a{k+1}, b{k+1}⟩ := seg_q _ _ _ {D}.seg{k}_ok
    (fun t ht => hθ' t ⟨by linarith [ht.1], ht.2⟩) (fun t ht => hφ' t ⟨by linarith [ht.1], ht.2⟩) a{k} b{k}
  have g{k+1} := ioc_glue g{k} (sn{k+1} rfl)""")
K = len(segs)
li = last['i']
C.append(f"""  have pL : (0 : ℝ) < ({D}.c{li}.t0 : ℝ) := by rw [{D}.last_t0]; norm_num
  have hE : (({D}.c{li}.t0 : ℚ) : ℝ) + (({D}.c{li}.h : ℚ) : ℝ) = {r(hi)} := by
    rw [{D}.last_t0, {D}.last_h]; norm_num
  obtain ⟨e1, e2, e3, e4⟩ := last32 (T := (183 / 50 : ℚ)) {D}.c{li} _ _ {D}.last_cell_ok {D}.last_ok (θ := θ) (φ := φ)
    (fun t ht => hθ' t ⟨by linarith [ht.1], by linarith [ht.2, hE]⟩)
    (fun t ht => hφ' t ⟨by linarith [ht.1], by linarith [ht.2, hE]⟩) a{K} b{K}
  have hS : (({D}.c{li}.t0 : ℚ) : ℝ) = {r(lo)} := by rw [{D}.last_t0]; norm_num
  rw [hE, hS] at e3 e4
  rw [hS] at e1 g{K}
  rw [hE] at e2
  refine ⟨ioc_glue g{K} e3, e1, e2, fun t ht => ?_⟩
  have := e4 t ht
  push_cast at this
  exact this
""")
C.append(f"end {PFX}.Math.LE32Certs\n")
open(f"{PFX}/Math/LE32Chain.lean", "w").write("\n".join(C))
print('cells', n, 'segments', K, file=sys.stderr)
