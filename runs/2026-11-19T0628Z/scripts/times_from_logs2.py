#!/usr/bin/env python3
"""Run 2026-11-19T0628Z: per-module replay seconds for scripts/nanoda/shard_times.txt.
Inputs: `leanchecker-time <s> <modules>` lines (a group's time split evenly over its modules), files given in order,
a later file overriding an earlier one for the same module; then OVERRIDE:<module>:<seconds> arguments.
Used with: the four shard logs of 44424316043 (cf5003e, FNV-1a partition; old*.times) then shards 1-3 of 44451569867
(2957da6, assigned partition; new*.times), then OVERRIDE:Checked:<s> (the root module, replayed exactly by
scripts/leanchecker_exact.lean: its old group of eight took 10,159 s because `leanchecker Checked` replays the whole
library; its other seven modules are measured in new*.times).
Usage: times_from_logs2.py FILE... [OVERRIDE:M:S] > scripts/nanoda/shard_times.txt"""
import re, sys
w, src = {}, {}
for a in sys.argv[1:]:
    if a.startswith("OVERRIDE:"):
        _, m, s = a.split(":")
        w[m] = float(s); src[m] = "override"
        continue
    for line in open(a, encoding="utf-8", errors="replace"):
        m = re.search(r"leanchecker-time (\d+) (.*)$", line.strip())
        if m:
            mods = m.group(2).split()
            for x in mods:
                w[x] = int(m.group(1)) / len(mods); src[x] = a
print("# Replay seconds per Checked module (leanchecker shard logs; a group's time split evenly over its modules), read by\n"
      "# `scripts/leanchecker_shard.py --assign`. Generated by runs/2026-11-19T0628Z/scripts/times_from_logs2.py from the\n"
      "# four shard logs of CI run 44424316043 (cf5003e) and shards 1-3 of 44451569867 (2957da6), runs/2026-11-19T0628Z/ci_logs/;\n"
      f"# {len(w)} modules; the root module Checked measured locally (exact replay). Refresh from the newest full replay's logs.")
for m in sorted(w):
    print(f"{m} {w[m]:.1f}")
