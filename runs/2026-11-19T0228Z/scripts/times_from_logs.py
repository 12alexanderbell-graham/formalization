#!/usr/bin/env python3
"""Run 2026-11-19T0228Z: per-module replay seconds for scripts/nanoda/shard_times.txt from leanchecker shard job logs
(`leanchecker-time <s> <modules>` lines; a group's time is split evenly over its modules). A shard whose log has no such
lines (still running) may be given as EST:<total seconds>:<shard index>: its modules (FNV-1a shard of 4) get the total
split evenly, marked estimated.
Usage: times_from_logs.py LOG... [EST:10600:2] > scripts/nanoda/shard_times.txt"""
import re, sys, subprocess
sys.path.insert(0, "scripts")
import leanchecker_shard as L
w, est = {}, {}
for a in sys.argv[1:]:
    if a.startswith("EST:"):
        _, tot, i = a.split(":")
        mods = [m for m in L.modules() if L.fnv_shard(m, 4) == int(i)]
        for m in mods:
            est[m] = float(tot) / len(mods)
        continue
    for line in open(a, encoding="utf-8-sig", errors="replace"):
        m = re.search(r"leanchecker-time (\d+) (.*)$", line.strip())
        if m:
            mods = m.group(2).split()
            for x in mods:
                w[x] = int(m.group(1)) / len(mods)
print("# Replay seconds per Checked module (leanchecker shard logs; a group's time split evenly over its modules), read by\n"
      "# `scripts/leanchecker_shard.py --assign`. Generated by runs/2026-11-19T0228Z/scripts/times_from_logs.py from CI run\n"
      f"# 44424316043 (cf5003e); {len(w)} measured, {len([m for m in est if m not in w])} estimated (a shard still running: its\n"
      "# total split evenly). Refresh from the newest full replay's logs.")
for m in sorted(set(w) | set(est)):
    print(f"{m} {w.get(m, est.get(m)):.1f}")
