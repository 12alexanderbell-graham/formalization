#!/usr/bin/env python3
"""Run 2026-11-12T2228Z: copy of runs/2026-11-12T1828Z/scripts/emit_rows.py for the rows of runs/2026-11-12T2228Z/scripts/rows_rev.json (names and row words changed). Original: emit the reversed-flow certificate modules Checked/FSRev/R{Name}{Over,Slow,Tube}.lean for the
rows of rows_rev.json with runs/2026-11-11T1228Z/scripts/emit_rev.py (exact generator output in CELLDIR), then rename
Work.* namespaces/imports to Checked.* and replace the module doc (as runs/2026-11-11T1828Z/scripts/promote_rev.py).
usage: emit_rows.py CELLDIR tag..."""
import json, sys, subprocess, re, pathlib
from fractions import Fraction as Fr
R = pathlib.Path(__file__).resolve().parents[3]
rows = json.load(open(R / 'runs/2026-11-12T2228Z/scripts/rows_rev.json')); cd = sys.argv[1]
WHICH = {'03': 'the third row of the reverse-flow table', '04': 'the fourth row of the reverse-flow table', '05': 'the fifth row of the reverse-flow table', '06': 'the sixth row of the reverse-flow table', '07': 'the seventh row of the reverse-flow table', '08': 'the eighth row of the reverse-flow table', '09': 'the ninth row of the reverse-flow table', '11': 'the eleventh row of the reverse-flow table', '12': 'the twelfth row of the reverse-flow table', '13': 'the thirteenth row of the reverse-flow table', '14': 'the fourteenth row of the reverse-flow table', '16': 'the sixteenth row of the reverse-flow table'}
NAMES = {'03': 'Three', '04': 'Four', '05': 'Five', '06': 'Six', '07': 'Seven', '08': 'Eight', '09': 'Nine', '11': 'Eleven', '12': 'Twelve', '13': 'Thirteen', '14': 'Fourteen', '16': 'Sixteen'}
EM = R / 'runs/2026-11-11T1228Z/scripts/emit_rev.py'
def lean(x):
    x = Fr(x); return f"({x.numerator} / {x.denominator})"
for tag in sys.argv[2:]:
    r = rows[tag]; nm = NAMES[tag]; K = r['K']
    for side, fn in (('Over', 'over'), ('Slow', 'slow'), ('Tube', 'tube')):
        mod = f'R{nm}{side}'; out = R / f'Checked/FSRev/{mod}.lean'
        A = {'over': r['Aover'], 'slow': r['Aslow'], 'tube': r['Ac']}[fn]
        args = ['python3', str(EM), f'{cd}/{tag}_{fn}.json', '8', str(out), mod, K, lean(A)]
        if fn == 'tube': args += [r['R0'], lean(r['Aover']), lean(r['Aslow'])]
        subprocess.run(args, check=True)
        s = out.read_text()
        s = s.replace('Work.FSAtt.', 'Checked.FSAtt.').replace('Work.FSRev.', 'Checked.FSRev.')
        s = s.replace('Work.FSSep.', 'Checked.FSSep.').replace('Work.FSNeg.', 'Checked.FSNeg.')
        assert 'import Mathlib\n' not in s and 'sorry' not in s and 'Work.' not in s, mod
        what = {'Over': 'below the window: every solution overshoots', 'Slow': 'above the window: every solution shows the lower slow-approach event', 'Tube': 'the tube around the window'}[side]
        doc = (f'Generated weighted one-sided cells for the clamped adverse-sign field at the scaled coefficient of {WHICH[tag]}, '  # number-free (check: module docs name no numbers)
               f'reversed-flow branch, {what}. Every numeric side condition is checked by kernel evaluation over the rationals. '
               f'Generated by `runs/2026-11-12T2228Z/scripts/emit_rows.py` (run 2026-11-11T1228Z generator `gen_rev.py`, emitter `emit_rev.py`). Module `{mod}`.')
        s = re.sub(r'/-!.*?-/', '/-! ' + doc + ' -/', s, count=1, flags=re.S)
        if fn == 'tube':  # run 2026-11-12T2228Z: a tube chain ending at L != 3/2 proves TubeRA K lo hi L (Checked/FSRev/RTubeA.lean)
            Lt = Fr(*json.load(open(f'{cd}/{tag}_tube.json'))['L'])
            if Lt != Fr(3, 2):
                s, k = re.subn(r'theorem tube : TubeR (.*) := by\n', lambda m: f'theorem tube : Checked.FSRev.RTubeA.TubeRA {m.group(1)} ({Lt.numerator} / {Lt.denominator} : ℝ) := by\n', s)
                assert k == 1, mod
                s = s.replace('import Checked.FSRev.RCell\n', 'import Checked.FSRev.RCell\nimport Checked.FSRev.RTubeA\n', 1)
                assert 'import Checked.FSRev.RTubeA' in s, mod
        out.write_text(s)
        print('wrote', out.relative_to(R))
