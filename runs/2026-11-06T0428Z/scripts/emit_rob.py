"""Emit Work/Sim/RobCerts<k>.lean from gen_rob.py cells (exact rational checks first).
Usage: python3 emit_rob.py DEG CELLS_PER_MODULE [first_n_cells]"""
import sys, math, os
from fractions import Fraction as Fr
sys.argv_saved = list(sys.argv); sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(__file__))
import gen_rob as G
sys.argv = sys.argv_saved
DEG = int(sys.argv[1]); PER = int(sys.argv[2])
NMAX = int(sys.argv[3]) if len(sys.argv) > 3 else None
D = Fr(70); W = Fr(4900)
K = (W*10000 + 30000000) + W*30000000/D

def sig_up(x, n=3):
    if x <= 0: return Fr(0) if x == 0 else -sig_dn(-x, n)
    e = math.floor(math.log10(float(x))) - n + 1
    q = Fr(10)**e
    return Fr(math.ceil(x / q)) * q
def sig_dn(x, n=3):
    if x <= 0: return -sig_up(-x, n) if x < 0 else Fr(0)
    e = math.floor(math.log10(float(x))) - n + 1
    q = Fr(10)**e
    return Fr(math.floor(x / q)) * q
def grid_dn(x, digits): q = Fr(1, 10**digits); return Fr(math.floor(x / q)) * q
def grid_up(x, digits): q = Fr(1, 10**digits); return Fr(math.ceil(x / q)) * q
def lit(x):
    x = Fr(x)
    if x.denominator == 1: return f"({x.numerator} : ℝ)"
    return f"({x.numerator} / {x.denominator} : ℝ)"
def qlist(a):
    return "[" + ", ".join(f"({c.numerator}/{c.denominator} : ℚ)" if c.denominator != 1 else f"({c.numerator} : ℚ)" for c in a) + "]"

cells = G.run(DEG)
if NMAX: cells = cells[:NMAX]
Delta = Fr(0); c2, c3 = Fr(0), Fr(0)
rows = []
for i, cl in enumerate(cells):
    t0, h = cl['t0'], cl['h']; r = h/2
    p2, p3, d2, d3 = cl['p2'], cl['p3'], cl['d2'], cl['d3']
    assert c2 == cl['c2'] and c3 == cl['c3'] or i == 0
    L2e, U2e = G.lowup(p2, r); L3e, U3e = G.lowup(p3, r)
    L2, U2 = grid_dn(L2e, 30), grid_up(U2e, 30); L3, U3 = grid_dn(L3e, 25), grid_up(U3e, 25)
    e2 = sig_up(G.absbound(d2, r)); e3 = sig_up(G.absbound(d3, r))
    eps = sig_up(Fr(math.sqrt(float(W*e2*e2 + e3*e3))) * Fr(1001, 1000))
    assert W*e2*e2 + e3*e3 < eps*eps
    Aex = Fr(1, 25) + 10000*L3 + 2*30000000*L2
    A = sig_dn(Aex)
    Cf = lambda x: -(W*Fr(1, 25)) - W*10000*x + 2*30000000*x
    Cm = sig_up(max(abs(Cf(L2)), abs(Cf(U2))))
    st2, st3 = G.peval(p2, -r), G.peval(p3, -r)
    delta = sig_up(Delta + D*abs(c2 - st2) + abs(c3 - st3) + Fr(1, 10**40))
    assert delta > 0
    B = sig_up((delta + eps*h) * 2)
    for _ in range(60):
        # smallest 3-digit mu with hcond for this B
        a = W*A - K*B
        mu = (-float(a) + math.sqrt(float(a)**2 + float(W*Cm*Cm))) / (2*float(W))
        mu = sig_up(Fr(max(mu, 1e-15)) * Fr(1001, 1000))
        while not (Cm*Cm <= 4*mu*(W*A - K*B + W*mu)): mu = sig_up(mu * Fr(11, 10))
        x = mu*h
        assert x <= 1, (i, float(mu), float(h))
        Bn = sig_up((delta + eps*h) * (1 + x + x*x) * Fr(10001, 10000))
        if Bn <= B and Bn * Fr(11, 10) >= B: break
        B = Bn if Bn > B else (B + Bn) / 2 if False else Bn
    assert (delta + eps*h) * (1 + x + x*x) <= B and Cm*Cm <= 4*mu*(W*A - K*B + W*mu)
    assert -Fr(1, 1000) <= L2 - B/70 and U2 + B/70 <= Fr(1, 1000) and Fr(-1, 10) <= L3 - B and U3 + B <= Fr(11, 10)
    E2, E3 = G.peval(p2, r), G.peval(p3, r)
    n2, n3 = G.roundc(E2, 24), G.roundc(E3, 20)
    Dn = sig_up(B + D*abs(E2 - n2) + abs(E3 - n3) + Fr(1, 10**40))
    rows.append(dict(i=i, t0=t0, h=h, t1=t0+h, p2=p2, p3=p3, d2=d2, d3=d3, L2=L2, U2=U2, L3=L3, U3=U3,
                     e2=e2, e3=e3, eps=eps, A=A, Cm=Cm, mu=mu, delta=delta, B=B, Delta=Delta, c2=c2,
                     c3=c3, n2=n2, n3=n3, Dn=Dn))
    Delta, c2, c3 = Dn, n2, n3
print('cells', len(rows), 'final Delta', float(Delta), 'y2 err', float(Delta/70), 'centre', float(c2), float(c3), float(1-c2-c3))

hdr = '''import Work.Sim.RobCell{prev}

/-! Generated by `runs/2026-11-06T0428Z/scripts/emit_rob.py` from `gen_rob.py` (exact rational
certificates; do not edit by hand). Robertson cells {a}–{b}: polynomial centres in u = t − (t₀ + h/2),
certified defects and one-sided bounds, weighted norm 4900·e₂² + e₃². -/

set_option maxHeartbeats 8000000

namespace Work.Sim.RobCerts
open Set Checked.Sim Work.Sim.RobCell
'''
def emit_cell(c):
    i = c['i']
    out = []
    out.append(f"def p2c{i} : List ℚ := {qlist(c['p2'])}")
    out.append(f"def p3c{i} : List ℚ := {qlist(c['p3'])}")
    out.append(f"def d2c{i} : List ℚ := {qlist(c['d2'])}")
    out.append(f"def d3c{i} : List ℚ := {qlist(c['d3'])}")
    out.append(f'''
theorem step{i} {{P Q : ℝ → ℝ → ℝ}}
    (hP : ∀ y2 y3, -1 / 1000 ≤ y2 → y2 ≤ 1 / 1000 → -1 / 10 ≤ y3 → y3 ≤ 11 / 10 →
      P y2 y3 = robP y2 y3 ∧ Q y2 y3 = robQ y2 y3) {{y2 y3 : ℝ → ℝ}}
    (hd2 : ∀ t ∈ Icc (0 : ℝ) 40, HasDerivWithinAt y2 (P (y2 t) (y3 t)) (Icc 0 40) t)
    (hd3 : ∀ t ∈ Icc (0 : ℝ) 40, HasDerivWithinAt y3 (Q (y2 t) (y3 t)) (Icc 0 40) t)
    (h0 : 4900 * (y2 {lit(c['t0'])} - {lit(c['c2'])}) ^ 2 + (y3 {lit(c['t0'])} - {lit(c['c3'])}) ^ 2 ≤ {lit(c['Delta'])} ^ 2) :
    (∀ t ∈ Icc {lit(c['t0'])} {lit(c['t1'])}, -1 / 1000 ≤ y2 t ∧ y2 t ≤ 1 / 1000 ∧ -1 / 10 ≤ y3 t ∧ y3 t ≤ 11 / 10) ∧
    4900 * (y2 {lit(c['t1'])} - {lit(c['n2'])}) ^ 2 + (y3 {lit(c['t1'])} - {lit(c['n3'])}) ^ 2 ≤ {lit(c['Dn'])} ^ 2 := by
  have k := step p2c{i} p3c{i} hP (T := 40) (t0 := {lit(c['t0'])}) (h := {lit(c['h'])}) (Δ := {lit(c['Delta'])})
    (δ := {lit(c['delta'])}) (ε := {lit(c['eps'])}) (μ := {lit(c['mu'])}) (B := {lit(c['B'])})
    (A := {lit(c['A'])}) (Cm := {lit(c['Cm'])}) (L2 := {lit(c['L2'])}) (U2 := {lit(c['U2'])})
    (L3 := {lit(c['L3'])}) (U3 := {lit(c['U3'])}) (e2 := {lit(c['e2'])}) (e3 := {lit(c['e3'])})
    (c2 := {lit(c['c2'])}) (c3 := {lit(c['c3'])}) (n2 := {lit(c['n2'])}) (n3 := {lit(c['n3'])}) (Δ' := {lit(c['Dn'])})
    (by norm_num) (by norm_num) (by norm_num) hd2 hd3
    (fun u hu => le_trans (by norm_num [p2c{i}, evalQ]) (lower_sym p2c{i} hu))
    (fun u hu => le_trans (upper_sym p2c{i} hu) (by norm_num [p2c{i}, evalQ]))
    (fun u hu => le_trans (by norm_num [p3c{i}, evalQ]) (lower_sym p3c{i} hu))
    (fun u hu => le_trans (upper_sym p3c{i} hu) (by norm_num [p3c{i}, evalQ]))
    (fun u hu => by
      rw [show dEvalQ p2c{i} u - robP (evalQ p2c{i} u) (evalQ p3c{i} u) = evalQ d2c{i} u by
        simp only [p2c{i}, p3c{i}, d2c{i}, evalQ, dEvalQ, robP]; push_cast; ring]
      exact (abs_evalQ_le_sym d2c{i} hu).trans (by norm_num [d2c{i}, evalQ]))
    (fun u hu => by
      rw [show dEvalQ p3c{i} u - robQ (evalQ p2c{i} u) (evalQ p3c{i} u) = evalQ d3c{i} u by
        simp only [p2c{i}, p3c{i}, d3c{i}, evalQ, dEvalQ, robQ]; push_cast; ring]
      exact (abs_evalQ_le_sym d3c{i} hu).trans (by norm_num [d3c{i}, evalQ]))
    (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)
    (by rw [abs_le]; constructor <;> norm_num) (by rw [abs_le]; constructor <;> norm_num)
    (by norm_num) (by norm_num) (by norm_num) h0 (by norm_num)
    (by norm_num [p2c{i}, p3c{i}, evalQ, abs_of_nonneg, abs_of_nonpos])
    (by norm_num)
    (by norm_num [p2c{i}, p3c{i}, evalQ, abs_of_nonneg, abs_of_nonpos])
  rwa [show {lit(c['t0'])} + {lit(c['h'])} = {lit(c['t1'])} by norm_num] at k
''')
    return "\n".join(out)

base = 'Work/Sim'
nmod = (len(rows) + PER - 1) // PER
