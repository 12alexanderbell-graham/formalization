#!/usr/bin/env python3
"""Emit Work/Blasius/BQData.lean from the JSON of gen_blasius.py (run 2026-11-07T1228Z).
Re-checks every cell, link and the end condition in exact Fractions before writing Lean.
usage: emit_blasius.py cells.json SEG FDIG out.lean"""
import sys, json
from fractions import Fraction as Fr
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from gen_blasius import cellprop, qeval, head, up

d = json.load(open(sys.argv[1])); SEG = int(sys.argv[2]); FD = 10 ** int(sys.argv[3]); out = sys.argv[4]
F = lambda x: Fr(x[0], x[1])
L = F(d['L'])
cells = []
for c in d['cells']:
    cells.append({k: ([F(y) for y in v] if isinstance(v[0], list) else F(v)) for k, v in c.items()})
n = len(cells)
for i, c in enumerate(cells):
    ok, conds = cellprop(L, c); assert ok, (i, conds)
    if i + 1 < n:
        e = cells[i + 1]
        assert c['t0'] + c['h'] == e['t0']
        for k in ('pg', 'pp', 'pq'):
            assert abs(qeval(c[k], c['h']) - head(e[k])) + c['B'] <= e['δ'], (i, k)
last = cells[-1]
ends = [qeval(last[k], last['h']) for k in ('pg', 'pp', 'pq')]
fs = [Fr(round(x * FD), FD) for x in ends]
r = up(max(abs(a - b) for a, b in zip(ends, fs)) + last['B'], 10 ** 22)
assert last['t0'] + last['h'] == L
for a, b in zip(ends, fs): assert abs(a - b) + last['B'] <= r
q = lambda x: f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"
ql = lambda xs: "[" + ", ".join(q(x) for x in xs) + "]"
Ls = q(L)
o = []
o.append("import Work.Blasius.BCellQ\n")
o.append(f"""/-! Generated by `runs/2026-11-07T1228Z/scripts/gen_blasius.py` and `emit_blasius.py` (SEG = {SEG}):
{n} validated cells for the Blasius initial-value problem g''' + g g''/2 = 0, g(0) = g'(0) = 0,
g''(0) = 1 on [0, {L}]. Every numeric side condition, link and defect bound is checked by kernel
evaluation over ℚ (`decide +kernel`), one declaration per segment. `chain`: every solution is
enclosed at t = {L} within r of the generated end values. -/

namespace Work.Blasius.BQData
open Set Work.Blasius.BCellQ
""")
for i, c in enumerate(cells):
    o.append(f"def c{i} : Cell := ⟨{q(c['t0'])}, {q(c['h'])}, {q(c['δ'])}, {q(c['ε'])}, {q(c['B'])}, {q(c['GH'])}, {q(c['QH'])}, {q(c['K'])},\n  {ql(c['pg'])},\n  {ql(c['pp'])},\n  {ql(c['pq'])}⟩\n")
FG, FP, FQ = fs
segs = [list(range(s, min(s + SEG, n))) for s in range(0, n, SEG)]
for j, sg in enumerate(segs):
    lst = "[" + ", ".join(f"c{i}" for i in sg) + "]"
    if j + 1 < len(segs):
        o.append(f"theorem seg{j}_ok : chainTo {Ls} (fun e => linkOK e c{segs[j+1][0]}) {lst} = true := by\n  decide +kernel\n")
    else:
        o.append(f"theorem seg{j}_ok : chainTo {Ls} (endOK {Ls} {q(FG)} {q(FP)} {q(FQ)} {q(r)}) {lst} = true := by\n  decide +kernel\n")
Lr = f"({L.numerator} : ℝ)" if L.denominator == 1 else f"({L.numerator}/{L.denominator} : ℝ)"
o.append(f"""/-- The generated end values and radius. -/
def FG : ℚ := {q(FG)}
def FP : ℚ := {q(FP)}
def FQ : ℚ := {q(FQ)}
def R : ℚ := {q(r)}

/-- Every solution of g' = p, p' = q, q' = −g q/2 on [0, {L}] (derivatives within [0, {L}]) with
g(0) = p(0) = 0, q(0) = 1 is within `R` of (`FG`, `FP`, `FQ`) at {L}. -/
theorem chain {{g p q : ℝ → ℝ}}
    (hg : ∀ t ∈ Icc (0 : ℝ) {Lr}, HasDerivWithinAt g (p t) (Icc 0 {Lr}) t)
    (hp : ∀ t ∈ Icc (0 : ℝ) {Lr}, HasDerivWithinAt p (q t) (Icc 0 {Lr}) t)
    (hq : ∀ t ∈ Icc (0 : ℝ) {Lr}, HasDerivWithinAt q (-(g t * q t / 2)) (Icc 0 {Lr}) t)
    (h0 : g 0 = 0) (h1 : p 0 = 0) (h2 : q 0 = 1) :
    |g {Lr} - FG| ≤ R ∧ |p {Lr} - FP| ≤ R ∧ |q {Lr} - FQ| ≤ R := by
  have hX : (({Ls} : ℚ) : ℝ) = {Lr} := by norm_num
  have hs : Sol (({Ls} : ℚ) : ℝ) 0 g p q := by rw [hX]; exact ⟨hg, hp, hq⟩
  have b0 : InBox c0 g p q := by
    simp only [InBox, c0, List.headD_cons]; push_cast
    simp [h0, h1, h2]
""")
for j, sg in enumerate(segs):
    rest = "[" + ", ".join(f"c{i}" for i in sg[1:]) + "]"
    if j + 1 < len(segs):
        o.append(f"  have b{j+1} := seg_q0 c{segs[j+1][0]} {rest} c{sg[0]} seg{j}_ok hs b{j}\n")
    else:
        o.append(f"  have e := end_q0 {rest} c{sg[0]} seg{j}_ok hs b{j}\n")
o.append(f"  rw [hX] at e\n  exact e\n\nend Work.Blasius.BQData\n")
open(out, 'w').write("\n".join(o))
print('cells', n, 'segments', len(segs), 'FG', float(FG), 'FP', float(FP), 'FQ', float(FQ), 'R', float(r))
print('FG =', FG, '\nFP =', FP, '\nFQ =', FQ, '\nR =', r)
