"""Emit Lean certificate modules from gen_min.py's JSON tree (run 2026-11-05T0628Z).
usage: emit_min.py tree.json OUTDIR NFILES [MAXLEAVES]"""
import json, sys
from fractions import Fraction as F
tree = json.load(open(sys.argv[1]))
C = tree['c']; tree = tree['tree']
outdir = sys.argv[2]; nfiles = int(sys.argv[3]); maxleaves = int(sys.argv[4]) if len(sys.argv) > 4 else 10**9
def q(x):
    x = F(x)
    if x.denominator == 1: return f"({x.numerator} : ℝ)"
    return f"({x.numerator} / {x.denominator} : ℝ)"
leaves = []
def collect(t, name):
    t['name'] = name
    if 'split' in t:
        collect(t['lo'], name + 'a'); collect(t['hi'], name + 'b')
    else:
        leaves.append(t)
collect(tree, 'n')
leaves = leaves[:maxleaves]
HYP = "(H0 m l : ℝ) (h0 : {m0} ≤ m) (h1 : m ≤ {m1}) (h2 : {l0} ≤ l) (h3 : l ≤ {l1})\n    (hy : ∀ i, 0 ≤ e2OL m l (m16Table i).1)"
CORNER = "simp only [alf_val, gam_val]; norm_num [Lf, wt, e2OL, m16Table, Fin.sum_univ_succ]"
def qq(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator} / {x.denominator}"
def leaf_lean(t):
    m0, m1, l0, l1 = [q(x) for x in t['box']]
    head = f"theorem {t['name']} " + HYP.format(m0=m0, m1=m1, l0=l0, l1=l1) + f" :\n    ((({qq(C)}) : ℚ) : ℝ) ≤ chiSqOL H0 m l :=\n"
    if 'vac' in t:
        k = t['vac']
        return head[:-1] + " by"  + f"\n  have h := hy {k}\n  norm_num [e2OL, m16Table] at h\n  linarith\n"
    sv = "![" + ", ".join(q(x) for x in t['s']) + "]"
    sv = "![" + ", ".join(qq(x) for x in t['s']) + "]"
    m0q, m1q, l0q, l1q = [qq(x) for x in t['box']]
    return (head + f"  box_boundQ {sv}\n    ({qq(C)}) ({m0q}) ({m1q}) ({l0q}) ({l1q}) (by decide +kernel) H0 m l\n"
            + "    (by push_cast; linarith) (by push_cast; linarith) (by push_cast; linarith) (by push_cast; linarith) hy\n")
per = (len(leaves) + nfiles - 1) // nfiles
hdr = "import Mathlib\nimport Work.Data.Moresco16MinTools\n\n/-! Generated by runs/2026-11-05T0628Z/scripts/emit_min.py: leaf boxes {a}–{b} of the cover of\n[-1, 1] × [0, 4] for c = {c} (helper lemmas). -/\n\nnamespace Work.Data.Moresco16Min\nopen Work.Data.Moresco16\n\nset_option maxHeartbeats 8000000\n\n"
for f in range(nfiles):
    chunk = leaves[f*per:(f+1)*per]
    if not chunk: continue
    body = "\n".join(leaf_lean(t) for t in chunk)
    prev = f"import Work.Data.Moresco16MinCerts{f-1}\n" if f > 0 else ""
    open(f"{outdir}/Moresco16MinCerts{f}.lean", 'w').write(
        hdr.replace("import Work.Data.Moresco16MinTools\n", "import Work.Data.Moresco16MinTools\n" + prev)
        .format(a=f*per, b=f*per+len(chunk)-1, c=C) + body + "\nend Work.Data.Moresco16Min\n")
# tree module
def node_lean(t):
    if 'split' not in t: return ""
    m0, m1, l0, l1 = [q(x) for x in t['box']]
    v = 'm' if t['split'] == 'm' else 'l'
    mid = q(t['at'])
    a, b = t['lo']['name'], t['hi']['name']
    if v == 'm':
        body = f"  rcases le_total m {mid} with h | h\n  · exact {a} H0 m l h0 h h2 h3 hy\n  · exact {b} H0 m l h h1 h2 h3 hy\n"
    else:
        body = f"  rcases le_total l {mid} with h | h\n  · exact {a} H0 m l h0 h1 h2 h hy\n  · exact {b} H0 m l h0 h1 h h3 hy\n"
    return (node_lean(t['lo']) + node_lean(t['hi']) + f"theorem {t['name']} " + HYP.format(m0=m0, m1=m1, l0=l0, l1=l1)
            + f" :\n    ((({qq(C)}) : ℚ) : ℝ) ≤ chiSqOL H0 m l := by\n" + body + "\n")
if maxleaves >= 10**9:
    open(f"{outdir}/Moresco16MinCover.lean", 'w').write(
        f"import Mathlib\nimport Work.Data.Moresco16MinCerts{nfiles-1}\n\n/-! Generated by runs/2026-11-05T0628Z/scripts/emit_min.py: the bisection tree joining the leaf boxes\n(helper lemmas); `n` covers [-1, 1] × [0, 4]. -/\n\nnamespace Work.Data.Moresco16Min\nopen Work.Data.Moresco16\n\n"
        + node_lean(tree) + "end Work.Data.Moresco16Min\n")
print(len(leaves), 'leaves,', per, 'per file')
