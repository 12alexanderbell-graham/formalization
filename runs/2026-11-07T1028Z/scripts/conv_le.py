#!/usr/bin/env python3
"""Convert the Lane–Emden cell certificates (Checked/Math/LECerts{1,2,3}.lean, run 2026-11-05T0028Z) to
the kernel-evaluated form of Checked/Math/LECellQ.lean (template: run 2026-11-07T0828Z's conv_townes.py).

Cells step0..step88 become `Cell` values checked by `segOK` (sign invariant φ < 0, links); the parameters
of step89 give the link target `c89` (step89 itself, which also yields the enclosure on its whole cell,
and `lastFacts` stay as they were, in Checked/Math/LELast.lean). Every condition is re-checked in exact
Fractions, with the defect polynomials recomputed, before the Lean file is written.

usage: conv_le.py <repo root> <out LEQData.lean> <out LELast.lean> [SEG]
"""
import re
import sys
from fractions import Fraction as F
from pathlib import Path

ROOT = Path(sys.argv[1])
OUT = Path(sys.argv[2])
OUTL = Path(sys.argv[3])
SEG = int(sys.argv[4]) if len(sys.argv) > 4 else 15
src = ''.join((ROOT / f'Checked/Math/LECerts{i}.lean').read_text() for i in ('', 1, 2, 3))
T = F(69, 10)


def lst(name):
    m = re.search(r'^def ' + name + r' : List ℚ := \[(.*)\]$', src, re.M)
    return [F(t.strip()) for t in re.findall(r'\(([^()]*?) : ℚ\)', m.group(1))]


steps = sorted(int(k) for k in re.findall(r'^theorem step(\d+) ', src, re.M))
assert steps == list(range(90)), steps[-3:]
cells = []
for k in steps:
    m = re.search(r'have hc := cell pt%d pp%d \(θ := θ\) \(φ := φ\) \(T := 69 / 10\) \(t0 := \((.*?) : ℝ\)\) \(h := \((.*?) : ℝ\)\)\s*\(δ := \((.*?) : ℝ\)\) \(ε := \((.*?) : ℝ\)\) \(B := \((.*?) : ℝ\)\) \(TH := \((.*?) : ℝ\)\) \(K := \((.*?) : ℝ\)\)' % (k, k), src, re.S)
    t0, h, d, e, B, TH, K = [F(x) for x in m.groups()]
    cells.append(dict(t0=t0, h=h, d=d, e=e, B=B, TH=TH, K=K, pt=lst('pt%d' % k), pp=lst('pp%d' % k)))
# start output (startI) = input box of step0
m = re.search(r'\(∀ t ∈ Ioc \(0 : ℝ\) \(1 / 2\), φ t < 0\) ∧ \|θ \(1 / 2\) - \((.*?) : ℝ\)\| ≤ \((.*?) : ℝ\) ∧\s*\|φ \(1 / 2\) - \((.*?) : ℝ\)\| ≤ \((.*?) : ℝ\)', src)
s_th, s_r1, s_ph, s_r2 = [F(x) for x in m.groups()]


def qadd(p, q):
    n = max(len(p), len(q)); return [(p[i] if i < len(p) else 0) + (q[i] if i < len(q) else 0) for i in range(n)]
def qsmul(c, p): return [c * a for a in p]
def qsub(p, q): return qadd(p, qsmul(-1, q))
def qmul(p, q):
    if not p: return []
    return qadd(qsmul(p[0], q), [F(0)] + qmul(p[1:], q))
def qderiv(p):
    if not p: return []
    return qadd(p[1:], [F(0)] + qderiv(p[1:]))
def qeval(p, x):
    v = F(0)
    for c in reversed(p): v = c + x * v
    return v
def qabs(p, h): return qeval([abs(c) for c in p], h)
def head(p): return p[0] if p else F(0)


def cellprop(c):
    t0, h, d, e, B, TH, K, pt, pp = c['t0'], c['h'], c['d'], c['e'], c['B'], c['TH'], c['K'], c['pt'], c['pp']
    d2 = qadd(qadd(qmul([t0, F(1)], qderiv(pp)), qsmul(2, pp)), qmul([t0, F(1)], qmul(pt, qmul(pt, pt))))
    return [0 < t0, t0 + h <= T, 0 < h, 1 <= K, 2 / t0 + 3 * TH * TH <= K, K * h < 1, 0 <= d, 0 <= e,
            -(TH - F(1, 100)) <= head(pt) - h * qabs(pt[1:], h), head(pt) + h * qabs(pt[1:], h) <= TH - F(1, 100),
            qabs(qsub(qderiv(pt), pp), h) <= e, qabs(d2, h) <= e * t0,
            d * (1 / (1 - K * h)) + e / K * (1 / (1 - K * h) - 1) <= B, B < F(1, 100)]


chain = cells[:89]
for i, c in enumerate(chain):
    conds = cellprop(c)
    assert all(conds), (i, conds)
    assert head(c['pp']) + c['h'] * qabs(c['pp'][1:], c['h']) + c['B'] < 0, i
    d = cells[i + 1]
    assert c['t0'] + c['h'] == d['t0'], i
    assert abs(qeval(c['pt'], c['h']) - head(d['pt'])) + c['B'] <= d['d'], i
    assert abs(qeval(c['pp'], c['h']) - head(d['pp'])) + c['B'] <= d['d'], i
c0 = cells[0]
assert c0['t0'] == F(1, 2) and head(c0['pt']) == s_th and head(c0['pp']) == s_ph and c0['d'] == s_r1 == s_r2
print(f'89 cells checked in Fractions (defects recomputed); link target t0 = {cells[89]["t0"]}', file=sys.stderr)


def q(x): return f'({x.numerator}/{x.denominator} : ℚ)' if x.denominator != 1 else f'({x.numerator} : ℚ)'
def ql(p): return '[' + ', '.join(q(x) for x in p) + ']'


out = ["""import Checked.Math.LECellQ

/-! Lane–Emden, `LEQData`: the validated cells of the Lane–Emden chain as data, generated by `runs/2026-11-07T1028Z/scripts/conv_le.py` from the cells of the earlier certificate modules (same Taylor polynomials and cell parameters). Every side condition and every defect bound is decided by kernel evaluation over the rationals, one declaration per segment of cells. -/

namespace Checked.Math.LEQData
open Set Checked.Math.LECellQ
"""]
for i, c in enumerate(cells):
    out.append(f"def c{i} : Cell := ⟨{q(c['t0'])}, {q(c['h'])}, {q(c['d'])}, {q(c['e'])}, {q(c['B'])}, {q(c['TH'])}, {q(c['K'])},\n  {ql(c['pt'])},\n  {ql(c['pp'])}⟩")
X = q(T)
n = 89
segs = [list(range(k, min(k + SEG, n))) for k in range(0, n, SEG)]
for k, sg in enumerate(segs):
    nxt = segs[k + 1][0] if k + 1 < len(segs) else 89
    lst_ = '[' + ', '.join(f'c{i}' for i in sg) + ']'
    out.append(f"\ntheorem seg{k}_ok : segOK {X} false true c{nxt} {lst_} = true := by\n  decide +kernel")
for i in (0, 89):
    c = cells[i]
    out.append(f"\ntheorem c{i}_t0 : c{i}.t0 = {q(c['t0'])} := rfl\ntheorem c{i}_δ : c{i}.δ = {q(c['d'])} := rfl\n"
               f"theorem c{i}_pt : c{i}.pt.headD 0 = {q(head(c['pt']))} := rfl\ntheorem c{i}_pp : c{i}.pp.headD 0 = {q(head(c['pp']))} := rfl")
out.append("\nend Checked.Math.LEQData\n")
OUT.write_text('\n'.join(out))
print('segments:', [s[0] for s in segs], file=sys.stderr)

# LELast: step89, lastFacts and their definitions, verbatim from LECerts3
s3 = (ROOT / 'Checked/Math/LECerts3.lean').read_text()
header = s3[:s3.index('/-!')]
i0 = s3.index('def pt89 ')
i1 = s3.index('end Checked.Math.LECerts')
body = s3[i0:i1]
pre = s3[s3.index('-/', s3.index('/-!')) + 2:s3.index('\ndef ')]
OUTL.write_text(header.replace('import Checked.Math.LECerts2\n', 'import Checked.Math.LECerts\n')
                + "/-! Lane–Emden, `LELast`: the last cell of the Lane–Emden chain, which also gives the enclosure on the whole cell, and the facts read off it (copied from the earlier generated certificates, run 2026-11-05T0028Z). -/\n"
                + pre + '\n' + body + 'end Checked.Math.LECerts\n')
