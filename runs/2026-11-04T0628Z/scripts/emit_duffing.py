"""Emit Work/Sim/DuffingCerts.lean from the certificate JSON of gen_duffing.py (no hand
transcription). Usage: python3 emit_duffing.py cert.json out.lean [ncells]"""
import json, sys
from fractions import Fraction as F

cert = json.load(open(sys.argv[1]))
out = sys.argv[2]
NC = int(sys.argv[3]) if len(sys.argv) > 3 else len(cert['cells'])
h = F(1, 20)


def q(s):
    f = F(s)
    if f.denominator == 1:
        return f"({f.numerator} : ℚ)"
    return f"({f.numerator}/{f.denominator} : ℚ)"


def r(f):
    f = F(f)
    if f.denominator == 1:
        return f"({f.numerator} : ℝ)"
    return f"({f.numerator}/{f.denominator} : ℝ)"


def lst(cs):
    return "[" + ", ".join(q(c) for c in cs) + "]"


def ev(p, s):
    acc = F(0)
    for c in reversed(p):
        acc = F(c) + s * acc
    return acc


def T(i):
    return r(F(i, 20)) if i else "(0 : ℝ)"


L = []
L.append("""import Mathlib
import Work.Sim.ODETools
import Work.Sim.DuffingCell

/-! Generated by `runs/2026-11-04T0628Z/scripts/emit_duffing.py` from `gen_duffing.py`
(exact rational certificates; do not edit by hand). Cell i is [i/20, (i+1)/20]. -/

set_option maxHeartbeats 4000000

namespace Work.Sim.DuffingCerts
open Set Work.Sim Work.Sim.DuffingCell
""")
for c in cert['cells'][:NC]:
    i = c['i']
    t0, t1 = F(i, 20), F(i + 1, 20)
    L.append(f"def px{i} : List ℚ := {lst(c['px'])}")
    L.append(f"def pv{i} : List ℚ := {lst(c['pv'])}")
    L.append(f"def da{i} : List ℚ := {lst(c['d1'])}")
    L.append(f"def db{i} : List ℚ := {lst(c['d2'])}")
    pxh, pvh = ev(c['px'], h), ev(c['pv'], h)
    x0, v0 = c['px'][0], c['pv'][0]
    L.append(f"""
theorem step{i} {{x v : ℝ → ℝ}}
    (hdx : ∀ t ∈ Icc {T(i)} {T(i+1)}, HasDerivAt x (v t) t)
    (hdv : ∀ t ∈ Icc {T(i)} {T(i+1)}, HasDerivAt v (-1 * x t - 1 * x t ^ 3) t)
    (hbox : ∀ t ∈ Icc {T(i)} {T(i+1)}, (x t, v t) ∈ box)
    (h0 : |x {T(i)} - {r(x0)}| ≤ {r(c['delta'])}) (h0' : |v {T(i)} - {r(v0)}| ≤ {r(c['delta'])}) :
    (∀ t ∈ Icc {T(i)} {T(i+1)}, |x t - evalQ px{i} (t - {T(i)})| ≤ {r(c['B'])} ∧
      |v t - evalQ pv{i} (t - {T(i)})| ≤ {r(c['B'])}) ∧
    |x {T(i+1)} - {r(c['nx'])}| ≤ {r(c['ndelta'])} ∧ |v {T(i+1)} - {r(c['nv'])}| ≤ {r(c['ndelta'])} := by
  have heq : {T(i)} + (1 / 20 : ℝ) = {T(i+1)} := by norm_num
  have hc := cell px{i} pv{i} (t0 := {T(i)}) (h := 1 / 20) (δ := {r(c['delta'])}) (ε := {r(c['eps'])})
    (B := {r(c['B'])}) (by norm_num) (by norm_num) (by norm_num) (by norm_num)
    (by rw [heq]; exact hdx) (by rw [heq]; exact hdv) (by rw [heq]; exact hbox)
    (fun s hs => (abs_evalQ_le px{i} hs.1 hs.2).trans (by norm_num [px{i}, evalQ]))
    (fun s hs => (abs_evalQ_le pv{i} hs.1 hs.2).trans (by norm_num [pv{i}, evalQ]))
    (fun s hs => by
      rw [show dEvalQ px{i} s - evalQ pv{i} s = evalQ da{i} s by
        simp only [px{i}, pv{i}, da{i}, evalQ, dEvalQ]; push_cast; ring]
      exact (abs_evalQ_le da{i} hs.1 hs.2).trans (by norm_num [da{i}, evalQ]))
    (fun s hs => by
      rw [show dEvalQ pv{i} s + evalQ px{i} s + evalQ px{i} s ^ 3 = evalQ db{i} s by
        simp only [px{i}, pv{i}, db{i}, evalQ, dEvalQ]; push_cast; ring]
      exact (abs_evalQ_le db{i} hs.1 hs.2).trans (by norm_num [db{i}, evalQ]))
    (by rw [px{i}, evalQ_zero]; push_cast; exact h0) (by rw [pv{i}, evalQ_zero]; push_cast; exact h0')
    (by norm_num)
  rw [heq] at hc
  have hPx : evalQ px{i} ({T(i+1)} - {T(i)}) = {r(pxh)} := by norm_num [px{i}, evalQ]
  have hPv : evalQ pv{i} ({T(i+1)} - {T(i)}) = {r(pvh)} := by norm_num [pv{i}, evalQ]
  have he := hc {T(i+1)} ⟨by norm_num, le_rfl⟩
  rw [hPx, hPv, abs_le, abs_le] at he
  refine ⟨hc, ?_, ?_⟩ <;> rw [abs_le] <;> constructor <;> linarith [he.1.1, he.1.2, he.2.1, he.2.2]
""")
L.append("end Work.Sim.DuffingCerts\n")
open(out, 'w').write("\n".join(L))
