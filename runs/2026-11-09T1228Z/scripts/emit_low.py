#!/usr/bin/env python3
"""Run 2026-11-09T1228Z variant for the lower branch: modes slowL (side sideU, end endSL, event LCell.SlowL) and tube (side sideP, end endT, start ball |α − A| ≤ R0, conclusion: PhiT on [0, L] and the end state). Base: Run 2026-11-09T0828Z (port of runs/2026-11-08T2028Z/scripts/emit_k10_wc.py): emit Work/FSNeg/<Mod>.lean from
gen_neg_wc.py's JSON (cells for the CLAMPED adverse-sign field `Work.FSNeg.NBase.vN`, cell module
`Work.FSNeg.NCellWC`). `chainC`: every solution Y of Y' = vN t Y on [0, L] from (0, 0, A) has the event
`Slow Y` (mode 'slow') or `Over Y` (mode 'over'), with η = L.
usage: emit_low.py cells.json SEG out.lean ModName A_lean [R0 (tube)]"""
import sys, json
from fractions import Fraction as Fr
d = json.load(open(sys.argv[1])); SEG = int(sys.argv[2]); out = sys.argv[3]; mod = sys.argv[4]; Alean = sys.argv[5]
fr = lambda v: Fr(v[0], v[1])
def q(x):
    x = Fr(x)
    return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"
def ql(xs): return "[" + ", ".join(q(fr(v)) for v in xs) + "]"
cells = d['cells']; n = len(cells); L = fr(d['L']); mode = d['mode']; A = fr(d['A'])
assert mode in ('slow', 'over', 'slowL', 'tube')
R0 = Fr(sys.argv[6]) if mode == 'tube' else None
Ls = q(L); Lr = f"({L.numerator} / {L.denominator} : ℝ)" if L.denominator != 1 else f"({L.numerator} : ℝ)"
side = {'slow': 'sideS', 'over': 'sideT', 'slowL': 'sideU', 'tube': 'sideP'}[mode]
endb = {'slow': f'(endSl {Ls})', 'over': f'(endO {Ls})', 'slowL': f'(endSL {Ls})', 'tube': f'(endT {Ls})'}[mode]
Phi = {'slow': '(fun _ p q t => p t < 1 ∧ 0 < q t)', 'over': '(fun _ _ _ _ => True)', 'slowL': '(fun _ p _ t => p t < 1)', 'tube': 'PhiT'}[mode]
spec = {'slow': '(fun c hok hsd => sideS_spec c hok hsd)', 'over': '(fun _ _ _ _ _ _ _ _ _ _ => trivial)', 'slowL': '(fun c hok hsd => sideU_spec c hok hsd)', 'tube': '(fun c hok hsd => sideP_spec c hok hsd)'}[mode]
what = {'slow': "Slow: p < 1 and q > 0 on [0, L], and at L: 0 ≤ p, q < 3(1 − p), f > 11/30",
        'over': "overshoot: p > 1 at L",
        'slowL': "the lower Slow event: p < 1 on [0, L], and at L: 1/3 < p, 0 < q < 3(1 − p), f > 11/30",
        'tube': "inside the clamps with p > −1/2 on [0, L], and at L: 0 < f < 1, 0 < p < 1, 0 < q < 6/5"}[mode]
startw = f"Y(0) = (0, 0, {A})" if mode != 'tube' else f"Y(0) = (0, 0, α) for every α with |α − ({A})| ≤ {R0}"
lines = ["import Work.FSNeg.NCellWC", "import Work.FSNeg.LCell", "",
 f"/-! Generated by `runs/2026-11-09T1228Z/scripts/gen_low.py` (FS_K = 10) and `emit_low.py` (SEG = {SEG}; variants of run 0828Z's `gen_neg_wc.py`, `emit_neg_wc.py`):",
 f"{n} weighted one-sided cells for the clamped adverse-sign K = 10 (Falkner–Skan β = −1/10, scaled) field `vN`",
 (f"(equal to g''' + 10 g g'' − 1 + g'² = 0 on every cell's ball), g(0) = g'(0) = 0, g''(0) = {A} on [0, {L}]." if mode != 'tube' else f"(equal to g''' + 10 g g'' − 1 + g'² = 0 on every cell's ball), g(0) = g'(0) = 0, |g''(0) − ({A})| ≤ {R0} on [0, {L}]."),
 "Every numeric side condition, link, defect bound and sign condition is checked by kernel evaluation over ℚ",
 f"(`decide +kernel`), one declaration per segment. `chainC`: every solution of the clamped field shows {what}. -/", "",
 f"namespace Work.FSNeg.{mod}", "open Set Checked.Sim Work.FSNeg.NCellWC Work.FSNeg.NBase Work.FSNeg.LCell", ""]
keys = ['t0', 'h', 'δ', 'ε', 'B', 'μ', 'w1', 'w2', 'r1', 'r2']
for i, c in enumerate(cells):
    lines.append(f"def c{i} : Cell := ⟨" + ", ".join(q(fr(c[k])) for k in keys) + ", " +
                 ", ".join(ql(c[k]) for k in ('pg', 'pp', 'pq')) + "⟩")
lines.append("")
segs = []; s = 0
while s < n:
    e = min(s + SEG, n); segs.append((s, e)); s = e
for j, (s, e) in enumerate(segs):
    lst = "[" + ", ".join(f"c{i}" for i in range(s, e)) + "]"
    term = f"(fun e => linkOK e c{e})" if e < n else endb
    lines += [f"theorem seg{j}_ok : chainS {Ls} {side} {term} {lst} = true := by", "  decide +kernel", ""]
lines += ["theorem glue {P : ℝ → Prop} {a b : ℝ} (h1 : ∀ t ∈ Icc 0 a, P t) (h2 : ∀ t ∈ Icc a b, P t) :",
 "    ∀ t ∈ Icc 0 b, P t := by",
 "  intro t ht",
 "  rcases le_total t a with h | h",
 "  · exact h1 t ⟨ht.1, h⟩",
 "  · exact h2 t ⟨h, ht.2⟩", "",
 f"/-- Every solution Y of Y' = vN t Y (the clamped adverse-sign K = 10 field) on [0, {L}] (derivatives within the",
 f"interval) with {startw}: {what}. -/",
 "theorem chainC {Y : ℝ → ℝ × ℝ × ℝ}",
 f"    (hY : ∀ t ∈ Icc (0 : ℝ) {Lr}, HasDerivWithinAt Y (vN t (Y t)) (Icc 0 {Lr}) t)",
 (f"    (h0 : Y 0 = (0, 0, {Alean})) : {'Slow' if mode == 'slow' else ('SlowL' if mode == 'slowL' else 'Over')} Y := by" if mode != 'tube' else
  f"    {{α : ℝ}} (h0 : Y 0 = (0, 0, α)) (hα : |α - {Alean}| ≤ {R0.numerator} / {R0.denominator}) :\n    (∀ t ∈ Icc (0 : ℝ) {Lr}, PhiT (fun t => (Y t).1) (fun t => (Y t).2.1) (fun t => (Y t).2.2) t) ∧\n    (0 < (Y {Lr}).1 ∧ (Y {Lr}).1 < 1 ∧ 0 < (Y {Lr}).2.1 ∧ (Y {Lr}).2.1 < 1 ∧ 0 < (Y {Lr}).2.2 ∧ (Y {Lr}).2.2 < 6 / 5) := by"),
 f"  have hX : (({Ls} : ℚ) : ℝ) = {Lr} := by norm_num",
 f"  have hs : SolC (({Ls} : ℚ) : ℝ) 0 (fun t => (Y t).1) (fun t => (Y t).2.1) (fun t => (Y t).2.2) := by",
 "    rw [hX]",
 "    exact ⟨fun t ht => (hY t ht).fst, fun t ht => (hY t ht).snd.fst, fun t ht => (hY t ht).snd.snd⟩",
 "  have z0 : ((c0.t0 : ℚ) : ℝ) = 0 := by simp [c0]",
 "  have b0 : InBox c0 (fun t => (Y t).1) (fun t => (Y t).2.1) (fun t => (Y t).2.2) := by",
 "    unfold InBox; simp only [z0, h0]",
 ("    simp only [V, c0, List.headD_cons]; push_cast; norm_num" if mode != 'tube' else
  "    simp only [V, c0, List.headD_cons]; push_cast\n    have hα' := abs_le.1 hα\n    nlinarith [hα'.1, hα'.2]"),
 ""]
prev = "b0"; acc = None
for j, (s, e) in enumerate(segs):
    rest = "[" + ", ".join(f"c{i}" for i in range(s + 1, e)) + "]"
    if e < n:
        lines.append(f"  obtain ⟨b{j+1}, P{j}⟩ := segS_q0 (Φ := {Phi}) {spec} c{e} {rest} c{s} seg{j}_ok hs {prev}")
        prev = f"b{j+1}"
    else:
        if mode == 'slow':
            lines.append(f"  obtain ⟨E, P{j}⟩ := endSl_q0 (Φ := {Phi}) {spec} {rest} c{s} seg{j}_ok hs {prev}")
        elif mode == 'slowL':
            lines.append(f"  obtain ⟨E, P{j}⟩ := endSL_q0 {rest} c{s} seg{j}_ok hs {prev}")
        elif mode == 'tube':
            lines.append(f"  obtain ⟨E, P{j}⟩ := endT_q0 {rest} c{s} seg{j}_ok hs {prev}")
        else:
            lines.append(f"  have E := endO_q0 {rest} c{s} seg{j}_ok hs {prev}")
    if mode in ('slow', 'slowL', 'tube'):
        if j == 0:
            lines.append(f"  rw [z0] at P0"); acc = "P0"
        else:
            lines.append(f"  have A{j} := glue {acc} P{j}"); acc = f"A{j}"
if mode == 'slow':
    lines += [f"  rw [hX] at E {acc}", f"  exact ⟨{Lr}, by norm_num, {acc}, E.1, E.2.1, E.2.2⟩"]
elif mode == 'slowL':
    lines += [f"  rw [hX] at E {acc}", f"  exact ⟨{Lr}, by norm_num, {acc}, E.1, E.2.1, E.2.2.1, E.2.2.2⟩"]
elif mode == 'tube':
    lines += [f"  rw [hX] at E {acc}", f"  exact ⟨{acc}, E⟩"]
else:
    lines += [f"  rw [hX] at E", f"  exact ⟨{Lr}, by norm_num, E⟩"]
lines += ["", f"end Work.FSNeg.{mod}", ""]
open(out, 'w').write("\n".join(lines))
print("wrote", out, n, "cells", len(segs), "segments")
