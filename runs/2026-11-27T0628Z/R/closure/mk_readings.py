#!/usr/bin/env python3
"""Build Readings.lean from the three blind reader files, code unchanged (each wrapped in its own
namespace; the `import Mathlib` line is hoisted), and Frozen.lean from an edition's
src/Statements.lean (byte-identical body under namespace Frozen). Run 2026-11-27T0628Z, target R.
  python3 mk_readings.py <R dir> <path to an edition's Statements.lean>"""
import hashlib, os, sys
R, stmts = sys.argv[1], sys.argv[2]
out = ['import Mathlib', '']
for r in 'ABC':
    src = open(os.path.join(R, r, 'reading.lean'), encoding='utf-8').read()
    body = src.split('\n', 1)[1] if src.startswith('import Mathlib') else src
    out += [f'namespace Reader{r}', body.rstrip('\n'), f'end Reader{r}', '']
open(os.path.join(R, 'closure', 'Readings.lean'), 'w', encoding='utf-8').write('\n'.join(out))
s = open(stmts, encoding='utf-8').read()
assert s.startswith('import Mathlib\n')
body = s[len('import Mathlib\n'):]
open(os.path.join(R, 'closure', 'Frozen.lean'), 'w', encoding='utf-8').write(
    '-- Generated by mk_readings.py: body of src/Statements.lean, byte-identical, sha256 of the file '
    + hashlib.sha256(s.encode()).hexdigest() + '\nimport Mathlib\nnamespace Frozen\n' + body.rstrip('\n') + '\nend Frozen\n'
    + '\n-- for the replay\'s axiom check of every non-reading module\ntheorem Frozen.copied : True := trivial\n#print axioms Frozen.copied\n')
print('ok', hashlib.sha256(s.encode()).hexdigest())
