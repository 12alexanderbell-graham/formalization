"""Emit the Lean data modules of the Bonnor–Ebert chain (run 2026-11-12T0427Z) from gen_be.py.

Writes <out>/BEStart.lean (singular start on [0, 1/64], the template of emit_g.py's startI with the domain
[0, 7]) and <out>/BEQData.lean (cells as data; each segment one `decide +kernel` of `bchainTo`).
Every condition is re-checked here in exact Fractions in the form the Lean definitions compute it.
usage: emit_be.py <out dir> <namespace prefix, e.g. Work.Math> [SEG]
"""
from fractions import Fraction as F
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_be as BE
import g_base as G

OUT = sys.argv[1]
NS = sys.argv[2] if len(sys.argv) > 2 else 'Work.Math'
SEG = int(sys.argv[3]) if len(sys.argv) > 3 else 15


def q(x):
    x = F(x)
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"({x.numerator}/{x.denominator} : ℚ)"


def r(x):
    x = F(x)
    return f"({x.numerator} : ℝ)" if x.denominator == 1 else f"({x.numerator}/{x.denominator} : ℝ)"


sb, cells = BE.run()
assert all(c['marg'] > 0 for c in cells)

# ---------- exact re-check of every cell in the Lean form ----------
def lo(p, h): return p[0] - h * sum(abs(c) * h ** k for k, c in enumerate(p[1:]))
def hi(p, h): return p[0] + h * sum(abs(c) * h ** k for k, c in enumerate(p[1:]))
def qabs(p, h): return sum(abs(c) * h ** k for k, c in enumerate(p))
for c in cells:
    t0, h, d, e, B, EH, PH, K, pe, pp = (c[k] for k in ['t0', 'h', 'delta', 'eps', 'B', 'EH', 'PH', 'K', 'pe', 'pp'])
    d1 = G.add(G.deriv(pe), G.sc(-1, G.mul(pe, pp)))
    d2 = G.add(G.add(G.mul([t0, F(1)], G.deriv(pp)), G.sc(2, pp)), G.mul([t0, F(1)], pe))
    assert 0 < t0 and t0 + h <= BE.T and 0 < h and 1 <= K and PH + EH <= K and 2 / t0 + 1 <= K
    assert K * h < 1 and 0 <= d and 0 <= e
    assert -(EH - F(1, 100)) <= lo(pe, h) and hi(pe, h) <= EH - F(1, 100)
    assert -(PH - F(1, 100)) <= lo(pp, h) and hi(pp, h) <= PH - F(1, 100)
    assert qabs(d1, h) <= e and qabs(d2, h) <= e * t0
    assert d * (1 / (1 - K * h)) + e / K * (1 / (1 - K * h) - 1) <= B and B < F(1, 100)
    gp = BE.gpoly(pe, pp)
    if c['kind'] == 'inc':
        assert 0 < lo(gp, h) - B * (1 + PH)
    elif c['kind'] == 'dec':
        assert hi(gp, h) + B * (1 + PH) < 0
for a, b in zip(cells, cells[1:]):
    assert a['t0'] + a['h'] == b['t0']
    assert abs(G.ev(a['pe'], a['h']) - b['pe'][0]) + a['B'] <= b['delta']
    assert abs(G.ev(a['pp'], a['h']) - b['pp'][0]) + a['B'] <= b['delta']

inc = [c for c in cells if c['kind'] == 'inc']
gap = [c for c in cells if c['kind'] == 'none']
dec = [c for c in cells if c['kind'] == 'dec']
assert len(gap) == 1 and inc[-1]['t0'] + inc[-1]['h'] == BE.A and gap[0]['t0'] == BE.A
assert gap[0]['t0'] + gap[0]['h'] == BE.B and dec[0]['t0'] == BE.B and dec[-1]['t0'] + dec[-1]['h'] == BE.T
gi = gap[0]['i']
last = dec[-1]
fE, fP = G.ev(last['pe'], last['h']), G.ev(last['pp'], last['h'])

# ---------- BEStart.lean: the startI template with the domain [0, 7] ----------
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'emit_g_base.py')).read()
tmpl = src[src.index('theorem startI {{w φ'):src.index('""")\n\n\ndef pos_concl')]
P, Pd, W, rho, R, Mp, Rr = G.start()
eta, C, cc, e0, f0, d0 = sb['eta'], sb['C'], sb['c'], sb['e0'], sb['f0'], sb['delta']
S0 = G.S0
assert cells[0]['pe'][0] == e0 and cells[0]['pp'][0] == f0 and cells[0]['delta'] == d0
etaw0 = S0 ** 2 / 6 * (2 * eta + R)
PX, PdX = G.ev(P, S0), G.ev(Pd, S0)
MQ = G.ceil_q(G.absb(Pd, S0), 10 ** 12)
assert MQ + S0 / 3 * (2 * eta + R) <= 1
assert G.absb(P, S0) <= Mp and G.absb(rho, S0) <= Rr and Rr + Mp ** 4 * F(5, 96) <= R
assert Mp + eta <= F(1, 2) and S0 ** 2 / 6 * (2 * eta + R) < eta
ew = etaw0 + abs(PX - cc)
assert abs(cc) + ew <= F(1, 2)
assert 2 * ew + abs(cc) ** 6 * F(7, 4320) + abs(G.T6v(cc) - e0) <= d0
assert S0 / 3 * (2 * eta + R) + abs(PdX - f0) <= d0
HW = "(hw : ∀ s ∈ Icc (0 : ℝ) 7, HasDerivWithinAt w (φ s) (Icc 0 7) s)"
HP = ("(hφ : ∀ s ∈ Ioc (0 : ℝ) 7,\n      HasDerivWithinAt φ (-(2 / s * φ s) - Real.exp (w s)) (Icc 0 7) s)")
HP0 = "(hφ0 : ContinuousWithinAt φ (Icc 0 7) 0)"
env = dict(HW=HW, HP=HP, HP0=HP0, r=r, S0=S0, e0=e0, d0=d0, f0=f0, Mp=Mp, R=R, Rr=Rr, eta=eta,
           PX=PX, PdX=PdX, MQ=MQ, c=cc, ew=ew)
body = eval('f"""' + tmpl.replace('"""', '') + '"""', env)
body = body.replace('theorem startI', 'theorem startBE').replace('(X := 41 / 10)', '(X := 7)')
body = body.replace('Work.Math.GStart.', 'Checked.Math.GStart.')
lst = lambda name, p: f"def {name} : List ℚ := [{', '.join(q(x) for x in p)}]\n"
hdr = f"""import Checked.Sim.ODETools
import Checked.Math.LECell
import Checked.Math.GStart
import Checked.Math.GCell
import Checked.Math.GHelp

/-! Bonnor–Ebert sphere, `BEStart`: the singular start of the isothermal solution on [0, 1/64] for a solution
on [0, 7] (generated by `runs/2026-11-12T0427Z/scripts/emit_be.py` from the template of the Gelfand start,
`runs/2026-11-06T1228Z/scripts/emit_g.py`; exact rational certificates). -/

set_option maxHeartbeats 8000000
set_option maxRecDepth 100000

namespace {NS}.BEStart
open Set Checked.Sim Checked.Math.LECell Checked.Math.GCell Checked.Math.GHelp

"""
open(os.path.join(OUT, 'BEStart.lean'), 'w').write(
    hdr + lst('P', P) + lst('Pd', Pd) + lst('W', W) + lst('rho', rho) + '\n' + body + f'\nend {NS}.BEStart\n')

# ---------- BEQData.lean ----------
def cell(c):
    return (f"def c{c['i']} : Cell := ⟨{q(c['t0'])}, {q(c['h'])}, {q(c['delta'])}, {q(c['eps'])}, {q(c['B'])}, "
            f"{q(c['EH'])}, {q(c['PH'])}, {q(c['K'])},\n  [{', '.join(q(x) for x in c['pe'])}],\n"
            f"  [{', '.join(q(x) for x in c['pp'])}]⟩\n")

o = [f"""import Work.Math.BECellQ

/-! Bonnor–Ebert sphere, `BEQData`: {len(cells)} validated cells of the isothermal solution from 1/64 to 7 as
data (generated by `runs/2026-11-12T0427Z/scripts/emit_be.py`); cell conditions, links and the sign of
E − φ²/2 (mode 1 up to {float(BE.A)}, mode 2 from {float(BE.B)}) decided by kernel evaluation. -/

namespace {NS}.BEQData
open Set Checked.Math.GCellQ Work.Math.BECellQ

"""]
o += [cell(c) for c in cells]
o.append('\n')
segs = []
def segments(lst_, mode, term_next):
    out = []
    for k in range(0, len(lst_), SEG):
        part = lst_[k:k + SEG]
        nxt = lst_[k + SEG] if k + SEG < len(lst_) else term_next
        out.append((part, mode, nxt))
    return out
segs = segments(inc, 1, gap[0])
for j, (part, mode, nxt) in enumerate(segs):
    names = ', '.join(f"c{c['i']}" for c in part)
    o.append(f"theorem inc{j}_ok : bchainTo (7 : ℚ) 1 (fun e => linkOK e c{nxt['i']}) [{names}] = true := by\n  decide +kernel\n\n")
o.append(f"theorem gap_ok : decide (CellProp (7 : ℚ) c{gi}) = true := by\n  decide +kernel\n\n")
o.append(f"theorem gap_link : linkOK c{gi} c{dec[0]['i']} = true := by\n  decide +kernel\n\n")
dsegs = segments(dec, 2, None)
for j, (part, mode, nxt) in enumerate(dsegs):
    names = ', '.join(f"c{c['i']}" for c in part)
    if nxt is None:
        o.append(f"theorem dec{j}_ok : bchainTo (7 : ℚ) 2 (endOK 7 {q(fE)} {q(fP)} {q(last['B'])}) [{names}] = true := by\n  decide +kernel\n\n")
    else:
        o.append(f"theorem dec{j}_ok : bchainTo (7 : ℚ) 2 (fun e => linkOK e c{nxt['i']}) [{names}] = true := by\n  decide +kernel\n\n")
for c in [cells[0], gap[0], dec[0]] + [p[0] for p, _, _ in segs[1:]] + [p[0] for p, _, _ in dsegs[1:]]:
    i = c['i']
    o.append(f"theorem c{i}_t0 : c{i}.t0 = {q(c['t0'])} := rfl\n")
    o.append(f"theorem c{i}_δ : c{i}.δ = {q(c['delta'])} := rfl\n")
    o.append(f"theorem c{i}_pe : c{i}.pe.headD 0 = {q(c['pe'][0])} := rfl\n")
    o.append(f"theorem c{i}_pp : c{i}.pp.headD 0 = {q(c['pp'][0])} := rfl\n\n")
o.append(f"theorem c{gi}_h : c{gi}.h = {q(gap[0]['h'])} := rfl\n\nend {NS}.BEQData\n")
open(os.path.join(OUT, 'BEQData.lean'), 'w').write(''.join(o))
print('cells', len(cells), 'inc segs', len(segs), 'dec segs', len(dsegs), 'gap cell', gi, file=sys.stderr)
