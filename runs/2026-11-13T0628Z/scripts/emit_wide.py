#!/usr/bin/env python3
"""Run 2026-11-13T0628Z: emit the certificate modules Checked/FSRevW/W{Name}{Over,Slow,Tube}.lean of a reversed-flow
row for the stack with a free shear clamp level (Checked/FSRevW/WCell.lean, WBase.lean), from the exact generator
output in CELLDIR (runs/2026-11-13T0428Z/scripts/gen_rev_wide.py via runs/2026-11-13T0628Z/scripts/chain.sh).
It runs run 2026-11-11T1228Z's emitter emit_rev.py and rewrites its output for the W stack; every rewrite is asserted.
usage: emit_wide.py CELLDIR tag Name QC"""
import json, sys, subprocess, re, pathlib
from fractions import Fraction as Fr

R = pathlib.Path(__file__).resolve().parents[3]
rows = json.load(open(R / 'runs/2026-11-12T2228Z/scripts/rows_rev.json'))
cd, tag, nm, QC = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
assert re.fullmatch(r'\d+', QC), 'integer clamp level'
EM = R / 'runs/2026-11-11T1228Z/scripts/emit_rev.py'
WHICH = {'02': 'the second row of the reverse-flow table', '01': 'the first row of the reverse-flow table'}


def lean(x):
    x = Fr(x)
    return f"({x.numerator} / {x.denominator})"


def sub(s, pat, rep, count=None, regex=False):
    if regex:
        s2, n = re.subn(pat, rep, s)
    else:
        n = s.count(pat)
        s2 = s.replace(pat, rep)
    assert n > 0, ('no match', pat[:80])
    if count is not None:
        assert n == count, ('count', pat[:80], n)
    return s2


r = rows[tag]
K = r['K'] if '/' in r['K'] else r['K'] + '/1'
for side, fn in (('Over', 'over'), ('Slow', 'slow'), ('Tube', 'tube')):
    old = f'R{nm}{side}'
    mod = f'W{nm}{side}'
    out = R / f'Checked/FSRevW/{mod}.lean'
    A = {'over': r['Aover'], 'slow': r['Aslow'], 'tube': r['Ac']}[fn]
    tmp = pathlib.Path('/tmp') / f'emit_wide_{old}.lean'
    args = ['python3', str(EM), f'{cd}/{tag}_{fn}.json', '8', str(tmp), old, K, lean(A)]
    if fn == 'tube':
        args += [r['R0'], lean(r['Aover']), lean(r['Aslow'])]
    subprocess.run(args, check=True)
    s = tmp.read_text()
    s = s.replace('Work.FSAtt.', 'Checked.FSAtt.').replace('Work.FSRev.', 'Checked.FSRev.')
    s = sub(s, 'import Checked.FSRev.RIdent\n', 'import Checked.FSRev.RIdent\nimport Checked.FSRevW.WCell\n', 1)
    s = sub(s, f'namespace Checked.FSRev.{old}', f'namespace Checked.FSRevW.{mod}', 1)
    s = sub(s, f'end Checked.FSRev.{old}', f'end Checked.FSRevW.{mod}', 1)
    s = sub(s, 'Checked.FSRev.RCell Checked.FSRev.RIdent\n', 'Checked.FSRev.RCell Checked.FSRev.RIdent\n  Checked.FSRevW.WBase Checked.FSRevW.WCell\n', 1)
    s = sub(s, r'chainS \(([^()]*) : ℚ\) \(([^()]*) : ℚ\) ', rf'chainW (\1 : ℚ) (\2 : ℚ) ({QC} : ℚ) ', regex=True)
    s = sub(s, r'have hs : SolC \((\(\([^()]* : ℚ\) : ℚ\) : ℝ)\) ', rf'have hs : SolW (\1) ((({QC} : ℚ) : ℚ) : ℝ) ', 1, regex=True)
    s = sub(s, r'(  have hK : [^\n]*\n)', rf'\1  have hQ : ((({QC} : ℚ) : ℚ) : ℝ) = ({QC} : ℝ) := by norm_num\n', 1, regex=True)
    s = sub(s, '    rw [hX, hK]\n', '    rw [hX, hK, hQ]\n', 1)
    if fn == 'tube':
        s = sub(s, r'vS \(([^()]*) : ℝ\) t \(Y t\)', rf'vW ({QC} : ℝ) (\1 : ℝ) t (Y t)', regex=True)
    s = sub(s, 'Y\' = vS K t Y', f'Y\' = vW {QC} K t Y')
    for a, b in [('segS_q0 ', 'segW_q0 '), ('endT_q0 ', 'endTW_q0 '), ('endSR_q0 ', 'endSRW_q0 '), ('endO_q0 ', 'endOW_q0 ')]:
        if a in s:
            s = s.replace(a, b)
    s = s.replace('sideU_spec c hok', 'sideU_specW c hok').replace('sideP_spec c hok', 'sideP_specW c hok')
    s = s.replace('(Φ := PhiT)', f'(Φ := PhiW (({QC} : ℚ) : ℝ))')
    if fn == 'tube':
        s = sub(s, r'PhiT \(fun t', rf'PhiW {QC} (fun t', 1, regex=True)
        s = sub(s, r'  rw \[hX\] at E (A\d+)\n', r'  rw [hX] at E \1\n  rw [hQ] at \1\n', 1, regex=True)
        Lt = Fr(*json.load(open(f'{cd}/{tag}_tube.json'))['L'])
        s = sub(s, r'theorem tube : TubeR (.*) := by\n',
                lambda m: f'theorem tube : TubeW {QC} {m.group(1)} ({Lt.numerator} / {Lt.denominator} : ℝ) := by\n', 1, regex=True)
    else:
        s = sub(s, r'theorem chain : ChainA ', f'theorem chain : ChainW {QC} ', 1)
    for bad in ['chainS ', 'SolC ', 'vS (', 'PhiT', 'ChainA', 'TubeR ', 'segS_q0', 'sideP_spec ', 'sideU_spec ', 'Work.', 'sorry']:
        assert bad not in s, (mod, bad, [l for l in s.split('\n') if bad in l][:2])
    what = {'Over': 'below the window: every solution overshoots', 'Slow': 'above the window: every solution shows the lower slow-approach event', 'Tube': 'the tube around the window'}[side]
    doc = (f'Generated weighted one-sided cells for the clamped adverse-sign field with the wider shear clamp at the scaled coefficient of {WHICH[tag]}, '
           f'reversed-flow branch, {what}. Every numeric side condition is checked by kernel evaluation over the rationals. '
           f'Generated by `runs/2026-11-13T0628Z/scripts/emit_wide.py` (generator `runs/2026-11-13T0428Z/scripts/gen_rev_wide.py`, emitter of run 2026-11-11T1228Z `emit_rev.py`). Module `{mod}`.')
    s = re.sub(r'/-!.*?-/', lambda m: '/-! ' + doc + ' -/', s, count=1, flags=re.S)
    out.write_text(s)
    print('wrote', out.relative_to(R))
