def lin(name):
    m = re.search(r'lemma ' + name + r' \(Ω : ℝ\)[^\n]*\n\s*(.*?) := by', src)
    t = m.group(1)
    t = t.split('≤')[1] if name.startswith('U') else t.split('≤')[0]
    nums = re.findall(r'\((-?\d+) / (\d+) : ℝ\)', t)
    a = F(int(nums[0][0]), int(nums[0][1])); b = F(int(nums[1][0]), int(nums[1][1]))
    if name.startswith('L'):
        b = -b
    return a, b


def lean_lin(p, name):
    a, b = p
    if name.startswith('L'):
        return f'(({a.numerator} / {a.denominator} : ℝ) - ({-b.numerator} / {b.denominator} : ℝ) * Ω)'
    return f'(({a.numerator} / {a.denominator} : ℝ) + ({b.numerator} / {b.denominator} : ℝ) * Ω)'


def q(x):
    return f'({x.numerator} / {x.denominator} : ℝ)'


def ev(p, O):
    return p[0] + p[1] * O


def rho_up(r, U, L, a, b):
    v = max(r * ev(U, O) / (KAP * ev(L, O)) for O in (a, b))
    # round up to 6 decimals
    return F(math.ceil(float(v) * 10**6) + 1, 10**6)


