#!/bin/bash
# T5 judge v6 (run 1028Z) = v5 + the prose/meaning check (check_prose.py, incl. --base) + the author regenerating the validation packet (make_packet.py fails on missing docstrings). v5 header:: the checks on main as CI runs them, incl. `lake build Work` (the CI work
# job and the axiom-audit step build Work; the 0028Z judge omitted it) and the certified-number check.
# Works in a second worktree W (default /home/claude/fz2) at BASE; the main tree is untouched.
# Author model as in 0028Z: the author relocks frozen.txt (TRUST_RELOCK=1) and commits; a LEDGER
# line is added only if the defect itself adds one. TRUST_MAP.md as the defect leaves it.
# Usage: judge_v5.sh <defect dir with apply.py | NONE> <out file>
set -u
W=${W:-/home/claude/fz2}; D=$1; OUT=$2
export PATH=$HOME/.elan/bin:$PATH
cd $W
BASE=$(git rev-parse HEAD)
{
echo "defect: $D  base: $BASE"; date -u +%T
if [ "$D" != NONE ]; then python3 $D/apply.py $W || echo "RESULT APPLY_FAILED"; fi
echo "--- changed files"; git status --porcelain
cp TRUST_MAP.md /tmp/v6_map_defect.md
# the author regenerates TRUST_MAP.md (one command, CI names it) unless the defect hand-edits it
TOUCHED_MAP=0; git diff --quiet -- TRUST_MAP.md || TOUCHED_MAP=1
echo "--- build Checked Work"
if timeout 2400 lake build Checked Work > /tmp/v6_build.log 2>&1; then echo "build: PASS"; B=0; else echo "build: FAIL"; B=1; grep -E "error" /tmp/v6_build.log | head -n 12; fi
echo "--- forbidden tokens"
if grep -rnE '\b(sorry|admit|axiom|native_decide|implemented_by|debug\.skipKernelTC)\b' Checked Checked.lean; then T=1; echo "tokens: FAIL"; else T=0; echo "tokens: PASS"; fi
S=1; M=1; N=1; R=1; P=1; K=1
if [ $B = 0 ]; then
  echo "--- trust step (author relocks)"
  if TRUST_RELOCK=1 timeout 900 lake env lean scripts/trust/StatementDeps.lean > /tmp/v6_sd.log 2>&1; then S=0; echo "trust: PASS"; else echo "trust: FAIL"; grep -v "^ " /tmp/v6_sd.log | grep -iE "error|rests on|witness|pin |never used|cite|imports|FROZEN|registered|RoundsTo|conjunction|no such constant" | head -n 25; fi
  if [ $TOUCHED_MAP = 0 ]; then M=0; echo "map: regenerated by the author"
  elif cmp -s TRUST_MAP.md /tmp/v6_map_defect.md; then M=0; echo "map: PASS"
  else echo "map: FAIL (hand-edited TRUST_MAP.md is stale)"; cp /tmp/v6_map_defect.md TRUST_MAP.md; fi
  echo "--- certified numbers"
  python3 scripts/trust/check_numbers.py && N=0
  echo "--- prose/meaning (v6)"
  P=1; python3 scripts/trust/check_prose.py && P=0
  echo "--- validation packet regenerated by the author (docstring rule)"
  K=1; python3 validation/make_packet.py > /tmp/v6_packet.log 2>&1 && K=0 || tail -n 5 /tmp/v6_packet.log
  git add -A >/dev/null; git -c user.email=j@x -c user.name=judge commit -qm "defect" >/dev/null 2>&1
  echo "--- frozen registry + certified-number diff vs base"
  python3 scripts/trust/check_relock.py $BASE && python3 scripts/trust/check_numbers.py --base $BASE && python3 scripts/trust/check_prose.py --base $BASE && R=0
fi
if [ $B = 0 ] && [ $T = 0 ] && [ $S = 0 ] && [ $M = 0 ] && [ $N = 0 ] && [ $R = 0 ] && [ $P = 0 ] && [ $K = 0 ]; then echo "RESULT V6 ACCEPTED"; else echo "RESULT V6 REJECTED build=$B tokens=$T trust=$S map=$M numbers=$N relock=$R prose=$P packet=$K"; fi
date -u +%T
} > $OUT 2>&1
git reset -q --hard $BASE; git clean -fdq -- Checked Work scripts runs
tail -n 2 $OUT
