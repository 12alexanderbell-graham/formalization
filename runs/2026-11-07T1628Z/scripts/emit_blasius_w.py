#!/usr/bin/env python3
"""Run 2026-11-07T1628Z: emit Work/Blasius/BWData.lean from gen_blasius_w.py's JSON. Same `chain` statement
and the same end values FG, FP, FQ, R as Work/Blasius/BQData.lean (run 1228Z), so Work/Blasius/Blasius.lean
needs only the import changed.
usage: emit_blasius_w.py cells.json SEG out.lean FG FP FQ R"""
import sys, json
from fractions import Fraction as Fr
d = json.load(open(sys.argv[1])); SEG = int(sys.argv[2]); out = sys.argv[3]
FG, FP, FQ, R = (Fr(x) for x in sys.argv[4:8])
fr = lambda v: Fr(v[0], v[1])
def q(x):
    x = Fr(x)
    return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"
def ql(xs): return "[" + ", ".join(q(fr(v)) for v in xs) + "]"
cells = d['cells']; n = len(cells); L = fr(d['L']); r2 = fr(d['r2'])
Ls = q(L)
lines = ["import Work.Blasius.BCellW", "",
 "/-! Generated by `runs/2026-11-07T1628Z/scripts/gen_blasius_w.py` and `emit_blasius_w.py` (SEG = %d):" % SEG,
 "%d weighted one-sided cells for the Blasius initial-value problem g''' + g g''/2 = 0, g(0) = g'(0) = 0," % n,
 "g''(0) = 1 on [0, %s]. Every numeric side condition, link and defect bound is checked by kernel" % (str(L)),
 "evaluation over ℚ (`decide +kernel`), one declaration per segment. `chain`: every solution is",
 "enclosed at the end within `R` of (`FG`, `FP`, `FQ`), the same end values as `Work.Blasius.BQData`. -/", "",
 "namespace Work.Blasius.BWData", "open Set Checked.Sim Work.Blasius.BCellW", ""]
keys = ['t0', 'h', 'δ', 'ε', 'B', 'μ', 'w1', 'w2', 'r1']
for i, c in enumerate(cells):
    lines.append(f"def c{i} : Cell := ⟨" + ", ".join(q(fr(c[k])) for k in keys) + ", " +
                 ", ".join(ql(c[k]) for k in ('pg', 'pp', 'pq')) + "⟩")
lines.append("")
segs = []
s = 0
while s < n:
    e = min(s + SEG, n); segs.append((s, e)); s = e
for j, (s, e) in enumerate(segs):
    lst = "[" + ", ".join(f"c{i}" for i in range(s, e)) + "]"
    if e < n: term = f"(fun e => linkOK e c{e})"
    else: term = f"(endOK {Ls} {q(FG)} {q(FP)} {q(FQ)} {q(R)} {q(r2)})"
    lines += [f"theorem seg{j}_ok : chainTo {Ls} {term} {lst} = true := by", "  decide +kernel", ""]
lines += [f"def FG : ℚ := {q(FG)}", f"def FP : ℚ := {q(FP)}", f"def FQ : ℚ := {q(FQ)}", f"def R : ℚ := {q(R)}", "",
 "/-- Every solution of g' = p, p' = q, q' = −g q/2 on [0, 9] (derivatives within [0, 9]) with",
 "g(0) = p(0) = 0, q(0) = 1 is within `R` of (`FG`, `FP`, `FQ`) at 9. -/",
 "theorem chain {g p q : ℝ → ℝ}",
 "    (hg : ∀ t ∈ Icc (0 : ℝ) (9 : ℝ), HasDerivWithinAt g (p t) (Icc 0 (9 : ℝ)) t)",
 "    (hp : ∀ t ∈ Icc (0 : ℝ) (9 : ℝ), HasDerivWithinAt p (q t) (Icc 0 (9 : ℝ)) t)",
 "    (hq : ∀ t ∈ Icc (0 : ℝ) (9 : ℝ), HasDerivWithinAt q (-(g t * q t / 2)) (Icc 0 (9 : ℝ)) t)",
 "    (h0 : g 0 = 0) (h1 : p 0 = 0) (h2 : q 0 = 1) :",
 "    |g (9 : ℝ) - FG| ≤ R ∧ |p (9 : ℝ) - FP| ≤ R ∧ |q (9 : ℝ) - FQ| ≤ R := by",
 f"  have hX : (({Ls} : ℚ) : ℝ) = (9 : ℝ) := by norm_num",
 f"  have hs : Sol (({Ls} : ℚ) : ℝ) 0 g p q := by rw [hX]; exact ⟨hg, hp, hq⟩",
 "  have b0 : InBox c0 g p q := by",
 "    simp only [InBox, V, c0, List.headD_cons]; push_cast",
 "    simp only [h0, h1, h2]; norm_num", ""]
prev = "b0"
for j, (s, e) in enumerate(segs):
    rest = "[" + ", ".join(f"c{i}" for i in range(s + 1, e)) + "]"
    if e < n:
        lines.append(f"  have b{j+1} := seg_q0 c{e} {rest} c{s} seg{j}_ok hs {prev}"); prev = f"b{j+1}"
    else:
        lines.append(f"  have e := end_q0 {rest} c{s} seg{j}_ok hs {prev}")
lines += ["  rw [hX] at e", "  exact e", "", "end Work.Blasius.BWData", ""]
open(out, 'w').write("\n".join(lines))
print("wrote", out, n, "cells", len(segs), "segments")
