#!/usr/bin/env python3
"""Run 2026-11-11T1228Z: emit Work/FSRev/<Mod>.lean from gen_rev.py's JSON (cells for the CLAMPED adverse-sign
coefficient-K field `Checked.FSSep.SBase.vS K`, cell module `Checked.FSSep.SCellWC`), reversed-flow branch.
Merge of runs/2026-11-11T1028Z/scripts/emit_att_wc.py (K-generic cells, `ChainA K A E`) and
runs/2026-11-09T1228Z/scripts/emit_low.py (K = 10 lower branch: modes slowL, tube).
Modes: over  -> `chain : ChainA K A Over`   (side sideT, end endO)
       slowL -> `chain : ChainA K A SlowR`  (side sideU, Φ = p < 1, end endSR, η = L)
       tube  -> `chainC` (ball |α − A| ≤ R0, side sideP, Φ = PhiT, end endT) and `tube : TubeR K lo hi`.
usage: emit_rev.py cells.json SEG out.lean ModName K_num/K_den A_lean [R0 lo_lean hi_lean (tube)]"""
import sys, json
from fractions import Fraction as Fr
d = json.load(open(sys.argv[1])); SEG = int(sys.argv[2]); out = sys.argv[3]; mod = sys.argv[4]; K = Fr(sys.argv[5])
Alean = sys.argv[6]
fr = lambda v: Fr(v[0], v[1])
def q(x):
    x = Fr(x)
    return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"
def ql(xs): return "[" + ", ".join(q(fr(v)) for v in xs) + "]"
cells = d['cells']; n = len(cells); L = fr(d['L']); mode = d['mode']; A = fr(d['A'])
assert mode in ('over', 'slowL', 'tube')
if mode == 'tube':
    R0 = Fr(sys.argv[7]); lo_l, hi_l = sys.argv[8], sys.argv[9]
Ls = q(L); Lr = f"({L.numerator} / {L.denominator} : ℝ)" if L.denominator != 1 else f"({L.numerator} : ℝ)"
KN, KD = sys.argv[5].split("/")
Kq = q(K); Kr = f"({KN} / {KD} : ℝ)"; Kchain = f"({KN} / {KD})"
side = {'over': 'sideT', 'slowL': 'sideU', 'tube': 'sideP'}[mode]
endb = {'over': f'(endO {Ls})', 'slowL': f'(endSR {Ls})', 'tube': f'(endT {Ls})'}[mode]
Phi = {'over': '(fun _ _ _ _ => True)', 'slowL': '(fun _ p _ t => p t < 1)', 'tube': 'PhiT'}[mode]
spec = {'over': '(fun _ _ _ _ _ _ _ _ _ _ => trivial)', 'slowL': '(fun c hok hsd => sideU_spec c hok hsd)',
        'tube': '(fun c hok hsd => sideP_spec c hok hsd)'}[mode]
what = {'over': "overshoot: p > 1 at L",
        'slowL': "the lower Slow event SlowR: p < 1 on [0, L], and at L: 1/3 < p, 0 < q < 3(1 − p), f > 11/15",
        'tube': "inside the clamps with p > −1/2 on [0, L], and at L: 0 < f < 1, 0 < p < 1, 0 < q < 6/5"}[mode]
startw = f"Y(0) = (0, 0, {A})" if mode != 'tube' else f"Y(0) = (0, 0, α) for every α with |α − ({A})| ≤ {R0}"
lines = ["import Checked.FSSep.SCellWC", "import Work.FSAtt.ABase", "import Work.FSRev.RCell", "",
 f"/-! Generated by `runs/2026-11-11T1228Z/scripts/gen_rev.py` (FS_K = {K}, FS_THETA = 11/15, FS_HFINE = 128:1/16) and `emit_rev.py` (SEG = {SEG}):",
 f"{n} weighted one-sided cells for the clamped adverse-sign coefficient-K field `vS K`, K = {K}",
 f"(Falkner–Skan β = −{1/K}, scaled; equal to g''' + K g g'' − 1 + g'² = 0 on every cell's ball),",
 (f"g(0) = g'(0) = 0, g''(0) = {A} on [0, {L}]." if mode != 'tube' else f"g(0) = g'(0) = 0, |g''(0) − ({A})| ≤ {R0} on [0, {L}]."),
 "Every numeric side condition, link, defect bound and sign condition is checked by kernel evaluation over ℚ",
 f"(`decide +kernel`), one declaration per segment. Every solution of the clamped field shows {what}. -/", "",
 f"namespace Work.FSRev.{mod}",
 "open Set Checked.Sim Checked.FSSep.SCellWC Checked.FSNeg.NBase Checked.FSSep.SBase Work.FSAtt.ABase Work.FSRev.RBase Work.FSRev.RCell", ""]
keys = ['t0', 'h', 'δ', 'ε', 'B', 'μ', 'w1', 'w2', 'r1', 'r2']
for i, c in enumerate(cells):
    lines.append(f"def c{i} : Cell := ⟨" + ", ".join(q(fr(c[k])) for k in keys) + ", " +
                 ", ".join(ql(c[k]) for k in ('pg', 'pp', 'pq')) + "⟩")
lines.append("")
segs = []; s = 0
while s < n:
    e = min(s + SEG, n); segs.append((s, e)); s = e
for j, (s, e) in enumerate(segs):
    lst = "[" + ", ".join(f"c{i}" for i in range(s, e)) + "]"
    term = f"(fun e => linkOK e c{e})" if e < n else endb
    lines += [f"theorem seg{j}_ok : chainS {Kq} {Ls} {side} {term} {lst} = true := by", "  decide +kernel", ""]
lines += ["theorem glue {P : ℝ → Prop} {a b : ℝ} (h1 : ∀ t ∈ Icc 0 a, P t) (h2 : ∀ t ∈ Icc a b, P t) :",
 "    ∀ t ∈ Icc 0 b, P t := by",
 "  intro t ht",
 "  rcases le_total t a with h | h",
 "  · exact h1 t ⟨ht.1, h⟩",
 "  · exact h2 t ⟨h, ht.2⟩", "",
 f"/-- Every solution Y of Y' = vS K t Y (the clamped adverse-sign field with K = {K}) on [0, {L}]",
 f"(derivatives within the interval) with {startw}: {what}. -/"]
if mode == 'tube':
    lines += ["theorem chainC {Y : ℝ → ℝ × ℝ × ℝ}",
     f"    (hY : ∀ t ∈ Icc (0 : ℝ) {Lr}, HasDerivWithinAt Y (vS {Kr} t (Y t)) (Icc 0 {Lr}) t)",
     f"    {{α : ℝ}} (h0 : Y 0 = (0, 0, α)) (hα : |α - {Alean}| ≤ {R0.numerator} / {R0.denominator}) :",
     f"    (∀ t ∈ Icc (0 : ℝ) {Lr}, PhiT (fun t => (Y t).1) (fun t => (Y t).2.1) (fun t => (Y t).2.2) t) ∧",
     f"    (0 < (Y {Lr}).1 ∧ (Y {Lr}).1 < 1 ∧ 0 < (Y {Lr}).2.1 ∧ (Y {Lr}).2.1 < 1 ∧ 0 < (Y {Lr}).2.2 ∧ (Y {Lr}).2.2 < 6 / 5) := by"]
else:
    ev = 'Over' if mode == 'over' else 'SlowR'
    lines += [f"theorem chain : ChainA {Kchain} {Alean} {ev} := by",
     f"  refine ⟨{Lr}, by norm_num, fun Y hY h0 => ?_⟩"]
lines += [f"  have hX : (({Ls} : ℚ) : ℝ) = {Lr} := by norm_num",
 f"  have hK : (({Kq} : ℚ) : ℝ) = {Kr} := by norm_num",
 f"  have hs : SolC (({Kq} : ℚ) : ℝ) (({Ls} : ℚ) : ℝ) 0 (fun t => (Y t).1) (fun t => (Y t).2.1) (fun t => (Y t).2.2) := by",
 "    rw [hX, hK]",
 "    exact ⟨fun t ht => (hY t ht).fst, fun t ht => (hY t ht).snd.fst, fun t ht => (hY t ht).snd.snd⟩",
 "  have z0 : ((c0.t0 : ℚ) : ℝ) = 0 := by simp [c0]",
 "  have b0 : InBox c0 (fun t => (Y t).1) (fun t => (Y t).2.1) (fun t => (Y t).2.2) := by",
 "    unfold InBox; simp only [z0, h0]",
 ("    simp only [V, c0, List.headD_cons]; push_cast; norm_num" if mode != 'tube' else
  "    simp only [V, c0, List.headD_cons]; push_cast\n    have hα' := abs_le.1 hα\n    nlinarith [hα'.1, hα'.2]"),
 ""]
prev = "b0"; acc = None
for j, (s, e) in enumerate(segs):
    rest = "[" + ", ".join(f"c{i}" for i in range(s + 1, e)) + "]"
    if e < n:
        lines.append(f"  obtain ⟨b{j+1}, P{j}⟩ := segS_q0 (Φ := {Phi}) {spec} c{e} {rest} c{s} seg{j}_ok hs {prev}")
        prev = f"b{j+1}"
    else:
        if mode == 'slowL':
            lines.append(f"  obtain ⟨E, P{j}⟩ := endSR_q0 (Φ := {Phi}) {spec} {rest} c{s} seg{j}_ok hs {prev}")
        elif mode == 'tube':
            lines.append(f"  obtain ⟨E, P{j}⟩ := endT_q0 (Φ := {Phi}) {spec} {rest} c{s} seg{j}_ok hs {prev}")
        else:
            lines.append(f"  have E := endO_q0 {rest} c{s} seg{j}_ok hs {prev}")
    if mode in ('slowL', 'tube'):
        if j == 0:
            lines.append(f"  rw [z0] at P0"); acc = "P0"
        else:
            lines.append(f"  have A{j} := glue {acc} P{j}"); acc = f"A{j}"
if mode == 'slowL':
    lines += [f"  rw [hX] at E {acc}", f"  exact ⟨{Lr}, by norm_num, {acc}, E.1, E.2.1, E.2.2.1, E.2.2.2⟩"]
elif mode == 'tube':
    lines += [f"  rw [hX] at E {acc}", f"  exact ⟨{acc}, E⟩", "",
     f"/-- The certified tube on [{lo_l}, {hi_l}] (inside the ball of `chainC`). -/",
     f"theorem tube : TubeR {Kchain} {lo_l} {hi_l} := by",
     "  intro α hα Y hY h0",
     f"  have hα' : |α - {Alean}| ≤ {R0.numerator} / {R0.denominator} := by",
     "    rw [abs_le]; constructor <;> linarith [hα.1, hα.2]",
     "  exact chainC hY h0 hα'"]
else:
    lines += [f"  rw [hX] at E", f"  exact ⟨{Lr}, by norm_num, E⟩"]
lines += ["", f"end Work.FSRev.{mod}", ""]
open(out, 'w').write("\n".join(lines))
print("wrote", out, n, "cells", len(segs), "segments")
