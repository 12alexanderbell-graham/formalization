#!/usr/bin/env python3
"""Run 2026-11-08T0428Z: emit Work/Homann/Hm{U,O}Data.lean from gen_homann_w.py's JSON (from emit_hiemenz_w.py).
mode 'under': chain ⇒ q L < 0 ∧ ∀ t ∈ [0, L], p t < 1; mode 'over': chain ⇒ 1 < p L ∧ ∀ t ∈ [0, L], 0 < q t.
usage: emit_hiemenz_w.py cells.json SEG out.lean ModName A_decimal"""
import sys, json
from fractions import Fraction as Fr
d = json.load(open(sys.argv[1])); SEG = int(sys.argv[2]); out = sys.argv[3]; mod = sys.argv[4]; Adec = sys.argv[5]
fr = lambda v: Fr(v[0], v[1])
def q(x):
    x = Fr(x)
    return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"
def ql(xs): return "[" + ", ".join(q(fr(v)) for v in xs) + "]"
cells = d['cells']; n = len(cells); L = fr(d['L']); mode = d['mode']
assert fr(d['A']) == Fr(Adec)
Ls = q(L); Lr = f"({L.numerator} / {L.denominator} : ℝ)"
side = 'sideU' if mode == 'under' else 'sideO'
endb = f'(endU {Ls})' if mode == 'under' else f'(endO {Ls})'
endlemma = 'endS_q0' if mode == 'under' else 'endSO_q0'
spec = 'sideU_spec' if mode == 'under' else 'sideO_spec'
Phi = '(fun _ p _ t => p t < 1)' if mode == 'under' else '(fun _ _ q t => 0 < q t)'
concl = (f"q {Lr} < 0 ∧ ∀ t ∈ Icc (0 : ℝ) {Lr}, p t < 1" if mode == 'under'
         else f"1 < p {Lr} ∧ ∀ t ∈ Icc (0 : ℝ) {Lr}, 0 < q t")
what = ("undershoot: q < 0 at the end and p < 1 throughout" if mode == 'under'
        else "overshoot: p > 1 at the end and q > 0 throughout")
lines = ["import Work.Homann.HmCellW", "",
 f"/-! Generated by `runs/2026-11-08T0428Z/scripts/gen_homann_w.py` and `emit_homann_w.py` (SEG = {SEG}):",
 f"{n} weighted one-sided cells for the Homann initial-value problem g''' + 2 g g'' + 1 − g'² = 0,",
 f"g(0) = g'(0) = 0, g''(0) = {Adec} on [0, {L}]. Every numeric side condition, link, defect bound and",
 "sign condition is checked by kernel evaluation over ℚ (`decide +kernel`), one declaration per segment.",
 f"`chain`: every solution shows the {what}. -/", "",
 f"namespace Work.Homann.{mod}", "open Set Checked.Sim Work.Homann.HmCellW", ""]
keys = ['t0', 'h', 'δ', 'ε', 'B', 'μ', 'w1', 'w2', 'r1', 'r2']
for i, c in enumerate(cells):
    lines.append(f"def c{i} : Cell := ⟨" + ", ".join(q(fr(c[k])) for k in keys) + ", " +
                 ", ".join(ql(c[k]) for k in ('pg', 'pp', 'pq')) + "⟩")
lines.append("")
segs = []; s = 0
while s < n:
    e = min(s + SEG, n); segs.append((s, e)); s = e
for j, (s, e) in enumerate(segs):
    lst = "[" + ", ".join(f"c{i}" for i in range(s, e)) + "]"
    term = f"(fun e => linkOK e c{e})" if e < n else endb
    lines += [f"theorem seg{j}_ok : chainS {Ls} {side} {term} {lst} = true := by", "  decide +kernel", ""]
lines += ["theorem glue {P : ℝ → Prop} {a b : ℝ} (h1 : ∀ t ∈ Icc 0 a, P t) (h2 : ∀ t ∈ Icc a b, P t) :",
 "    ∀ t ∈ Icc 0 b, P t := by",
 "  intro t ht",
 "  rcases le_total t a with h | h",
 "  · exact h1 t ⟨ht.1, h⟩",
 "  · exact h2 t ⟨h, ht.2⟩", "",
 f"/-- Every solution of g' = p, p' = q, q' = −2 g q − 1 + p² on [0, {L}] (derivatives within the",
 f"interval) with g(0) = p(0) = 0, q(0) = {Adec}: {what}. -/",
 "theorem chain {g p q : ℝ → ℝ}",
 f"    (hg : ∀ t ∈ Icc (0 : ℝ) {Lr}, HasDerivWithinAt g (p t) (Icc 0 {Lr}) t)",
 f"    (hp : ∀ t ∈ Icc (0 : ℝ) {Lr}, HasDerivWithinAt p (q t) (Icc 0 {Lr}) t)",
 f"    (hq : ∀ t ∈ Icc (0 : ℝ) {Lr}, HasDerivWithinAt q (-(2 * g t * q t) - 1 + p t ^ 2) (Icc 0 {Lr}) t)",
 f"    (h0 : g 0 = 0) (h1 : p 0 = 0) (h2 : q 0 = {Adec}) :",
 f"    {concl} := by",
 f"  have hX : (({Ls} : ℚ) : ℝ) = {Lr} := by norm_num",
 f"  have hs : Sol (({Ls} : ℚ) : ℝ) 0 g p q := by rw [hX]; exact ⟨hg, hp, hq⟩",
 "  have b0 : InBox c0 g p q := by",
 "    simp only [InBox, V, c0, List.headD_cons]; push_cast",
 "    simp only [h0, h1, h2]; norm_num",
 "  have z0 : ((c0.t0 : ℚ) : ℝ) = 0 := by simp [c0]",
 ""]
prev = "b0"; acc = None
for j, (s, e) in enumerate(segs):
    rest = "[" + ", ".join(f"c{i}" for i in range(s + 1, e)) + "]"
    if e < n:
        lines.append(f"  obtain ⟨b{j+1}, P{j}⟩ := segS_q0 (Φ := {Phi}) (fun c hok hsd => {spec} c hok hsd) c{e} {rest} c{s} seg{j}_ok hs {prev}")
        prev = f"b{j+1}"
    else:
        lines.append(f"  obtain ⟨E, P{j}⟩ := {endlemma} (Φ := {Phi}) (fun c hok hsd => {spec} c hok hsd) {rest} c{s} seg{j}_ok hs {prev}")
    if j == 0:
        lines.append(f"  rw [z0] at P0"); acc = "P0"
    else:
        lines.append(f"  have A{j} := glue {acc} P{j}"); acc = f"A{j}"
lines += [f"  rw [hX] at E {acc}", f"  exact ⟨E, {acc}⟩", "", f"end Work.Homann.{mod}", ""]
open(out, 'w').write("\n".join(lines))
print("wrote", out, n, "cells", len(segs), "segments")
