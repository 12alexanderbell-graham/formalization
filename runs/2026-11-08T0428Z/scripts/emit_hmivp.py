#!/usr/bin/env python3
"""Emit Checked/Homann/HmIVP.lean (run 2026-11-08T0428Z; port of runs/2026-11-08T0428Z/scripts/emit_hmivp.py): the clamps of the clamped Homann flow are inactive on
[0, 6] at both certified shooting values, so the flow is a solution of the Homann initial-value problem there
(used by the non-vacuity witnesses of homann_under / homann_over). The chain proofs are the text of
`chainC` in HUDataC/HODataC with the carried property replaced by the box of every cell (CellProp's six box
conditions); the segment certificates (seg*_ok) are reused, nothing new is decided."""
import re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[3]

def chain_text(mod, phi_old, spec_old, end_name):
    s = (ROOT / "Checked" / "Homann" / f"{mod}.lean").read_text()
    m = re.search(r"theorem chainC .*?\n(  have hX.*?)\n  rw \[hX\] at E A11\n", s, re.S)
    body = m.group(1)
    body = body.replace(f"(Φ := {phi_old})", "(Φ := BoxΦ)")
    body = body.replace(f"(fun c hok hsd => {spec_old} c hok hsd)", "(fun c hok _ => box_spec c hok)")
    assert phi_old not in body and spec_old not in body
    assert body.count("BoxΦ") == 12 and end_name in body
    return body

lo = chain_text("HmUDataC", "(fun _ p _ t => p t < 1)", "sideU_spec", "endS_q0")
hi = chain_text("HmODataC", "(fun _ _ q t => 0 < q t)", "sideO_spec", "endSO_q0")

