"""Emit the Lean certificate files for the Thomas-Fermi shooting from gen_tf.py (run 2026-11-06T1828Z).
Usage: python3 emit_tf.py HDEN DEG MUEXP [--test K]"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_tf as G
from fractions import Fraction as F

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
HDEN, DEG, MUE = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
TEST = int(sys.argv[sys.argv.index('--test')+1]) if '--test' in sys.argv else None
PER = 14
G.DIG = int(os.environ.get("TFDIG", "20"))
h = F(1, HDEN)
LO = F(-158807103, 100000000); HI = F(-158807102, 100000000)
OMEGA = F(208, 10000); PI = F(771, 10000000)

def q(x: F):
    return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"
def r(x: F):
    return f"({x.numerator}/{x.denominator} : ℝ)" if x.denominator != 1 else f"({x.numerator} : ℝ)"
def lst(p): return "[" + ", ".join(q(F(x)) for x in p) + "]"

def stop_sup(t, c): return c['ew'] < OMEGA and c['ep'] < -PI
def stop_sub(t, c): return c['ep'] > 0

HYP = """{{W P : ℝ → ℝ}} (hcW : ContinuousOn W (Icc 0 {T})) (hcP : ContinuousOn P (Icc 0 {T}))
    (hW : ∀ t ∈ Ioc (0:ℝ) {T}, HasDerivAt W (t * P t / W t) t)
    (hP : ∀ t ∈ Ioc (0:ℝ) {T}, HasDerivAt P (2 * W t ^ 3) t)
    (hpos : ∀ t ∈ Ioc (0:ℝ) {T}, 0 < W t)"""
ARGS = "hcW hcP hW hP hpos"

def cell_thm(tag, k, c, T, sign):
    t0 = c['t0']; t1 = t0 + h
    nm = f"{tag}{k}"
    lem = "super_cell" if sign > 0 else "sub_cell"
    out = []
    out.append(f"def qw_{nm} : List ℚ := {lst(c['qw'])}")
    out.append(f"def qp_{nm} : List ℚ := {lst(c['qp'])}")
    out.append(f"def d1_{nm} : List ℚ := {lst(c['d1'])}")
    out.append(f"def d2_{nm} : List ℚ := {lst(c['d2'])}")
    if sign > 0:
        s_in = f"(hs1 : W {r(t0)} < {r(c['qw'][0])}) (hs2 : P {r(t0)} < {r(c['qp'][0])})"
        concl = f"W {r(t1)} < {r(c['nw'])} ∧ P {r(t1)} < {r(c['np'])}"
        cert = lambda d: f"exact lt_of_lt_of_le (by norm_num [{d}, evalQ]) (lower_of {d} hσ.1 hσ.2)"
        bnd = "le"
    else:
        s_in = f"(hs1 : {r(c['qw'][0])} < W {r(t0)}) (hs2 : {r(c['qp'][0])} < P {r(t0)})"
        concl = f"{r(c['nw'])} < W {r(t1)} ∧ {r(c['np'])} < P {r(t1)}"
        cert = lambda d: f"exact lt_of_le_of_lt (upper_of {d} hσ.1 hσ.2) (by norm_num [{d}, evalQ])"
    out.append(f"""theorem {nm} {HYP.format(T=r(T))}
    {s_in} :
    {concl} := by
  have sub : Icc {r(t0)} ({r(t0)} + {r(h)}) ⊆ Icc 0 {r(T)} := Icc_subset_Icc (by norm_num) (by norm_num)
  have sub' : ∀ t ∈ Ioc {r(t0)} ({r(t0)} + {r(h)}), t ∈ Ioc (0:ℝ) {r(T)} := fun t ht =>
    ⟨lt_of_le_of_lt (by norm_num) ht.1, le_trans ht.2 (by norm_num)⟩
  have hc := {lem} qw_{nm} qp_{nm} (w := W) (P := P) (t0 := {r(t0)}) (h := {r(h)}) (by norm_num) (by norm_num)
    (hcW.mono sub) (hcP.mono sub) (fun t ht => hW t (sub' t ht)) (fun t ht => hP t (sub' t ht))
    (fun t ht => hpos t (sub' t ht))
    (fun σ hσ => by
      rw [show evalQ qw_{nm} σ * dEvalQ qw_{nm} σ - ({r(t0)} + σ) * evalQ qp_{nm} σ = evalQ d1_{nm} σ by
        simp only [qw_{nm}, qp_{nm}, d1_{nm}, evalQ, dEvalQ]; push_cast; ring]
      {cert('d1_'+nm)})
    (fun σ hσ => by
      rw [show dEvalQ qp_{nm} σ - 2 * evalQ qw_{nm} σ ^ 3 = evalQ d2_{nm} σ by
        simp only [qw_{nm}, qp_{nm}, d2_{nm}, evalQ, dEvalQ]; push_cast; ring]
      {cert('d2_'+nm)})
    (by rw [qw_{nm}, evalQ_zero]; push_cast; linarith [hs1]) (by rw [qp_{nm}, evalQ_zero]; push_cast; linarith [hs2])
  have he := hc {r(t1)} ⟨by norm_num, by norm_num⟩
  have b1 : {"evalQ qw_"+nm+" ("+r(t1)+" - "+r(t0)+") ≤ "+r(c['nw']) if sign>0 else r(c['nw'])+" ≤ evalQ qw_"+nm+" ("+r(t1)+" - "+r(t0)+")"} := by
    norm_num [qw_{nm}, evalQ]
  have b2 : {"evalQ qp_"+nm+" ("+r(t1)+" - "+r(t0)+") ≤ "+r(c['np']) if sign>0 else r(c['np'])+" ≤ evalQ qp_"+nm+" ("+r(t1)+" - "+r(t0)+")"} := by
    norm_num [qp_{nm}, evalQ]
  exact ⟨{"lt_of_lt_of_le he.1 b1, lt_of_lt_of_le he.2 b2" if sign>0 else "lt_of_le_of_lt b1 he.1, lt_of_le_of_lt b2 he.2"}⟩
""")
    return "\n".join(out)

HEADER = """import Mathlib
import Work.Sim.ODETools
import Work.Math.LECell
import Work.Math.TFCell
{imports}
/-! Generated by `runs/2026-11-06T1828Z/scripts/emit_tf.py` from `gen_tf.py` (Thomas–Fermi shooting
certificates, exact rationals; do not edit by hand). {what} -/

set_option maxHeartbeats 8000000
set_option maxRecDepth 100000

namespace Work.Math.TFCerts
open Set Work.Sim Work.Math.LECell Work.Math.TFCell
"""

def main():
    sup, ok1 = G.chain(1, LO, h, DEG, F(1, 10**MUE), 1.0, F(12), stop_sup)
    sub, ok2 = G.chain(-1, HI, h, DEG, F(1, 10**MUE), 1.0, F(12), stop_sub)
    assert ok1 and ok2, (ok1, ok2)
    T1 = sup[-1]['t0'] + h; T2 = sub[-1]['t0'] + h
    assert sup[-1]['nw'] <= OMEGA and sup[-1]['np'] <= -PI, (float(sup[-1]['nw']), float(sup[-1]['np']))
    assert 4*OMEGA**5 < T1*PI**2
    assert sub[-1]['np'] > 0
    print('sup cells', len(sup), 'T1', T1, 'sub cells', len(sub), 'T2', T2,
          'end sup', float(sup[-1]['nw']), float(sup[-1]['np']), 'end sub', float(sub[-1]['nw']), float(sub[-1]['np']))
    if TEST:
        sup, sub = sup[:TEST], sub[:TEST]
    files = []
    for tag, cells, T, sign, nmf in [('sup', sup, T1, 1, 'TFCertsSup'), ('sub', sub, T2, -1, 'TFCertsSub')]:
        for j in range(0, len(cells), PER):
            fn = f"{nmf}{j//PER + 1}"
            body = HEADER.format(imports="", what=f"{tag} cells {j}..{min(j+PER, len(cells))-1}, h = {h}, degree {DEG}.")
            body += "\n" + "\n\n".join(cell_thm(tag, k, cells[k], T, sign) for k in range(j, min(j+PER, len(cells))))
            body += "\nend Work.Math.TFCerts\n"
            path = os.path.join(ROOT, 'Work', 'Math', fn + '.lean') if not TEST else os.path.join(ROOT, 'runs', '2026-11-06T1828Z', 'lean', fn + '.lean')
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'w').write(body)
            files.append(fn)
    if TEST:
        return
    # chain file
    imports = "".join(f"import Work.Math.{f}\n" for f in files)
    body = HEADER.format(imports=imports, what=(
        f"Chains: super barrier from slope −1.58807103 to T1 = {T1} ({len(sup)} cells), sub barrier from "
        f"slope −1.58807102 to T2 = {T2} ({len(sub)} cells); h = {h}, Taylor degree {DEG}, margin 10^-{MUE}."))
    def chain_proof(tag, cells, sign):
        lines = []
        prev = None
        for k in range(len(cells)):
            if k == 0:
                if sign > 0:
                    a1 = "(by rw [h0]; norm_num)"; a2 = "(by linarith [hp0])"
                else:
                    a1 = "(by rw [h0]; norm_num)"; a2 = "(by linarith [hp0])"
                lines.append(f"  have c0 := {tag}0 {ARGS} {a1} {a2}")
            else:
                lines.append(f"  have c{k} := {tag}{k} {ARGS} c{k-1}.1 c{k-1}.2")
        return "\n".join(lines), f"c{len(cells)-1}"
    sp, last = chain_proof('sup', sup, 1)
    body += f"""
theorem sup_chain {HYP.format(T=r(T1))}
    (h0 : W 0 = 1) (hp0 : P 0 < -158807103/100000000) : W {r(T1)} < {r(OMEGA)} ∧ P {r(T1)} < -{r(PI)} := by
{sp}
  exact ⟨lt_of_lt_of_le {last}.1 (by norm_num), lt_of_lt_of_le {last}.2 (by norm_num)⟩

theorem sup_event : 4 * {r(OMEGA)} ^ 5 < {r(T1)} * {r(PI)} ^ 2 := by norm_num

"""
    sbp, lastb = chain_proof('sub', sub, -1)
    body += f"""theorem sub_chain {HYP.format(T=r(T2))}
    (h0 : W 0 = 1) (hp0 : -158807102/100000000 < P 0) : 0 < P {r(T2)} := by
{sbp}
  exact lt_of_le_of_lt (by norm_num) {lastb}.2

end Work.Math.TFCerts
"""
    open(os.path.join(ROOT, 'Work', 'Math', 'TFChain.lean'), 'w').write(body)
    print('files', files)

main()
