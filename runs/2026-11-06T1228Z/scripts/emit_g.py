for c in cells:
    i = c['i']
    t1 = c['t0'] + c['h']
    if TEST and i not in (0, 1, 79, 80, 81, iL):
        o.append(f"  obtain ⟨n{i + 1}, a{i + 1}, b{i + 1}⟩ : "
                 f"{pos_concl(t1) if c['kind'] == 'pos' else dec_concl(t1)} ∧ "
                 f"|Real.exp (w {r(t1)}) - {r(c['ne'])}| ≤ {r(c['nd'])} ∧ |φ {r(t1)} - {r(c['nf'])}| ≤ {r(c['nd'])} := sorry\n")
