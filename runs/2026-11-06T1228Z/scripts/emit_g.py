    if c['kind'] == 'dec' and c['t0'] == CD:
        o.append(f"  obtain ⟨n{i + 1}, a{i + 1}, b{i + 1}⟩ := step{i} hw hφ a{i} b{i}\n")
        ipos = i
    else:
        o.append(f"  obtain ⟨n{i + 1}, a{i + 1}, b{i + 1}⟩ := step{i} hw hφ n{i} a{i} b{i}\n")
