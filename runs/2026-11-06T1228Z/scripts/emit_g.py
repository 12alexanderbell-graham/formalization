def pos_concl(t1):
    return f"(∀ t ∈ Ioc (0 : ℝ) {r(t1)}, 0 < 2 + t * φ t)"


def dec_concl(t1):
    return f"(∀ t ∈ Icc {r(CD)} {r(t1)}, 0 < φ t + t * Real.exp (w t))"


def step(c):
    i = c['i']
    t0, h = c['t0'], c['h']
    t1 = t0 + h
    pe, pp, d1, d2 = c['pe'], c['pp'], c['d1'], c['d2']
    eps, delta, Bc, K, EH, PH = c['eps'], c['delta'], c['B'], c['K'], c['EH'], c['PH']
    Eg = 1 / (1 - K * h)
    assert delta * Eg + eps / K * (Eg - 1) <= Bc and Bc < F(1, 100)
    assert G.lowb(pe, h) >= -(EH - F(1, 100)) and G.upb(pe, h) <= EH - F(1, 100)
    assert G.lowb(pp, h) >= -(PH - F(1, 100)) and G.upb(pp, h) <= PH - F(1, 100)
    assert G.absb(d1, h) <= eps and G.absb(d2, h) <= eps * t0
    assert 1 <= K and PH + EH <= K and 2 / t0 + 1 <= K and K * h < 1
    ee, fe = G.ev(pe, h), G.ev(pp, h)
    ne, nf, nd = c['ne'], c['nf'], c['nd']
    assert Bc + abs(ee - ne) <= nd and Bc + abs(fe - nf) <= nd
    kind = c['kind']
    first_dec = kind == 'dec' and t0 == CD
    if kind == 'pos':
        U = G.pos_poly(c)
        lo = G.lowb(U, h)
        assert lo - t1 * Bc > 0
        hyp = f"(hprev : {pos_concl(t0)})"
        concl = pos_concl(t1)
    else:
        U = G.dec_poly(c)
        lo = G.lowb(U, h)
        assert lo - (1 + t1) * Bc > 0
        hyp = '' if first_dec else f"(hprev : {dec_concl(t0)})"
        concl = dec_concl(t1)
    s = [lst(f'pe{i}', pe) + lst(f'pp{i}', pp) + lst(f'da{i}', d1) + lst(f'db{i}', d2) + lst(f'U{i}', U)]
