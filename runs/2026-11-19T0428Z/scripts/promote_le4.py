#!/usr/bin/env python3
"""Promote the index-4 Lane–Emden headline, its certificates and its existence proof from Work/Math to
Checked/Math (run 2026-11-19T0428Z; pattern of runs/2026-11-08T0228Z/scripts/promote_le2.py).

Mechanical copy: namespaces Work.Math -> Checked.Math, `import Mathlib` -> specific modules, module docs
replaced by number-free text (check_prose rule 7). Statements and proofs otherwise byte-identical."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parents[3]
W, C = ROOT / "Work/Math", ROOT / "Checked/Math"
MODS = ["LE4Start", "LE4QData", "LE4Last", "LE4Chain", "LaneEmden4",
        "LE4ExistsLeft", "LE4ExistsStart", "LE4ExistsCell", "LE4ExistsData", "LE4Exists"]
G = "`runs/2026-11-19T0428Z/scripts/emit_len4.py`"
DOCS = {
 "LE4Start": f"Generated by {G} (exact rational certificates; do not edit by hand): the singular start of the Lane–Emden chain of index four from the truncated series at the centre. Promoted verbatim from `Work/Math/LE4Start.lean`.",
 "LE4QData": f"Generated by {G}: the validated cells of the Lane–Emden chain of index four as data; every side condition and defect bound decided by kernel evaluation over the rationals, one declaration per segment of cells. Promoted verbatim from `Work/Math/LE4QData.lean`.",
 "LE4Last": f"Generated by {G}: the last cell of the Lane–Emden chain of index four (enclosure on the whole cell) and the facts read off it. Promoted verbatim from `Work/Math/LE4Last.lean`.",
 "LE4Chain": f"Generated by {G}: chaining of the singular start, the kernel-checked segments and the last cell of the Lane–Emden chain of index four. Promoted verbatim from `Work/Math/LE4Chain.lean`.",
 "LE4ExistsLeft": "Lane–Emden equation of index four, existence near the centre: Banach fixed point of the scaled Volterra map with the clamped fourth-power nonlinearity (adapted from `Checked.Math.LE2ExistsLeft`). Promoted verbatim from `Work/Math/LE4ExistsLeft.lean`.",
 "LE4ExistsStart": "Generated: the singular start of the Lane–Emden chain of index four on the short initial interval used by the existence proof. Promoted verbatim from `Work/Math/LE4ExistsStart.lean`.",
 "LE4ExistsCell": "Lane–Emden equation of index four, existence away from the centre: the validated cells run on the flow of the clamped field, with box conditions decided per cell, so that the flow stays inside the clamps. Promoted verbatim from `Work/Math/LE4ExistsCell.lean`.",
 "LE4ExistsData": "Generated by `runs/2026-11-19T0428Z/scripts/gen_exists4.py`: the cells of the clamped-flow chain of the Lane–Emden existence proof of index four as data, decided by kernel evaluation. Promoted verbatim from `Work/Math/LE4ExistsData.lean`.",
 "LE4Exists": "Lane–Emden equation of index four: existence of a solution meeting every hypothesis of `Checked.Math.LaneEmden4.laneEmden4_constants` (left piece by a fixed point, right piece by Picard–Lindelöf for the clamped field with the clamps shown inactive by the certified cells, glued). Promoted verbatim from `Work/Math/LE4Exists.lean`.",
}
for m in MODS:
    s = (W / f"{m}.lean").read_text()
    s = s.replace("Work.Math.", "Checked.Math.")
    assert "Work." not in s, m
    if m == "LaneEmden4":
        s = s.replace("import Mathlib\n", "import Mathlib.Analysis.Calculus.Deriv.MeanValue\nimport Mathlib.Topology.Order.IntermediateValue\n", 1)
        s = s.replace("frozen before proof, run 2026-11-19T0428Z", "frozen before proof in `Work/Math/LaneEmden4.lean`, statement promoted\nbyte-identical")
        s = s.replace("Existence of such a θ is a separate theorem (to do).",
                      "Existence of such a θ:\n`Checked.Math.LE4Exists.exists_solution` (non-vacuity witness in `Checked/Trust/Witnesses.lean`).")
        assert "to do" not in s
    else:
        assert "import Mathlib\n" not in s, m
        i = s.index("/-!")
        j = s.index("-/", i) + 2
        s = s[:i] + "/-! " + DOCS[m] + " -/" + s[j:]
    (C / f"{m}.lean").write_text(s)
    print("wrote", m)
