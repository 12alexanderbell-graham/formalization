"""Run 2026-11-19T0028Z: emit Checked/Trust/NecessityAVCertsC.lean from gen_junk.py's JSON.
usage: python3 -I emit_junk.py junk.json OUTDIR"""
import json, sys
from fractions import Fraction as F
D = json.load(open(sys.argv[1])); outdir = sys.argv[2]
def q(x):
    x = F(x)
    return f"({x.numerator} : ℝ)" if x.denominator == 1 else f"({x.numerator} / {x.denominator} : ℝ)"
def qq(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator} / {x.denominator}"
CQ = qq(D['c'])
HYP = "(H0 m l : ℝ) (h0 : {m0} ≤ m) (h1 : m ≤ {m1}) (h2 : {l0} ≤ l) (h3 : l ≤ {l1})"
BX = "(by push_cast; linarith) (by push_cast; linarith) (by push_cast; linarith) (by push_cast; linarith)"
def collect(t, name, leaves):
    t['name'] = name
    if 'split' in t:
        collect(t['lo'], name + 'a', leaves); collect(t['hi'], name + 'b', leaves)
    else:
        leaves.append(t)
def head(t):
    m0, m1, l0, l1 = [q(x) for x in t['box']]
    return f"theorem {t['name']} " + HYP.format(m0=m0, m1=m1, l0=l0, l1=l1) + f" :\n    ((({CQ}) : ℚ) : ℝ) ≤ chiSqOL H0 m l := by\n"
def leaf_lean(t):
    h = head(t)
    m0q, m1q, l0q, l1q = [qq(x) for x in t['box']]
    if 'hy' in t:
        return h + (f"  have h := chiSqOL_ge H0 m l (by linarith) (by linarith)\n"
                    f"    (hy_boxQ ({m0q}) ({m1q}) ({l0q}) ({l1q}) (by decide +kernel) m l\n      {BX})\n"
                    f"  norm_num at h ⊢\n  linarith\n")
    if 'neg' in t:
        return h + (f"  exact neg_row H0 m l {t['neg']} (by norm_num [e2OL, m16Table]; linarith)\n"
                    f"    (by norm_num [m16Table])\n")
    if 'far' in t:
        return h + (f"  exact far_hi H0 m l {t['far']} ({qq(t['q'])}) (by norm_num)\n"
                    f"    (by norm_num [e2OL, m16Table]; linarith) (by norm_num [m16Table])\n")
    sv = "![" + ", ".join(qq(x) for x in t['s']) + "]"
    return (h + f"  exact box_boundQJ {sv}\n    ({CQ}) ({m0q}) ({m1q}) ({l0q}) ({l1q}) (by decide +kernel) H0 m l\n    {BX}\n")
def node_lean(t):
    if 'split' not in t: return ""
    mid = q(t['at']); a, b = t['lo']['name'], t['hi']['name']
    if t['split'] == 'm':
        body = f"  rcases le_total m {mid} with h | h\n  · exact {a} H0 m l h0 h h2 h3\n  · exact {b} H0 m l h h1 h2 h3\n"
    else:
        body = f"  rcases le_total l {mid} with h | h\n  · exact {a} H0 m l h0 h1 h2 h\n  · exact {b} H0 m l h0 h1 h h3\n"
    return node_lean(t['lo']) + node_lean(t['hi']) + head(t) + body + "\n"
t = D['C']['tree']; leaves = []
collect(t, 'avc', leaves)
body = "\n".join(leaf_lean(x) for x in leaves) + "\n" + node_lean(t)
open(f"{outdir}/NecessityAVCertsC.lean", 'w').write(
    "import Checked.Trust.NecessityAVJunk\n\n/-! Leaf boxes and bisection tree covering a bounded part of the region where the matter density is\n"
    "at most one and the dark-energy density is nonnegative, with no sign condition on the squared expansion\n"
    "factors, for the chi-square of `Checked.Data.Moresco16` (helper lemmas of `Checked.Trust.NecessityAV`;\n"
    "generated by `runs/2026-11-19T0028Z/scripts/gen_junk.py` and `emit_junk.py`). -/\n\n"
    "namespace Checked.Trust.NecessityAV\nopen Checked.Data.Moresco16 Checked.Data.Moresco16Min\n\n"
    "set_option maxHeartbeats 8000000\n\n" + body + "end Checked.Trust.NecessityAV\n")
print(len(leaves), 'leaves; root', t['name'], t['box'])
