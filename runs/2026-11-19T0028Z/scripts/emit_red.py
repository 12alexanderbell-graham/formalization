"""Run 2026-11-19T0028Z: emit Checked/Trust/NecessityAVCertsA.lean, ...CertsB.lean from gen_red.py's JSON.
usage: python3 -I emit_red.py red.json OUTDIR"""
import json, sys
from fractions import Fraction as F
D = json.load(open(sys.argv[1])); outdir = sys.argv[2]
C = D['c']
def q(x):
    x = F(x)
    return f"({x.numerator} : ℝ)" if x.denominator == 1 else f"({x.numerator} / {x.denominator} : ℝ)"
def qq(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator} / {x.denominator}"
CQ = qq(C)
HYP = "(H0 m l : ℝ) (h0 : {m0} ≤ m) (h1 : m ≤ {m1}) (h2 : {l0} ≤ l) (h3 : l ≤ {l1})\n    (hy : ∀ i, 0 ≤ e2OL m l (m16Table i).1)"
def collect(t, name, leaves):
    t['name'] = name
    if 'split' in t:
        collect(t['lo'], name + 'a', leaves); collect(t['hi'], name + 'b', leaves)
    else:
        leaves.append(t)
def head(t):
    m0, m1, l0, l1 = [q(x) for x in t['box']]
    return f"theorem {t['name']} " + HYP.format(m0=m0, m1=m1, l0=l0, l1=l1) + f" :\n    ((({CQ}) : ℚ) : ℝ) ≤ chiSqOL H0 m l := by\n"
def leaf_lean(t):
    h = head(t)
    if 'vac' in t:
        return h + f"  have h := hy {t['vac']}\n  norm_num [e2OL, m16Table] at h\n  linarith\n"
    if 'far' in t:
        return h + (f"  exact far_hi H0 m l {t['far']} ({qq(t['q'])}) (by norm_num)\n"
                    f"    (by norm_num [e2OL, m16Table]; linarith) (by norm_num [m16Table])\n")
    sv = "![" + ", ".join(qq(x) for x in t['s']) + "]"
    m0q, m1q, l0q, l1q = [qq(x) for x in t['box']]
    return (h + f"  exact box_boundQ {sv}\n    ({CQ}) ({m0q}) ({m1q}) ({l0q}) ({l1q}) (by decide +kernel) H0 m l\n"
            + "    (by push_cast; linarith) (by push_cast; linarith) (by push_cast; linarith) (by push_cast; linarith) hy\n")
def node_lean(t):
    if 'split' not in t: return ""
    mid = q(t['at']); a, b = t['lo']['name'], t['hi']['name']
    if t['split'] == 'm':
        body = f"  rcases le_total m {mid} with h | h\n  · exact {a} H0 m l h0 h h2 h3 hy\n  · exact {b} H0 m l h h1 h2 h3 hy\n"
    else:
        body = f"  rcases le_total l {mid} with h | h\n  · exact {a} H0 m l h0 h1 h2 h hy\n  · exact {b} H0 m l h0 h1 h h3 hy\n"
    return node_lean(t['lo']) + node_lean(t['hi']) + head(t) + body + "\n"
DOC = {'A': ("the region where the matter density is at least one and the dark-energy density is nonnegative",),
       'B': ("the region where the matter density is at most one and the dark-energy density is nonpositive",)}
for k, prev in (('A', 'Checked.Trust.NecessityAVFar'), ('B', 'Checked.Trust.NecessityAVFar')):
    t = D[k]['tree']; leaves = []
    collect(t, 'av' + k.lower(), leaves)
    body = "\n".join(leaf_lean(x) for x in leaves) + "\n" + node_lean(t)
    open(f"{outdir}/NecessityAVCerts{k}.lean", 'w').write(
        f"import {prev}\n\n/-! Leaf boxes and bisection tree covering a bounded part of {DOC[k][0]} for the\n"
        f"chi-square of `Checked.Data.Moresco16` (helper lemmas of `Checked.Trust.NecessityAV`; generated by\n"
        f"`runs/2026-11-19T0028Z/scripts/gen_red.py` and `emit_red.py`). -/\n\n"
        f"namespace Checked.Trust.NecessityAV\nopen Checked.Data.Moresco16 Checked.Data.Moresco16Min\n\n"
        f"set_option maxHeartbeats 8000000\n\n" + body + "end Checked.Trust.NecessityAV\n")
    print(k, len(leaves), 'leaves; root', t['name'], t['box'], 'outer', D[k]['out_m'], D[k]['out_l'])
