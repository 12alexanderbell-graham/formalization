# Certificate generator for Work/Cosmography/B1L19Certs.lean (run 2026-11-04T1228Z).
# Proposes, per Ω-subinterval [a,b] of [0,1], a tangent lower bound L5(Ω) = A − BΩ of
# ∫_{w5}^1 gL Ω (valid for every Ω ∈ [0,1]) and a chord upper bound U3(Ω) = C + DΩ of ∫_{w3}^1 gL Ω
# (valid on [a,b]); both linear in Ω, so L5 ≥ ρ U3 on [a,b] follows from the two endpoints (linarith).
# Exact rationals; Lean re-checks everything. Reuses run 0228Z's gen_fit.py (cell formulas, emitters).
import sys, os
from fractions import Fraction as F
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '../../2026-11-04T0228Z/scripts'))
import gen_fit as G

RHO = F(142, 100)   # J5 ≥ 1.42 J3, i.e. d_L(4√2−1)/d_L(2√2−1) = 2 J5/J3 ≥ 2.84
N = 20

def piece(a, b):
    lc = G.lower_cert(5, (a + b) / 2, N)
    uc = G.upper_cert(3, a, b, N)
    A_, B_ = G.lower_trunc(lc); C_, D_ = G.upper_round(uc)
    ok = all(A_ - B_ * O - RHO * (C_ + D_ * O) >= 0 for O in (a, b))
    return ok, lc, uc

def split(a, b, depth=0):
    ok, lc, uc = piece(a, b)
    if ok: return [(a, b, lc, uc)]
    if depth > 8: raise SystemExit(f"fails on [{a},{b}]")
    m = (a + b) / 2
    return split(a, m, depth + 1) + split(m, b, depth + 1)

def main(out):
    pieces = []
    for k in range(8):
        pieces += split(F(k, 8), F(k + 1, 8))
    s = ["import Checked.Cosmography.B1Fit", "",
         "/-! Generated by `runs/2026-11-04T1228Z/scripts/gen_l19.py` (do not edit): certified bound",
         "`∫_{594603/10⁶}^1 gL Ω · 142/100 ≤ ∫_{420449/10⁶}^1 gL Ω` for every `Ω ∈ [0, 1]`, by",
         f"{len(pieces)} Ω-pieces (tangent cells below, chord cells above, {N} cells each). -/", "",
         "namespace Work.Cosmography.B1L19Certs", "",
         "open Checked.Cosmography.B1 Checked.Cosmography.B1Fit", ""]
    cases = []
    for i, (a, b, lc, uc) in enumerate(pieces):
        s.append(G.emit_lower(f"L5_{i}", lc))
        s.append(G.emit_upper(f"U3_{i}", uc))
        s.append(f"""lemma piece_{i} (Ω : ℝ) (ha : {G.fstr(a)} ≤ Ω) (hb : Ω ≤ {G.fstr(b)}) :
    142 / 100 * ∫ v in (594603 / 1000000 : ℝ)..1, gL Ω v ≤ ∫ v in (420449 / 1000000 : ℝ)..1, gL Ω v := by
  have h1 := L5_{i} Ω (by linarith) (by linarith)
  have h2 := U3_{i} Ω ha hb
  linarith
""")
        cases.append((a, b, i))
    # case split
    body = ["theorem ratio_bound (Ω : ℝ) (h0 : 0 ≤ Ω) (h1 : Ω ≤ 1) :",
            "    142 / 100 * ∫ v in (594603 / 1000000 : ℝ)..1, gL Ω v ≤ ∫ v in (420449 / 1000000 : ℝ)..1, gL Ω v := by"]
    for (a, b, i) in cases[:-1]:
        body.append(f"  rcases le_or_gt Ω {G.fstr(b)} with h | h")
        body.append(f"  · exact piece_{i} Ω (by linarith) h")
    body.append(f"  exact piece_{cases[-1][2]} Ω (by linarith) h1")
    s.append("\n".join(body))
    s += ["", "end Work.Cosmography.B1L19Certs", ""]
    open(out, 'w').write("\n".join(s))
    print(len(pieces), "pieces:", [(str(a), str(b)) for a, b, _, _ in pieces])

if __name__ == '__main__':
    main(sys.argv[1])
