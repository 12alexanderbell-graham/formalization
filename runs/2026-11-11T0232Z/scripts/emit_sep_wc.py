#!/usr/bin/env python3
"""Run 2026-11-11T0232Z (port of runs/2026-11-09T0828Z/scripts/emit_neg_wc.py): emit Work/FSSep/<Mod>.lean from
gen_sep_wc.py's JSON (cells for the CLAMPED adverse-sign coefficient-K field `Work.FSSep.SBase.vS K`, cell module
`Work.FSSep.SCellWC`, start (0, 0, 0)). `chain`: `ChainK K Over` (mode 'over') or `ChainK K SlowS` (mode 'slowp'),
with η = L.
usage: emit_sep_wc.py cells.json SEG out.lean ModName K_num/K_den"""
import sys, json
from fractions import Fraction as Fr
d = json.load(open(sys.argv[1])); SEG = int(sys.argv[2]); out = sys.argv[3]; mod = sys.argv[4]; K = Fr(sys.argv[5])
fr = lambda v: Fr(v[0], v[1])
def q(x):
    x = Fr(x)
    return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"
def ql(xs): return "[" + ", ".join(q(fr(v)) for v in xs) + "]"
cells = d['cells']; n = len(cells); L = fr(d['L']); mode = d['mode']; A = fr(d['A'])
assert A == 0
if mode == 'slow': mode = 'slowp'
assert mode in ('slowp', 'over')
Ls = q(L); Lr = f"({L.numerator} / {L.denominator} : ℝ)" if L.denominator != 1 else f"({L.numerator} : ℝ)"
KN, KD = sys.argv[5].split("/")  # the literal as written in the target statement (not reduced)
Kq = q(K); Kr = f"({KN} / {KD} : ℝ)"
Kchain = f"({KN} / {KD})"
side = 'sideU' if mode == 'slowp' else 'sideT'
endb = f'(endSl {Ls})' if mode == 'slowp' else f'(endO {Ls})'
Phi = '(fun _ p _ t => p t < 1)' if mode == 'slowp' else '(fun _ _ _ _ => True)'
spec = '(fun c hok hsd => sideU_spec c hok hsd)' if mode == 'slowp' else '(fun _ _ _ _ _ _ _ _ _ _ => trivial)'
what = ("SlowS: p < 1 on [0, L], and at L: 0 ≤ p, q < 3(1 − p), f > 11/15" if mode == 'slowp'
        else "overshoot: p > 1 at L")
ev = 'SlowS' if mode == 'slowp' else 'Over'
lines = ["import Work.FSSep.SCellWC", "",
 f"/-! Generated by `runs/2026-11-11T0232Z/scripts/gen_sep_wc.py` (FS_K = {K}) and `emit_sep_wc.py` (SEG = {SEG}):",
 f"{n} weighted one-sided cells for the clamped adverse-sign coefficient-K field `vS K`, K = {K}",
 f"(Falkner–Skan β = −{1/K}, scaled; equal to g''' + K g g'' − 1 + g'² = 0 on every cell's ball),",
 f"g(0) = g'(0) = g''(0) = 0 on [0, {L}].",
 "Every numeric side condition, link, defect bound and sign condition is checked by kernel evaluation over ℚ",
 f"(`decide +kernel`), one declaration per segment. `chain`: every solution of the clamped field shows {what}. -/", "",
 f"namespace Work.FSSep.{mod}", "open Set Checked.Sim Work.FSSep.SCellWC Work.FSNeg.NBase Work.FSSep.SBase", ""]
keys = ['t0', 'h', 'δ', 'ε', 'B', 'μ', 'w1', 'w2', 'r1', 'r2']
for i, c in enumerate(cells):
    lines.append(f"def c{i} : Cell := ⟨" + ", ".join(q(fr(c[k])) for k in keys) + ", " +
                 ", ".join(ql(c[k]) for k in ('pg', 'pp', 'pq')) + "⟩")
lines.append("")
segs = []; s = 0
while s < n:
    e = min(s + SEG, n); segs.append((s, e)); s = e
for j, (s, e) in enumerate(segs):
    lst = "[" + ", ".join(f"c{i}" for i in range(s, e)) + "]"
    term = f"(fun e => linkOK e c{e})" if e < n else endb
    lines += [f"theorem seg{j}_ok : chainS {Kq} {Ls} {side} {term} {lst} = true := by", "  decide +kernel", ""]
lines += ["theorem glue {P : ℝ → Prop} {a b : ℝ} (h1 : ∀ t ∈ Icc 0 a, P t) (h2 : ∀ t ∈ Icc a b, P t) :",
 "    ∀ t ∈ Icc 0 b, P t := by",
 "  intro t ht",
 "  rcases le_total t a with h | h",
 "  · exact h1 t ⟨ht.1, h⟩",
 "  · exact h2 t ⟨h, ht.2⟩", "",
 f"/-- Every solution Y of Y' = vS K t Y (the clamped adverse-sign field with K = {K}) on [0, {L}]",
 f"(derivatives within the interval) with Y(0) = (0, 0, 0): {what}. -/",
 f"theorem chain : ChainK {Kchain} {ev} := by",
 f"  refine ⟨{Lr}, by norm_num, fun Y hY h0 => ?_⟩",
 f"  have hX : (({Ls} : ℚ) : ℝ) = {Lr} := by norm_num",
 f"  have hK : (({Kq} : ℚ) : ℝ) = {Kr} := by norm_num",
 f"  have hs : SolC (({Kq} : ℚ) : ℝ) (({Ls} : ℚ) : ℝ) 0 (fun t => (Y t).1) (fun t => (Y t).2.1) (fun t => (Y t).2.2) := by",
 "    rw [hX, hK]",
 "    exact ⟨fun t ht => (hY t ht).fst, fun t ht => (hY t ht).snd.fst, fun t ht => (hY t ht).snd.snd⟩",
 "  have z0 : ((c0.t0 : ℚ) : ℝ) = 0 := by simp [c0]",
 "  have b0 : InBox c0 (fun t => (Y t).1) (fun t => (Y t).2.1) (fun t => (Y t).2.2) := by",
 "    unfold InBox; simp only [z0, h0]",
 "    simp only [V, c0, List.headD_cons]; push_cast; norm_num",
 ""]
prev = "b0"; acc = None
for j, (s, e) in enumerate(segs):
    rest = "[" + ", ".join(f"c{i}" for i in range(s + 1, e)) + "]"
    if e < n:
        lines.append(f"  obtain ⟨b{j+1}, P{j}⟩ := segS_q0 (Φ := {Phi}) {spec} c{e} {rest} c{s} seg{j}_ok hs {prev}")
        prev = f"b{j+1}"
    else:
        if mode == 'slowp':
            lines.append(f"  obtain ⟨E, P{j}⟩ := endSl_q0 (Φ := {Phi}) {spec} {rest} c{s} seg{j}_ok hs {prev}")
        else:
            lines.append(f"  have E := endO_q0 {rest} c{s} seg{j}_ok hs {prev}")
    if mode == 'slowp':
        if j == 0:
            lines.append(f"  rw [z0] at P0"); acc = "P0"
        else:
            lines.append(f"  have A{j} := glue {acc} P{j}"); acc = f"A{j}"
if mode == 'slowp':
    lines += [f"  rw [hX] at E {acc}", f"  exact ⟨{Lr}, by norm_num, {acc}, E.1, E.2.1, E.2.2⟩"]
else:
    lines += [f"  rw [hX] at E", f"  exact ⟨{Lr}, by norm_num, E⟩"]
lines += ["", f"end Work.FSSep.{mod}", ""]
open(out, 'w').write("\n".join(lines))
print("wrote", out, n, "cells", len(segs), "segments")
