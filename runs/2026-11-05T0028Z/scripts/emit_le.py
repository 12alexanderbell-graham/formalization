def q(x):
    x = F(x)
    if x.denominator == 1:
        return f"({x.numerator} : ℚ)"
    return f"({x.numerator}/{x.denominator} : ℚ)"


def r(x):
    x = F(x)
    if x.denominator == 1:
        return f"({x.numerator} : ℝ)"
    return f"({x.numerator}/{x.denominator} : ℝ)"


def lst(name, p):
    return f"def {name} : List ℚ := [{', '.join(q(c) for c in p)}]\n"


