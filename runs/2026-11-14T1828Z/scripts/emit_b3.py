"""Emit Work/Math/BE3Data.lean (cells as data, each segment decided by kernel evaluation) and
Work/Math/BE3Chain.lean (the segments chained) from gen_b3.py's cells (run 2026-11-14T1828Z; adapted from
runs/2026-11-14T1428Z/scripts/emit_bo.py).  Segments: m=1 (2u-v>0) to A5, one m=4 bracket cell [A5, B5]
(G<0, the third maximum), m=2 (2u-v<0) to T.
usage: emit_b3.py cells.json BE3Data.lean BE3Chain.lean"""
import json, sys
from fractions import Fraction as F
cells = json.load(open(sys.argv[1]))
outD, outC = sys.argv[2], sys.argv[3]
L0, T, FU, FV, R = '20000', '300000', '998005545 / 1000000000', '2002054156 / 1000000000', '4 / 10000000'
ULW, UHW = '10018942 / 10000000', '10018978 / 10000000'
SEG = 10
def q(x):
    x = F(x)
    return '(%d : ℚ)' % x.numerator if x.denominator == 1 else '(%d/%d : ℚ)' % (x.numerator, x.denominator)
n = len(cells)
segs = []; i = 0
while i < n:
    j = i
    while j < n and cells[j]['m'] == cells[i]['m'] and j - i < SEG: j += 1
    segs.append((cells[i]['m'], list(range(i, j)))); i = j
L = ['import Checked.Math.BEOCell', '',
     '/-! Bonnor–Ebert sphere, `BE3Data`: one-sided cells (`Checked.Math.BEOCell`) of the regular isothermal',
     'solution in homology variables from the end radius of `BEOChain` to the start of the tail, as data',
     '(generator `runs/2026-11-14T1828Z/scripts/gen_b3.py`, emitter `emit_b3.py`), each segment decided by kernel',
     'evaluation. -/', '',
     'namespace Work.Math.BE3Data', 'open Checked.Math.BEOCell', 'open Checked.Math.GCellQ (lo hi)', '']
for k, c in enumerate(cells):
    f = [c[x] for x in ('t0', 'h', 'delta', 'eps', 'B', 'Be', 'mu', 'UL', 'UH', 'VL', 'VH')]
    L.append('def c%d : OCell := ⟨%s,' % (k, ', '.join(q(x) for x in f)))
    L.append('  [%s],' % ', '.join(q(x) for x in c['pu']))
    L.append('  [%s]⟩' % ', '.join(q(x) for x in c['pv']))
L.append('')
names = []
for s, (m, idx) in enumerate(segs):
    e = idx[-1] + 1
    term = ('fun e => linkOK e c%d' % e) if e < n else 'endOK %s (%s) (%s) (%s)' % (T, FU, FV, R)
    nm = 's%d_ok' % s; names.append(nm)
    L.append('theorem %s : chainTo (%s : ℚ) %s %d (%s) [%s] = true := by\n  decide +kernel\n' %
             (nm, L0, T, m, term, ', '.join('c%d' % i for i in idx)))
ib = [k for k, c in enumerate(cells) if c['m'] == 4]
assert len(ib) == 1; ib = ib[0]
L.append('theorem br_u : decide ((%s : ℚ) ≤ lo c%d.pu c%d.h - c%d.B ∧ hi c%d.pu c%d.h + c%d.B ≤ %s) = true := by\n  decide +kernel\n'
         % (ULW, ib, ib, ib, ib, ib, ib, UHW))
L.append('end Work.Math.BE3Data')
open(outD, 'w').write('\n'.join(L) + '\n')
def t0(k): return cells[k]['t0']
A5 = t0(ib); B5 = t0(ib + 1)
def rl(x):
    x = F(x); return '%d' % x.numerator if x.denominator == 1 else '%d / %d' % (x.numerator, x.denominator)
C = ['import Work.Math.BE3Data', '',
     '/-! Bonnor–Ebert sphere, `BE3Chain`: the one-sided cells of `BE3Data` chained along every solution of the',
     'homology system on [20000, 300000] that starts in the first cell\'s input box: 2u − v > 0 up to the bracket of',
     'the third maximum of the mass, 6u − 2u² − 3uv + v < 0 and u in a window on it, 2u − v < 0 after it, and the',
     'state at 300000. Generated by `runs/2026-11-14T1828Z/scripts/emit_b3.py`. -/', '',
     'namespace Work.Math.BE3Chain', 'open Set Checked.Sim Checked.Sim.QPoly Checked.Math.BEOCell Work.Math.BE3Data',
     'open Checked.Math.GCellQ (lo hi lo_le le_hi)', '',
     'set_option maxHeartbeats 8000000 in',
     'theorem chain {u v : ℝ → ℝ}',
     '    (hu : ∀ t ∈ Icc (%s : ℝ) %s,' % (L0, T),
     '      HasDerivWithinAt u (u t * (3 - u t - v t) / t) (Icc ((%s : ℚ) : ℝ) ((%s : ℚ) : ℝ)) t)' % (L0, T),
     '    (hv : ∀ t ∈ Icc (%s : ℝ) %s,' % (L0, T),
     '      HasDerivWithinAt v (v t * (u t - 1) / t) (Icc ((%s : ℚ) : ℝ) ((%s : ℚ) : ℝ)) t)' % (L0, T),
     '    (h0 : |u %s - 1005687661 / 1000000000| ≤ 2 / 10000000)' % L0,
     '    (h0\' : |v %s - 1989078226 / 1000000000| ≤ 2 / 10000000) :' % L0,
     '    (∀ t ∈ Icc (%s : ℝ) (%s), 0 < 2 * u t - v t) ∧' % (L0, rl(A5)),
     '    (∀ t ∈ Icc (%s : ℝ) (%s),' % (rl(A5), rl(B5)),
     '      6 * u t - 2 * u t ^ 2 - 3 * (u t * v t) + v t < 0 ∧ (%s : ℝ) ≤ u t ∧ u t ≤ %s) ∧' % (ULW, UHW),
     '    (∀ t ∈ Icc (%s : ℝ) %s, 2 * u t - v t < 0) ∧' % (rl(B5), T),
     '    |u %s - %s| ≤ %s ∧ |v %s - %s| ≤ %s := by' % (T, FU, R, T, FV, R),
     '  have hX : ((%s : ℚ) : ℝ) = %s := by norm_num' % (T, T),
     '  have hL : ((%s : ℚ) : ℝ) = %s := by norm_num' % (L0, L0),
     '  have hu\' : ∀ t ∈ Icc (c0.t0 : ℝ) ((%s : ℚ) : ℝ),' % T,
     '      HasDerivWithinAt u (u t * (3 - u t - v t) / t) (Icc ((%s : ℚ) : ℝ) ((%s : ℚ) : ℝ)) t := by' % (L0, T),
     '    rw [hX, show c0.t0 = %s from rfl]; push_cast; exact hu' % L0,
     '  have hv\' : ∀ t ∈ Icc (c0.t0 : ℝ) ((%s : ℚ) : ℝ),' % T,
     '      HasDerivWithinAt v (v t * (u t - 1) / t) (Icc ((%s : ℚ) : ℝ) ((%s : ℚ) : ℝ)) t := by' % (L0, T),
     '    rw [hX, show c0.t0 = %s from rfl]; push_cast; exact hv' % L0,
     '  have a0 : Nw (u (c0.t0 : ℝ) - ((c0.pu.headD 0 : ℚ) : ℝ)) (v (c0.t0 : ℝ) - ((c0.pv.headD 0 : ℚ) : ℝ)) ≤ (c0.δ : ℝ) ^ 2 := by',
     '    rw [show c0.t0 = %s from rfl, show c0.pu.headD 0 = 1005687661 / 1000000000 from rfl,' % L0,
     '      show c0.pv.headD 0 = 1989078226 / 1000000000 by decide +kernel, show c0.δ = 8 / 10000000 by decide +kernel]',
     '    push_cast',
     '    exact start_box h0 h0\' (by norm_num) (by norm_num)',
     '  have p0 : (c0.t0 : ℝ) ≤ (c0.t0 : ℝ) := le_rfl']
assert F(cells[0]['delta']) == F(8, 10000000)
assert F(cells[0]['pu'][0]) == F(1005687661, 1000000000) and F(cells[0]['pv'][0]) == F(1989078226, 1000000000)
ns = len(segs)
for s in range(ns):
    if s < ns - 1:
        C += ['  obtain ⟨o%d, i%d, a%d⟩ := seg_q _ _ _ %s' % (s, s, s + 1, names[s]),
              '    (fun t ht => hu\' t ⟨by linarith [ht.1, p%d], ht.2⟩) (fun t ht => hv\' t ⟨by linarith [ht.1, p%d], ht.2⟩) a%d' % (s, s, s),
              '  have p%d := p%d.trans o%d' % (s + 1, s, s)]
    else:
        C += ['  obtain ⟨i%d, kU, kV⟩ := end_q _ _ %s' % (s, names[s]),
              '    (fun t ht => hu\' t ⟨by linarith [ht.1, p%d], ht.2⟩) (fun t ht => hv\' t ⟨by linarith [ht.1, p%d], ht.2⟩) a%d' % (s, s, s)]
groups = []
for s, (m, idx) in enumerate(segs):
    if groups and groups[-1][0] == m: groups[-1][1].append(s)
    else: groups.append((m, [s]))
assert [g[0] for g in groups] == [1, 4, 2], [g[0] for g in groups]
for gi, (m, ss) in enumerate(groups):
    C.append('  have G%d := i%d' % (gi, ss[0]))
    for s in ss[1:]:
        C.append('  have G%d := Checked.Math.GCellQ.icc_glue G%d i%d' % (gi, gi, s))
def eq(name, k, val):
    return '  have %s : (c%d.t0 : ℝ) = %s := by rw [show c%d.t0 = %s from rfl]; norm_num' % (name, k, val, k, val)
firsts = [idx[0] for _, idx in segs]
k5a = firsts[groups[1][1][0]]; k5b = firsts[groups[2][1][0]]
assert k5a == ib and k5b == ib + 1
C += ['  have e0 : (c0.t0 : ℝ) = %s := by rw [show c0.t0 = %s from rfl]; norm_num' % (L0, L0),
      eq('e1', k5a, rl(A5)), eq('e2', k5b, rl(B5)),
      '  -- the bracket cell of the third maximum: u window',
      '  have hok := (show cellOK (%s : ℚ) %s 4 c%d = true by decide +kernel)' % (L0, T, ib),
      '  have hok1 : decide (CellProp %s %s c%d) = true := by' % (L0, T, ib),
      '    simp only [cellOK, Bool.and_eq_true] at hok; exact hok.1',
      '  have hT : ((c%d.t0 : ℚ) : ℝ) + ((c%d.h : ℚ) : ℝ) ≤ ((%s : ℚ) : ℝ) := by' % (ib, ib, T),
      '    exact_mod_cast (show c%d.t0 + c%d.h ≤ %s by decide +kernel)' % (ib, ib, T),
      '  have pb := p%d' % groups[1][1][0],
      '  have hub : ∀ t ∈ Icc (c%d.t0 : ℝ) (c%d.t0 + c%d.h),' % (ib, ib, ib),
      '      HasDerivWithinAt u (u t * (3 - u t - v t) / t) (Icc ((%s : ℚ) : ℝ) ((%s : ℚ) : ℝ)) t := fun t ht =>' % (L0, T),
      '    hu\' t ⟨by linarith [ht.1, pb], by linarith [ht.2, hT]⟩',
      '  have hvb : ∀ t ∈ Icc (c%d.t0 : ℝ) (c%d.t0 + c%d.h),' % (ib, ib, ib),
      '      HasDerivWithinAt v (v t * (u t - 1) / t) (Icc ((%s : ℚ) : ℝ) ((%s : ℚ) : ℝ)) t := fun t ht =>' % (L0, T),
      '    hv\' t ⟨by linarith [ht.1, pb], by linarith [ht.2, hT]⟩',
      '  have hcq := (cell_q c%d hok1 hub hvb a%d).1' % (ib, groups[1][1][0]),
      '  have eh : (c%d.t0 : ℝ) + c%d.h = %s := by' % (ib, ib, rl(B5)),
      '    rw [show c%d.t0 = %s from rfl, show c%d.h = %s - %s by decide +kernel]; norm_num' % (ib, rl(A5), ib, rl(B5), rl(A5)),
      '  have bu := of_decide_eq_true br_u',
      '  have bu1 : ((%s : ℚ) : ℝ) ≤ ((lo c%d.pu c%d.h - c%d.B : ℚ) : ℝ) := by exact_mod_cast bu.1' % (ULW, ib, ib, ib),
      '  have bu2 : ((hi c%d.pu c%d.h + c%d.B : ℚ) : ℝ) ≤ ((%s : ℚ) : ℝ) := by exact_mod_cast bu.2' % (ib, ib, ib, UHW),
      '  push_cast at bu1 bu2',
      '  rw [e0] at G0',
      '  rw [hX] at G2',
      '  refine ⟨?_, ?_, ?_, ?_, ?_⟩',
      '  · intro t ht; exact G0 t ⟨ht.1, by rw [e1]; exact ht.2⟩',
      '  · intro t ht',
      '    have ht\' : t ∈ Icc (c%d.t0 : ℝ) (c%d.t0 + c%d.h) := ⟨by rw [e1]; exact ht.1, by rw [eh]; exact ht.2⟩' % (ib, ib, ib),
      '    have hN := hcq t ht\'',
      '    obtain ⟨c1, -⟩ := cell_box\' c%d hok1 ht\' hN' % ib,
      '    have l1 := lo_le c%d.pu (h := c%d.h) (σ := t - c%d.t0) (by linarith [ht\'.1]) (by linarith [ht\'.2])' % (ib, ib, ib),
      '    have l2 := le_hi c%d.pu (h := c%d.h) (σ := t - c%d.t0) (by linarith [ht\'.1]) (by linarith [ht\'.2])' % (ib, ib, ib),
      '    have c1\' := abs_le.1 c1',
      '    rw [e1, e2] at G1',
      '    exact ⟨G1 t ht, by linarith [c1\'.1], by linarith [c1\'.2]⟩',
      '  · intro t ht; rw [e2] at G2; exact G2 t ht',
      '  · push_cast at kU; norm_num at kU ⊢; exact kU',
      '  · push_cast at kV; norm_num at kV ⊢; exact kV', '',
      'end Work.Math.BE3Chain']
open(outC, 'w').write('\n'.join(C) + '\n')
print('cells', n, 'segments', ns, 'groups', [(g[0], len(g[1])) for g in groups], 'A5 B5', rl(A5), rl(B5), file=sys.stderr)
