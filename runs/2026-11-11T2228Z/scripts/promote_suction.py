import re, pathlib
R = pathlib.Path('/home/claude/formalization')
NAMES = {'HS': 'Hiemenz', 'HmS': 'Homann', 'F5S': 'coefficient-five (Falkner–Skan one-fifth row)',
         'F10S': 'coefficient-ten (Falkner–Skan one-tenth row)'}
DOCS = {
 'Flow': 'the clamped {n} flow started from a nonzero wall value of f, with zero wall velocity and a free wall shear; continuity in the wall shear. Ported by `runs/2026-11-11T2228Z/scripts/port_suction_all.py` from the zero-wall-value module of the same stack.',
 'Limit': 'along the clamped {n} flow from a nonnegative wall value of f (suction), neither shooting event implies that every clamp is inactive, that the velocity stays in [0, 1) with positive shear, and that the velocity tends to one. Ported by `runs/2026-11-11T2228Z/scripts/port_suction_all.py`.',
 'UData': 'generated cells (`runs/2026-11-11T2228Z/scripts/gen_k_wc_s.py` or `gen_hiemenz_wc_s.py`, then `emit_hiemenz_wc_s.py`) for the clamped {n} field with suction, started at the lower end of the shooting interval, ending in the undershoot event; every side condition is checked by kernel evaluation.',
 'OData': 'generated cells (`runs/2026-11-11T2228Z/scripts/gen_k_wc_s.py` or `gen_hiemenz_wc_s.py`, then `emit_hiemenz_wc_s.py`) for the clamped {n} field with suction, started at the upper end of the shooting interval, ending in the overshoot event; every side condition is checked by kernel evaluation.',
 'Assemble': 'the supremum argument for the {n} boundary-value problem with suction (a nonzero wall value of f): a wall shear between the two certified shooting values with neither event, hence a solution with velocity in [0, 1), positive shear and velocity tending to one, whose wall shear lies in the interval printed in the statement of `exists_bvpS`. Ported by `runs/2026-11-11T2228Z/scripts/port_suction_all.py`.',
}
def fix(src):
    src = src.replace('Work.Suction.', 'Checked.Suction.')
    assert 'Work.' not in src, [l for l in src.splitlines() if 'Work.' in l]
    return src
(R / 'Checked/Suction').mkdir(exist_ok=True)
mods = []
for T in NAMES:
    for part in ['Flow', 'Limit', 'UData', 'OData', 'Assemble']:
        f = R / f'Work/Suction/{T}{part}.lean'
        src = fix(f.read_text())
        doc = f"/-! Suction witnesses for hypothesis necessity, `{T}{part}`: " + DOCS[part].format(n=NAMES[T]) + " -/"
        src, c = re.subn(r'/-!.*?-/', lambda m: doc, src, count=1, flags=re.S)
        assert c == 1
        (R / f'Checked/Suction/{T}{part}.lean').write_text(src)
        mods.append(f'Checked.Suction.{T}{part}')
WIT = [('runs/2026-11-11T2228Z/lean/BlasiusSuction.lean', 'NecessityI', 'Checked.Trust.NCH', 'Checked.Trust.NCI',
        'Necessity of the wall condition (f vanishes at the wall) in the Blasius and Falkner–Skan β-zero wall-shear headlines: the Blasius flow with suction from the wall state with f, p, q equal to one, zero, one has every clamp inactive and its velocity increases to a limit at most two; scaled to velocity tending to one it has a nonzero wall value of f and a wall shear above each window. Module `NecessityI`, from `runs/2026-11-11T2228Z/lean/BlasiusSuction.lean`.'),
       ('Work/Suction/HSWitness.lean', 'NecessityJ', 'Work.Suction.HSWitness', 'Checked.Trust.NCJ',
        'Necessity of the wall condition (f vanishes at the wall) in the Hiemenz boundary-value headlines (bound-free, bounded-class, monotone; window and equality pairs): the Hiemenz problem with suction has a solution (`Checked.Suction.HSAssemble.exists_bvpS`) with a nonzero wall value of f and a wall shear above the window. Module `NecessityJ`.'),
       ('Work/Suction/FSWitness.lean', 'NecessityK', 'Work.Suction.FSWitness', 'Checked.Trust.NCK',
        'Necessity of the wall condition (f vanishes at the wall) in the Homann and the three Falkner–Skan row boundary-value headlines: the suction solutions of the coefficient problems (`Checked.Suction.*Assemble.exists_bvpS`), scaled to the Falkner–Skan form, have a nonzero wall value of f and a wall shear above each window. Module `NecessityK`, generated by `runs/2026-11-11T2228Z/scripts/gen_witness.py`.')]
for path, mod, oldns, newns, doc in WIT:
    src = (R / path).read_text()
    src = src.replace(oldns, newns)
    src = fix(src)
    src, c = re.subn(r'/-!.*?-/', lambda m: '/-! ' + doc + ' -/', src, count=1, flags=re.S)
    assert c == 1
    # module docs carry no numbers (check_prose rule 7): replace the numerals of the docs above by words
    d = re.search(r'/-!.*?-/', src, re.S).group(0)
    d2 = d
    assert not re.search(r'\d', re.sub(r'`[^`]*`', '', d2)), d2
    src = src.replace(d, d2)
    (R / f'Checked/Trust/{mod}.lean').write_text(src)
    mods.append(f'Checked.Trust.{mod}')
root = (R / 'Checked.lean').read_text()
add = [f'import {m}' for m in mods if f'import {m}\n' not in root]
(R / 'Checked.lean').write_text(root.rstrip('\n') + '\n' + '\n'.join(add) + '\n')
print('promoted', len(mods), 'modules')
