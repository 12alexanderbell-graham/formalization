# chaining
lowg = [g for g in groups if float(g[2]) <= 0.2875]
highg = [g for g in groups if float(g[1]) >= 0.2881]
def chain(name, gs, lo, hi):
    s = f'''
theorem {name} (Ω : ℝ) (h0 : ({lo} : ℝ) ≤ Ω) (h1 : Ω ≤ {hi}) :
    margChi tbl 68 2.8 0.2878 + 1 / 10 ^ 12 < margChi tbl 68 2.8 Ω := by
'''
    for g in gs[:-1]:
        k = g[0].split('_')[1]
        s += f"  rcases le_or_gt Ω {g[2]} with h | h\n  · exact gap68_{k} Ω (by linarith) h\n"
    k = gs[-1][0].split('_')[1]
    s += f"  exact gap68_{k} Ω (by linarith) (by linarith)\n"
    return s
out.append(chain('low68_gap', lowg, '0', '0.2875'))
out.append(chain('high68_gap', highg, '0.2881', '1'))
out.append('\nend Work.Data.FR13GapCerts\n')
open('Work/Data/FR13GapCerts.lean', 'w').write(''.join(out))
print(len(lowg), len(highg))
