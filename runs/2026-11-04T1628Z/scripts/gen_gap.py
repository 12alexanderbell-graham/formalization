"""Emit Work/Data/FR13GapCerts.lean: gap versions (eta) of the prior-68 group certificates of
Work/Data/FR13Certs.lean, reusing its per-group sum lemmas; only the two endpoint checks change.
Run from the repository root."""
import re
from fractions import Fraction as F
src = open('Work/Data/FR13Certs.lean').read()
pat = re.compile(r"theorem (g68_\d+) \(Ω : ℝ\) \(ha : \((\S+) : ℝ\) ≤ Ω\) \(hb : Ω ≤ (\S+)\) :\n.*?\n  group_ok tbl hz hh 68 2\.8 0\.2878 (\S+) \((\S+) / (\S+) : ℝ\) \((\S+) / (\S+) : ℝ\) (\S+) (\S+) (\S+) (\S+) (s68_\d+) sR68\n.*?t0_68_\d+ t1_68_\d+ lo68", re.S)
ETA = F(1, 10**12)
def q(x): return F(x)
out = []
groups = []
for m in pat.finditer(src):
    name, a, b, blo, p0n, p0d, p1n, p1d, b0, b1, a2, b2, s = m.groups()
    assert a == a2 and b == b2
    Hb, sg = F(68), F(28, 10)
    blo, p0, p1, b0, b1 = q(blo), F(int(p0n), int(p0d)), F(int(p1n), int(p1d)), q(b0), q(b1)
    Ar = p0 + 1/sg**2 + p1*F('0.2878')
    K = (blo + Hb/sg**2)**2/Ar + 1 - ETA
    for x in (q(a), q(b)):
        val = K*((p0 + 1/sg**2) + p1*x) - ((b0 + Hb/sg**2) + b1*x)**2 - Ar
        assert val > 0, (name, x, float(val))
    groups.append((name, a, b, s, m.group(4), p0n, p0d, p1n, p1d, m.group(9), m.group(10)))
print(len(groups), "groups ok")
