ROWS = [("0.070","69","19.6"),("0.100","69","12"),("0.120","68.6","26.2"),("0.170","83","8"),("0.179","75","4"),("0.199","75","5"),("0.200","72.9","29.6"),("0.270","77","14"),("0.280","88.8","36.6"),("0.350","76.3","5.6"),("0.352","83","14"),("0.400","95","17"),("0.440","82.6","7.8"),("0.480","97","62"),("0.593","104","13"),("0.600","87.9","6.1"),("0.680","92","8"),("0.730","97.3","7.0"),("0.781","105","12"),("0.875","125","17"),("0.880","90","40"),("0.900","117","23"),("1.037","154","20"),("1.300","168","17"),("1.430","177","18"),("1.530","140","14"),("1.750","202","40"),("2.300","224","8")]
Z=[F(a) for a,_,_ in ROWS]; H=[F(b) for _,b,_ in ROWS]; S=[F(c) for _,_,c in ROWS]
Cc=[(1+z)**3-1 for z in Z]
W=[1/s**2 for s in S]
P0=sum(W); P1=sum(c*w for c,w in zip(Cc,W))
def dec(x, digits=12, up=None):
    """decimal string of rational x rounded (up=True ceil, False floor, None nearest) at 10^-digits"""
    q=F(10)**digits; n=x*q
    import math
    if up is True: k=math.ceil(n)
    elif up is False: k=math.floor(n)
    else: k=round(n)
    r=F(k,10**digits)
    s=Decimal(k)/Decimal(10**digits)
    return r, format(s,'f')
def sqrt_approx(y, digits=10):
    d=Decimal(y.numerator)/Decimal(y.denominator)
    return dec(F(str(d.sqrt())), digits)
def T0(s): return sum(h*(1+si**2)/(2*si*sg**2) for h,si,sg in zip(H,s,S))
def T1(s): return sum(h*c/(2*si*sg**2) for h,c,si,sg in zip(H,Cc,s,S))
def Lsum(s,om): 
    tot=F(0)
    for h,c,si,sg in zip(H,Cc,s,S):
        y=om*c+1; tot+=h*2*si*y/(y+si**2)/sg**2
    return tot
def plan(Hb, sp, omr, lo, hi):
    Hb=F(Hb); sp=F(sp); omr=F(omr)
    A0=P0+1/sp**2; A1=P1; Ar=A0+A1*omr; hb=Hb/sp**2
    sr=[sqrt_approx(1+omr*c) for c in Cc]
    blo_r, blo_s = dec(Lsum([x[0] for x in sr],omr), 10, False)
    K=(blo_r+hb)**2/Ar+1
    groups=[]
    def try_group(a,b,depth=0):
        m=(a+b)/2
        s=[sqrt_approx(1+m*c) for c in Cc]
        sv=[x[0] for x in s]
        b0,b0s=dec(T0(sv),10,True); b1,b1s=dec(T1(sv),10,True)
        q=lambda x: K*(A0+A1*x)-(b0+hb+b1*x)**2-Ar
        if q(a)>0 and q(b)>0:
            groups.append((a,b,s,b0s,b1s)); return
        assert depth<40, (a,b)
        mm=F(str(Decimal(m.numerator)/Decimal(m.denominator)))  # keep
        # split at a short decimal
        mid=F(round(m*10**8),10**8)
        try_group(a,mid,depth+1); try_group(mid,b,depth+1)
    try_group(F(0),F(lo)); try_group(F(hi),F(1))
    return dict(Hb=Hb,sp=sp,omr=omr,sr=sr,blo=blo_s,groups=groups)
def fmtF(x):
    d=Decimal(x.numerator)/Decimal(x.denominator)
    s=format(d.normalize(),'f')
    assert F(s)==x, x
    return s
