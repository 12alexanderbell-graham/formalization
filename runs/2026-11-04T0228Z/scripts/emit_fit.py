def tr_low(c):
    A_, B_ = lower_trunc(c); c['A_'], c['B_'] = A_, B_
def tr_up(c):
    C_, D_ = upper_round(c); c['C_'], c['D_'] = C_, D_

def try_case2(a, b, pr, low, upp):
    # as try_case but with truncated certificate values (what Lean sees)
    cons = []
    for (k, j) in pr:
        r = R[(k, j)]; Lc = low[j]; Uc = upp[k]
        Lv = lambda O: Lc['A_'] - Lc['B_'] * O
        Uv = lambda O: Uc['C_'] + Uc['D_'] * O
        if min(Lv(a), Lv(b)) <= 0: return None
        rho = max(r * Uv(O) / (KAPPA * Lv(O)) for O in (a, b))
        rho = rat(float(rho), 6, up=True)
        while any(rho * KAPPA * Lv(O) < r * Uv(O) for O in (a, b)): rho += F(1, 10**6)
        cons.append((k, j, rho))
    (k1, j1, r1), (k2, j2, r2) = cons
    a11 = (r1*j1**2 - k1**2)/4; a12 = (r2*j2**2 - k2**2)/4
    a21 = (r1*j1**3 - k1**3)/8; a22 = (r2*j2**3 - k2**3)/8
    det = a11*a22 - a12*a21
    if det == 0: return None
    l1 = (-1*a22 - a12*F(20,3))/det; l2 = (a11*F(20,3) - a21*-1)/det
    if l1 < 0 or l2 < 0: return None
    S = [F(0)]*3
    for (k, j, rho), lam in zip(cons, (l1, l2)):
        S = padd(S, pscale(padd(Qlo(k), pscale(Qhi(j), rho), -1), lam))
    mn = pmin(S, a, b)
    return dict(a=a, b=b, cons=cons, lam=(l1, l2), S=S, min=mn, ok=mn > M)

def cover(A_, B_, low, upp):
    cases = []; stack = [(A_, B_, 0)]
    while stack:
        a_, b_, d = stack.pop()
        best = None
        for pr in PAIRS:
            r = try_case2(a_, b_, pr, low, upp)
            if r and (best is None or r['min'] > best['min']): best = r
        if best and best['ok']: cases.append(best)
        elif d >= DEPTH: return None
        else:
            m = (a_ + b_)/2; stack += [(m, b_, d+1), (a_, m, d+1)]
    return cases

def jint(A_, B_):
    mid = (A_ + B_)/2
    low = {j: lower_cert(j, mid, N) for j in (1, 5)}
    upp = {k: upper_cert(k, A_, B_, N) for k in (1, 3)}
    for c in low.values(): tr_low(c)
    for c in upp.values(): tr_up(c)
    cs = cover(A_, B_, low, upp)
    if cs is not None: return [((A_, B_), low, upp, cs)]
    m = (A_ + B_)/2
    return jint(A_, m) + jint(m, B_)

