import json, re
C = json.load(open('srk_consts.json'))
RK = open('../../../Work/Chemistry/RKExists.lean').read().split('\n')
i_ns = next(i for i, l in enumerate(RK) if l.startswith('namespace Work.Chemistry.RKExists'))
