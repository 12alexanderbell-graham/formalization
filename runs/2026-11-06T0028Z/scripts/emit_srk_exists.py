RKC = {'1187001329 / 10000000000': C['T0'], '593500771 / 5000000000': C['T1'], '2569 / 2000000': C['PLO'],
       '12849 / 10000000': C['PHI'], '3486983 / 2500000': C['A1'], '6973967 / 5000000': C['B1'],
       '844017 / 10000': C['A3'], '3486981 / 2500000': C['B1h'], '843727 / 10000': C['A3h'], '52733 / 625': C['B3h']}
WIN = {'3 / 2': '7 / 5', '139 / 100': '6 / 5'}
def tr(txt):
    for k, v in WIN.items(): txt = re.sub(r'(?<![\d.])' + re.escape(k) + r'(?![\d.])', v, txt)
    txt = re.sub(r'\b(60|110|87)\b', lambda mm: {'60': '400', '110': '1200', '87': '800'}[mm.group(1)], txt)
    keys = sorted(RKC, key=len, reverse=True)
    return re.compile('|'.join(re.escape(k) for k in keys)).sub(lambda mm: RKC[mm.group(0)], txt)
