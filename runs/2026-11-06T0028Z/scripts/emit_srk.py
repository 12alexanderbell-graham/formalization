    txt = txt.replace('8 / 5', C['W1a']).replace('21 / 10', C['W1b'])
    return re.sub(r'\b(11|15|18)\b', lambda mm: {'11': C['W2a'], '15': C['W2b'], '18': C['XF']}[mm.group(1)], txt)
