C = json.load(open('srk_consts.json'))
RK = open('../../../Work/Chemistry/RKReduced.lean').read().split('\n')
idx = lambda s: next(i for i, l in enumerate(RK) if l.startswith(s))
i_gen, i_struct = idx('/-! ## Generated certificates -/'), idx('/-! ## Structure of the roots of `q` -/')
i_mono, i_ratio = idx('/-! ## Monotonicity of `g` and `ψ` -/'), idx('/-! ## From the pressure ratio to the acentric factor -/')
