"""Sibling SRK claims by substitution (run 2026-11-06T0028Z): given a variant config (kappa(1) as an exact
rational and as the statement literal, rounding targets, reduced-pressure window) whose certificates were
generated by `gen_srk.py <PLO_N> <PHI_N> variant_<tag>.json`, emit Work/Chemistry/<M>Reduced.lean,
<M>Exists.lean and <M>Acentric.lean from the compiled SRK modules: generated certificate blocks replaced
wholesale, every other generated constant replaced between non-digits, names and kappa replaced.
Usage: python3 variant.py variant_<tag>.json"""
import json, re, sys
from fractions import Fraction as F
V = json.load(open(sys.argv[1]))
TAG, M, T = V['tag'], V['module'], V['thm']
W = '../../../Work/Chemistry/'
old = json.load(open('srk_consts.json')); new = json.load(open(f'{TAG}_consts.json'))
for k in ['W1a', 'W1b', 'W2a', 'W2b', 'XF', 'X0', 'X1', 'S0', 'S1']:
    assert old[k] == new[k], k          # windows and enclosures shared with SRK
fr = lambda s: F(*[int(t) for t in s.replace(' ', '').split('/')]) if '/' in s else F(int(s))
def lit(q): return f"{q.numerator} / {q.denominator}" if q.denominator != 1 else f"{q.numerator}"
K = F(*V['kappa']); WT = F(*V['omega']); WH = F(1, 2 * 10 ** V['omega_k'])
ALO, AHI = -(1 + WT + WH), -(1 + WT - WH)
NUM = {old[k]: new[k] for k in ['T0', 'T1', 'PLO', 'PHI', 'A1', 'B1', 'A3', 'B1h', 'A3h', 'B3h', 'lA', 'lB', 'uC', 'uD', 'RLOr', 'RHIr']}
NUM.update({'939 / 500': lit(K), '-19925 / 10000': lit(ALO), '-19915 / 10000': lit(AHI)})
assert len(set(NUM)) == len(NUM)
TXT = [('0.480 + 1.574 * 1 - 0.176 * 1 ^ 2', V['kappa_lit']), ('0.0102', V['ratio_lit']), ('0.992', V['omega_lit']),
       ('Work.Chemistry.SRKReduced', f'Work.Chemistry.{M}Reduced'), ('Work.Chemistry.SRKExists', f'Work.Chemistry.{M}Exists'),
       ('Work.Chemistry.SRKAcentric', f'Work.Chemistry.{M}Acentric'),
       ('srk_omega1_unique', f'{T}_omega1_unique'), ('srk_omega1_exists', f'{T}_omega1_exists'),
       ('srk_unique_core', f'{T}_unique_core'), ('srk_exists_core', f'{T}_exists_core')] + [tuple(x) for x in V.get('text', [])]
def num_sub(s):
    keys = sorted(NUM, key=len, reverse=True)
    pat = re.compile(r'(?<![\d.])(' + '|'.join(re.escape(k) for k in keys) + r')(?![\d])')
    return pat.sub(lambda m: NUM[m.group(1)], s)
def doc_sub(s, doc):
    a = s.index('/-!'); b = s.index('-/', a) + 2
    return s[:a] + doc + s[b:]
c1o, c2o = open('srk_certs.lean.txt').read(), open('srk_certs2.lean.txt').read()
c1n, c2n = open(f'{TAG}_certs.lean.txt').read(), open(f'{TAG}_certs2.lean.txt').read()
for mod in ['Reduced', 'Exists', 'Acentric']:
    s = open(W + f'SRK{mod}.lean').read()
    if mod == 'Reduced':
        assert s.count(c1o) == 1 and s.count(c2o) == 1
        s = s.replace(c1o, '@@C1@@').replace(c2o, '@@C2@@')
    s = num_sub(s)
    for a, b in TXT:
        s = s.replace(a, b)
    s = s.replace('@@C1@@', c1n).replace('@@C2@@', c2n)
    s = doc_sub(s, V['docs'][mod].replace('\\n', '\n'))
    for k in NUM:
        if k in s and k not in ('939 / 500',):
            assert not re.search(r'(?<![\d.])' + re.escape(k) + r'(?![\d])', s), (mod, k)
    open(W + f'{M}{mod}.lean', 'w').write(s)
    print(M + mod, len(s.split('\n')))
