def q(s):
    f = F(s)
    return f"({f.numerator} : ℚ)" if f.denominator == 1 else f"({f.numerator}/{f.denominator} : ℚ)"


def r(f):
    f = F(f)
    return f"({f.numerator} : ℝ)" if f.denominator == 1 else f"({f.numerator}/{f.denominator} : ℝ)"


def lst(cs):
    return "[" + ", ".join(q(c) for c in cs) + "]"


def ev(p, s):
    acc = F(0)
    for c in reversed(p):
        acc = F(c) + s * acc
    return acc


def add(p, q_):
    n = max(len(p), len(q_))
    return [(F(p[i]) if i < len(p) else 0) + (F(q_[i]) if i < len(q_) else 0) for i in range(n)]


