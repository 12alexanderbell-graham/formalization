#!/usr/bin/env python3
"""Frozen-registry guard (trust track T2/T3, run 2026-10-31T0028Z; see LEDGER).

`scripts/trust/frozen.txt` holds a fingerprint of every headline, pin theorem, pinned and
classified definition (generated by `TRUST_RELOCK=1 lake env lean scripts/trust/StatementDeps.lean`;
StatementDeps fails CI when the compiled constants differ from it). This script fails CI when a
push *changes or removes* a frozen entry without adding a LEDGER.md line that names the constant
(its last name component is enough). New entries need no LEDGER line.

Why: red-team defects (runs/2026-10-31T0028Z/t5) silently changed what registered headlines,
pins and printed transcriptions say while keeping their names; nothing in CI noticed.

usage: check_relock.py <base-commit>   (empty / all-zero base: compares with HEAD~1)
"""
import re, subprocess, sys

LOCK = "scripts/trust/frozen.txt"


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True)


def parse(text):
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) == 2:
            out[parts[0]] = parts[1]
    return out


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else ""
    if not base or set(base) == {"0"} or git("cat-file", "-e", base + "^{commit}").returncode:
        base = "HEAD~1"
    old = git("show", f"{base}:{LOCK}")
    if old.returncode:
        print(f"no {LOCK} at {base}: nothing frozen yet")
        return 0
    new = parse(open(LOCK, encoding="utf-8").read())
    old = parse(old.stdout)
    changed = sorted(n for n, f in old.items() if new.get(n) != f)
    if not changed:
        print(f"frozen registry: {len(old)} entries at {base}, none changed or removed")
        return 0
    diff = git("diff", base, "HEAD", "--", "LEDGER.md").stdout
    added = "\n".join(l[1:] for l in diff.splitlines() if l.startswith("+") and not l.startswith("+++"))
    # the full name, or its last component as a whole word (red team C: `D1` must not be covered by `D1y`)
    def named(n):
        last = re.escape(n.split(".")[-1])
        return n in added or re.search(r"(?<![\w'])" + last + r"(?![\w'])", added) is not None
    missing = [n for n in changed if not named(n)]
    for n in changed:
        status = "removed" if n not in new else "changed"
        print(f"{status}: {n}" + ("  -- NOT named in a LEDGER.md addition" if n in missing else ""))
    if missing:
        print(f"::error::{len(missing)} frozen statement(s)/definition(s) changed or removed without a "
              "LEDGER.md entry naming them (annex XLIII: never weaken a statement and keep its name)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
