#!/usr/bin/env python3
"""Hypothesis necessity may not regress, and open hypotheses are disclosed (trust track T2b, run 2026-11-11T0028Z).

TRUST_MAP.md (generated by StatementDeps.lean, staleness-checked in CI) classifies every hypothesis of every
headline as NEEDED (a Checked theorem `necessity% <headline> i`), REDUNDANT (`dropped% <headline> i`) or open.
Until this run the classification was report-only: deleting a witness module, or changing a headline so that
a needed hypothesis became open again, changed only a number in a report nobody had to read.

Rule N1 (always): every headline with open hypotheses has a line in the baseline
`scripts/trust/necessity_open_baseline.txt` of the form `<headline as TRUST_MAP.md names it> | <open indices>`,
and the line lists exactly the open indices (so the baseline is updated in the same commit as new witnesses,
and it always states what is still open). Lines for headlines with nothing open, or for unknown headlines, fail.
Rule N2 (--base SHA): for a headline that the base TRUST_MAP.md lists with the same number of hypotheses,
every hypothesis that was NEEDED or REDUNDANT at the base still is (a classification never regresses: not to
open, not to "no obligation", whatever the reason: a deleted witness, a renumbered statement). A headline that
is new, or whose hypothesis count changed, needs a line added to LEDGER.md that names it in backticks exactly
as TRUST_MAP.md does, with the words `open <its open indices>` (or `classified` if nothing is open); a headline
that had classified hypotheses at the base and is gone needs such a line with the word `removed`. Lines that
differ from a base LEDGER line only by surrounding whitespace do not count as added.
Rule N3 (--base SHA): the totals NEEDED + REDUNDANT may not fall, and "no obligation" may not rise.
Rule N4 (blind red team AF, run 2026-11-11T0428Z: 4 of 6 defects got assumptions past the numbering): a
headline line may end with `shape: <reasons>` (StatementDeps `necShape`: `conclusion` = a `let` or a program
definition hides an implication or `∀` in the conclusion; `subtype` = a subtype binder assumes its property;
`bundled i` = hypothesis i is a conjunction behind a definition; `restated i` = hypothesis i is a conjunct of
the conclusion). Every such headline has exactly that line in the shrink-only baseline
`scripts/trust/necessity_shape_baseline.txt` (`<headline> | <reasons>`); with --base, the baseline may not gain
a line, so a new headline with a shape entry fails (no disclosure route: restate the headline). A headline with
a shape entry never counts as fully classified.
Conjunct parts (run 2026-11-11T1428Z, T2b item 3e): StatementDeps drops `bundled i` once every conjunct of
hypothesis i is NEEDED (`necessity% <headline> i j`) or REDUNDANT (`dropped% <headline> i j`) and lists them as
`conjuncts of i (m) needed …` / `conjuncts of i (m) redundant …`; the parser requires those parts to partition
1..m (m ≥ 2), to name an existing hypothesis, and never to stand next to `bundled i`. A baseline line may lose
reasons (a `bundled i` closed this way), never gain them; losing the witnesses brings `bundled i` back, which the
baseline no longer lists, so N4 fails (the ratchet).
The parser fails closed: exactly one section heading and one summary paragraph, every list line of the
section in the generator's grammar, no duplicate headline, indices partitioning 1..n, summary totals equal to
the sums of the lines; an unreadable base fails too (adversary of run 2026-11-11T0028Z, 7 holes in the first
draft, all repaired before the rule went live).

`--selftest` runs planted controls (each rule rejects its bad case and accepts the clean twin) and is run first
by the normal mode.

This check reads only generated text (TRUST_MAP.md) and a baseline; no author prose can satisfy it.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = "scripts/trust/necessity_open_baseline.txt"
SHAPE_BASELINE = "scripts/trust/necessity_shape_baseline.txt"
SHAPE_ITEM = re.compile(r"^(conclusion|subtype|(bundled|restated) \d+)$")

LINE = re.compile(r"^- `([^`]+)` \((\d+)\): (.*)$")
HEAD = re.compile(r"^## Hypothesis necessity, per headline$", re.M)
TOT = re.compile(r"^Hypothesis necessity \(trust track T2b[^\n]*\n(\d+) shown NEEDED [^\n]*\n(\d+) shown REDUNDANT in Lean[^\n]*?(\d+) with no obligation",
                 re.M)
LABELS = {"needed": "needed", "redundant": "redundant", "redundant (each alone, not together)": "redundant",
          "no obligation (instance, or proof used as data)": "data", "open": "open"}
WIT = re.compile(r"^(\d+) \(`[^`]+`\)$")
# per-conjunct witnesses of a bundled hypothesis (run 2026-11-11T1428Z): `conjuncts of <i> (<m>) <label> <items>`
CONJ = re.compile(r"^conjuncts of (\d+) \((\d+)\) (needed|redundant \(each alone, not together\)|redundant) (.+)$")


class ParseError(Exception):
    pass


def parse_parts(rest):
    """`needed 1 (`w`), 2 (`w`); redundant 3 (`w`); open 4, 5` -> dict label -> set of indices (strict)."""
    out = {v: set() for v in LABELS.values()}
    out["shape"] = ()
    if not rest:
        raise ParseError("empty classification")
    seen = []
    parts = rest.split("; ")
    if parts[-1].startswith("shape: "):
        items = parts[-1][len("shape: "):].split(", ")
        for it in items:
            if not SHAPE_ITEM.match(it):
                raise ParseError(f"bad shape item `{it}`")
        if len(set(items)) != len(items):
            raise ParseError("shape item twice")
        out["shape"] = tuple(items)
        parts = parts[:-1]
    out["conj"] = {}
    for part in parts:
        cm = CONJ.match(part)
        if cm:
            i, m_, lab, body = int(cm.group(1)), int(cm.group(2)), cm.group(3), cm.group(4)
            key = LABELS[lab]
            if key not in ("needed", "redundant"):
                raise ParseError(f"bad conjunct label `{lab}`")
            c = out["conj"].setdefault(i, {"m": m_, "needed": set(), "redundant": set()})
            if c["m"] != m_:
                raise ParseError(f"conjuncts of {i}: two conjunct counts")
            if c[key] or (key, i) in seen:
                raise ParseError(f"part `conjuncts of {i} {lab}` twice")
            seen.append((key, i))
            for it in body.split(", "):
                w = WIT.match(it)
                if not w:
                    raise ParseError(f"bad item `{it}` in `conjuncts of {i}`")
                c[key].add(int(w.group(1)))
            continue
        lab = next((l for l in sorted(LABELS, key=len, reverse=True) if part.startswith(l + " ")), None)
        if lab is None:
            raise ParseError(f"unknown part `{part}`")
        key = LABELS[lab]
        if key in seen:
            raise ParseError(f"part `{lab}` twice")
        seen.append(key)
        items = part[len(lab) + 1:].split(", ")
        for it in items:
            if key in ("needed", "redundant"):
                m = WIT.match(it)
                if not m:
                    raise ParseError(f"bad item `{it}` in `{lab}`")
                i = int(m.group(1))
            else:
                if not re.fullmatch(r"\d+", it):
                    raise ParseError(f"bad item `{it}` in `{lab}`")
                i = int(it)
            out[key].add(i)
    return out


def parse_map(text):
    """headline -> dict(n=..., needed=, redundant=, data=, open=); plus (needed, redundant, data) totals.
    Fails closed (ParseError) on anything it does not recognise."""
    heads = list(HEAD.finditer(text))
    if len(heads) != 1:
        raise ParseError(f"{len(heads)} section headings `## Hypothesis necessity, per headline` (need exactly 1)")
    sec = text[heads[0].end():]
    nxt = re.search(r"^## ", sec, re.M)
    if nxt:
        sec = sec[:nxt.start()]
    out = {}
    for line in sec.splitlines():
        if not line.startswith("- "):
            if line.lstrip().startswith(("- ", "* ", "+ ")):
                raise ParseError(f"unparsed list line `{line}`")
            continue
        m = LINE.match(line)
        if not m:
            raise ParseError(f"unparsed line `{line}`")
        name, n = m.group(1), int(m.group(2))
        if name in out:
            raise ParseError(f"duplicate headline `{name}`")
        d = parse_parts(m.group(3))
        if n == 0 and not d["shape"]:
            raise ParseError(f"`{name}`: a line with no hypotheses must carry a shape entry")
        for i, c in d["conj"].items():
            if not 1 <= i <= n:
                raise ParseError(f"`{name}`: conjuncts of {i}, but {n} hypotheses")
            if c["m"] < 2 or c["needed"] & c["redundant"] or c["needed"] | c["redundant"] != set(range(1, c["m"] + 1)):
                raise ParseError(f"`{name}`: conjuncts of {i} do not partition 1..{c['m']}")
            if f"bundled {i}" in d["shape"]:
                raise ParseError(f"`{name}`: conjuncts of {i} listed while the shape keeps `bundled {i}`")
        allidx = d["needed"] | d["redundant"] | d["data"] | d["open"]
        if allidx != set(range(1, n + 1)) or sum(len(d[k]) for k in set(LABELS.values())) != n:
            raise ParseError(f"`{name}`: indices {sorted(allidx)} do not partition 1..{n}")
        d["n"] = n
        out[name] = d
    tm = list(TOT.finditer(text))
    if len(tm) != 1:
        raise ParseError(f"{len(tm)} summary paragraphs `Hypothesis necessity (trust track T2b ...` (need exactly 1)")
    tot = tuple(int(tm[0].group(k)) for k in (1, 2, 3))
    if tot[0] != sum(len(d["needed"]) for d in out.values()) or \
       tot[1] != sum(len(d["redundant"]) for d in out.values()) or \
       tot[2] != sum(len(d["data"]) for d in out.values()):
        raise ParseError(f"summary totals {tot} disagree with the per-headline lines")
    return out, tot


def parse_baseline(text, errors):
    out = {}
    for k, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        parts = [p.strip() for p in s.split("|")]
        if len(parts) != 2:
            errors.append(f"{BASELINE}:{k}: expected `<headline> | <open indices>`")
            continue
        name, idx = parts
        try:
            opens = {int(x) for x in idx.replace(" ", "").split(",") if x}
        except ValueError:
            errors.append(f"{BASELINE}:{k}: indices must be integers")
            continue
        if name in out:
            errors.append(f"{BASELINE}:{k}: duplicate line for `{name}`")
        out[name] = opens
    return out


def rule_n1(m, base_lines, errors):
    for name, d in m.items():
        opens = d["open"]
        if opens and name not in base_lines:
            errors.append(f"N1: `{name}` has open hypotheses {sorted(opens)} but no line in {BASELINE}")
        elif opens and base_lines[name] != opens:
            errors.append(f"N1: `{name}`: open hypotheses are {sorted(opens)}, {BASELINE} lists "
                          f"{sorted(base_lines[name])} (update the line in the same commit)")
    for name in base_lines:
        if name not in m:
            errors.append(f"N1: {BASELINE} names `{name}`, which TRUST_MAP.md does not list")
        elif not m[name]["open"]:
            errors.append(f"N1: {BASELINE} lists `{name}`, which has no open hypothesis: remove the line")


def parse_shape_baseline(text, errors):
    out = {}
    for k, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        parts = [p.strip() for p in s.split("|")]
        if len(parts) != 2:
            errors.append(f"{SHAPE_BASELINE}:{k}: expected `<headline> | <reasons>`")
            continue
        if parts[0] in out:
            errors.append(f"{SHAPE_BASELINE}:{k}: duplicate line for `{parts[0]}`")
        out[parts[0]] = tuple(x.strip() for x in parts[1].split(","))
    return out


def rule_n4(m, shape_lines, errors):
    for name, d in m.items():
        if d["shape"] and shape_lines.get(name) != d["shape"]:
            errors.append(f"N4: `{name}` has shape entry `{', '.join(d['shape'])}` (assumptions the necessity "
                          f"numbering does not reach); {SHAPE_BASELINE} lists "
                          f"{shape_lines.get(name)}: restate the headline (no new shape entries)")
    for name in shape_lines:
        if name not in m or not m[name]["shape"]:
            errors.append(f"N4: {SHAPE_BASELINE} lists `{name}`, which has no shape entry: remove the line")


def rule_n4_base(old_text, new_text, errors):
    if old_text is None:
        return   # the base predates the shape rule
    old = {l.strip() for l in old_text.splitlines() if l.strip() and not l.strip().startswith("#")}
    oldp = {}
    for l in old:
        parts = [p.strip() for p in l.split("|")]
        if len(parts) == 2:
            oldp[parts[0]] = {x.strip() for x in parts[1].split(",")}
    for l in new_text.splitlines():
        s = l.strip()
        if s and not s.startswith("#") and s not in old:
            # a line may lose reasons (run 2026-11-11T1428Z: `bundled i` closed by conjunct witnesses), never gain
            parts = [p.strip() for p in s.split("|")]
            if len(parts) == 2 and parts[0] in oldp and {x.strip() for x in parts[1].split(",")} < oldp[parts[0]]:
                continue
            errors.append(f"N4: line added to the shrink-only {SHAPE_BASELINE}: `{s}`")


def fmt(ix):
    return ", ".join(str(i) for i in sorted(ix))


def disclosed(name, words, ledger_added):
    """a LEDGER line added in this diff names the headline (as TRUST_MAP names it) in backticks, followed
    somewhere on the line by the exact words (e.g. `open 2, 3`)."""
    return any(f"`{name}`" in l and words in l for l in ledger_added)


def classified(d):
    return d["needed"] | d["redundant"]


def rule_n2(old_map, new_map, ledger_added, errors):
    for name, d in new_map.items():
        o = old_map.get(name)
        if o is not None and o["n"] == d["n"]:
            lost = classified(o) - classified(d)
            if lost:
                errors.append(f"N2: `{name}`: hypotheses {sorted(lost)} were NEEDED/REDUNDANT at the base and are "
                              f"not now (a classification never regresses)")
        else:
            words = f"open {fmt(d['open'])}" if d["open"] else "classified"
            if (d["open"] or d["data"] or o is not None) and not disclosed(name, words, ledger_added):
                why = "is new" if o is None else f"changed its hypothesis count {o['n']} -> {d['n']}"
                errors.append(f"N2: `{name}` {why}: name it in backticks in a line added to LEDGER.md together with "
                              f"the words `{words}`")
    for name, o in old_map.items():
        if name not in new_map and classified(o) and not disclosed(name, "removed", ledger_added):
            errors.append(f"N2: `{name}` had classified hypotheses {sorted(classified(o))} at the base and is gone: "
                          f"name it in backticks with the word `removed` in a line added to LEDGER.md")


def rule_n3(old_tot, new_tot, errors):
    if new_tot[0] + new_tot[1] < old_tot[0] + old_tot[1]:
        errors.append(f"N3: NEEDED + REDUNDANT fell from {old_tot[0] + old_tot[1]} to {new_tot[0] + new_tot[1]}")
    if new_tot[2] > old_tot[2]:
        errors.append(f"N3: hypotheses with no obligation rose from {old_tot[2]} to {new_tot[2]}")


def git_show(base, rel):
    r = subprocess.run(["git", "show", f"{base}:{rel}"], cwd=ROOT, capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None


def selftest():
    fails = []
    summ = ("Hypothesis necessity (trust track T2b, run X): 6 hypotheses in 3 headlines;\n"
            "{n} shown NEEDED (a machine-checked example meeting every other hypothesis where the conclusion fails),\n"
            "{r} shown REDUNDANT in Lean (the same statement proved without it), 0 with no obligation (instance arguments, proofs used as data),\n"
            "2 open; headlines with every hypothesis classified: 2/3\n")
    sec = ("## Hypothesis necessity, per headline\n\nintro text\n\n"
           "- `A.a` (3): needed 1 (`a_h1`); open 2, 3\n- `B.b` (2): needed 1 (`b_h1`), 2 (`b_h2`)\n"
           "- `C.c` (1): redundant 1 (`c_r1`)\n\n## Next\n- `Z.z` (1): open 1\n")
    tm = "x\n" + summ.format(n=3, r=1) + sec
    m, tot = parse_map(tm)
    want = {"A.a": ({1}, set(), {2, 3}), "B.b": ({1, 2}, set(), set()), "C.c": (set(), {1}, set())}
    if {k: (v["needed"], v["redundant"], v["open"]) for k, v in m.items()} != want or tot != (3, 1, 0):
        fails.append(f"parser: {m} {tot}")
    bad_texts = {
        "duplicate headline": tm.replace("- `C.c` (1)", "- `A.a` (3): open 1, 2, 3\n- `C.c` (1)"),
        "second section heading": "## Hypothesis necessity, per headline\n" + tm,
        "unparsed list line": tm.replace("- `C.c` (1): redundant 1 (`c_r1`)", "* `C.c` (1): redundant 1 (`c_r1`)"),
        "trailing junk": tm.replace("open 2, 3\n", "open 2, 3 \n"),
        "non-partition": tm.replace("- `B.b` (2)", "- `B.b` (3)"),
        "wrong totals": "x\n" + summ.format(n=9, r=9) + sec,
        "no summary": sec,
    }
    for lbl, t in bad_texts.items():
        try:
            parse_map(t)
            fails.append(f"parser accepted: {lbl}")
        except ParseError:
            pass
    def n1(bl):
        e = []
        rule_n1(m, parse_baseline(bl, e), e)
        return e
    if n1("A.a | 2, 3\n"):
        fails.append("N1 clean twin rejected")
    if not n1(""):
        fails.append("N1 accepted a missing baseline line")
    if not n1("A.a | 2\n"):
        fails.append("N1 accepted a baseline line listing fewer open hypotheses")
    if not n1("A.a | 2, 3\nB.b | 1\n"):
        fails.append("N1 accepted a line for a fully classified headline")
    def d(n, needed=(), red=(), op=(), data=()):
        return {"n": n, "needed": set(needed), "redundant": set(red), "open": set(op), "data": set(data)}
    def n2(old, new, led):
        e = []
        rule_n2(old, new, led, e)
        return e
    old = {"A.a": d(3, needed=[1], op=[2, 3]), "B.b": d(2, needed=[1, 2])}
    if n2(old, {"A.a": d(3, needed=[1, 2], op=[3]), "B.b": d(2, needed=[1, 2])}, []):
        fails.append("N2 clean twin (progress) rejected")
    if not n2(old, {"A.a": d(3, needed=[2], op=[1, 3]), "B.b": d(2, needed=[1, 2])}, []):
        fails.append("N2 accepted a regression")
    if not n2(old, {"A.a": d(3, needed=[1], op=[2, 3]), "B.b": d(2, needed=[1], data=[2])}, []):
        fails.append("N2 accepted a needed hypothesis turned into `no obligation`")
    newD = {"A.a": d(3, needed=[1], op=[2, 3]), "B.b": d(2, needed=[1, 2]), "D.d": d(2, needed=[2], op=[1])}
    if not n2(old, newD, []):
        fails.append("N2 accepted a new headline with open hypotheses and no LEDGER line")
    if not n2(old, newD, ["- new headline `D.d`"]):
        fails.append("N2 accepted a LEDGER line without the open indices")
    if not n2(old, newD, ["- new headline `X.D.d` (open 1)"]):
        fails.append("N2 accepted a LEDGER line naming another headline")
    if n2(old, newD, ["- run X: new headline `D.d` (open 1: no witness yet)"]):
        fails.append("N2 rejected a disclosed new headline")
    if not n2(old, {"A.a": d(4, needed=[1], op=[2, 3, 4]), "B.b": d(2, needed=[1, 2])}, []):
        fails.append("N2 accepted a changed hypothesis count without a LEDGER line")
    if not n2(old, {"A.a": d(3, needed=[1], op=[2, 3])}, []):
        fails.append("N2 accepted a removed classified headline without a LEDGER line")
    if n2(old, {"A.a": d(3, needed=[1], op=[2, 3])}, ["- `B.b` removed (merged into `A.a`)"]):
        fails.append("N2 rejected a disclosed removal")
    try:
        m2, _ = parse_map(tm.replace("- `B.b` (2): needed 1 (`b_h1`), 2 (`b_h2`)",
                                     "- `B.b` (2): redundant (each alone, not together) 1 (`b_h1`), 2 (`b_h2`)")
                          .replace("3 shown NEEDED", "1 shown NEEDED").replace("1 shown REDUNDANT", "3 shown REDUNDANT"))
        if m2["B.b"]["redundant"] != {1, 2}:
            fails.append("parser: joint-redundancy label")
    except ParseError as ex:
        fails.append(f"parser rejected the joint-redundancy label: {ex}")
    tm4 = tm.replace("- `C.c` (1): redundant 1 (`c_r1`)",
                     "- `C.c` (1): redundant 1 (`c_r1`); shape: conclusion, restated 1\n- `E.e` (0): shape: subtype")
    try:
        m4, _ = parse_map(tm4)
        if m4["C.c"]["shape"] != ("conclusion", "restated 1") or m4["E.e"]["shape"] != ("subtype",):
            fails.append(f"parser: shape {m4}")
    except ParseError as ex:
        fails.append(f"parser rejected shape entries: {ex}")
        m4 = m
    for lbl, t in {"bad shape item": tm4.replace("shape: conclusion", "shape: hidden"),
                   "shape not last": tm4.replace("redundant 1 (`c_r1`); shape: conclusion, restated 1",
                                                 "shape: conclusion; redundant 1 (`c_r1`)"),
                   "zero-hypothesis line without shape": tm4.replace("- `E.e` (0): shape: subtype", "- `E.e` (0): open 1")}.items():
        try:
            parse_map(t)
            fails.append(f"parser accepted: {lbl}")
        except ParseError:
            pass
    def n4(bl):
        e = []
        rule_n4(m4, parse_shape_baseline(bl, e), e)
        return e
    if n4("C.c | conclusion, restated 1\nE.e | subtype\n"):
        fails.append("N4 clean twin rejected")
    if not n4("E.e | subtype\n"):
        fails.append("N4 accepted a shape entry without a baseline line")
    if not n4("C.c | conclusion\nE.e | subtype\n"):
        fails.append("N4 accepted a baseline line with fewer reasons")
    if not n4("C.c | conclusion, restated 1\nE.e | subtype\nA.a | subtype\n"):
        fails.append("N4 accepted a line for a headline without shape entry")
    e = []
    rule_n4_base("C.c | conclusion\n", "C.c | conclusion\nE.e | subtype\n", e)
    if not e:
        fails.append("N4 accepted a line added to the shape baseline")
    e = []
    rule_n4_base("C.c | conclusion\nE.e | subtype\n", "E.e | subtype\n", e)
    if e:
        fails.append("N4 rejected a shrinking shape baseline")
    e = []
    rule_n4_base("C.c | conclusion, bundled 1\n", "C.c | bundled 1\n", e)
    if e:
        fails.append("N4 rejected a baseline line that lost a reason")
    e = []
    rule_n4_base("C.c | conclusion\n", "C.c | conclusion, bundled 1\n", e)
    if not e:
        fails.append("N4 accepted a baseline line that gained a reason")
    e = []
    rule_n4_base("C.c | conclusion\n", "D.d | conclusion\n", e)
    if not e:
        fails.append("N4 accepted a reason moved to another headline")
    # conjunct parts (run 2026-11-11T1428Z)
    tc = tm.replace("- `C.c` (1): redundant 1 (`c_r1`)",
                    "- `C.c` (1): redundant 1 (`c_r1`); conjuncts of 1 (3) needed 1 (`w1`), 3 (`w3`); conjuncts of 1 (3) redundant 2 (`w2`)")
    try:
        mc, _ = parse_map(tc)
        if mc["C.c"]["conj"] != {1: {"m": 3, "needed": {1, 3}, "redundant": {2}}}:
            fails.append(f"parser: conjuncts {mc['C.c']['conj']}")
    except ParseError as ex:
        fails.append(f"parser rejected conjunct parts: {ex}")
    for lbl, t in {"incomplete conjuncts": tc.replace("1 (`w1`), 3 (`w3`)", "1 (`w1`)"),
                   "conjunct index out of range": tc.replace("redundant 2 (`w2`)", "redundant 4 (`w2`)"),
                   "conjuncts of a missing hypothesis": tc.replace("conjuncts of 1 (3) needed", "conjuncts of 2 (3) needed"),
                   "conjuncts next to bundled": tc.replace("redundant 2 (`w2`)", "redundant 2 (`w2`); shape: bundled 1"),
                   "conjunct both needed and redundant": tc.replace("redundant 2 (`w2`)", "redundant 2 (`w2`), 3 (`w3`)"),
                   "conjunct part twice": tc.replace("; conjuncts of 1 (3) redundant 2 (`w2`)",
                                                     "; conjuncts of 1 (3) needed 2 (`w2`)"),
                   "one conjunct": tm.replace("- `C.c` (1): redundant 1 (`c_r1`)",
                                              "- `C.c` (1): redundant 1 (`c_r1`); conjuncts of 1 (1) needed 1 (`w1`)")}.items():
        try:
            parse_map(t)
            fails.append(f"parser accepted: {lbl}")
        except ParseError:
            pass
    e = []
    rule_n3((12, 3, 0), (11, 3, 0), e)
    if not e:
        fails.append("N3 accepted a falling total")
    e = []
    rule_n3((12, 3, 0), (14, 3, 1), e)
    if not e:
        fails.append("N3 accepted a rising no-obligation count")
    e = []
    rule_n3((12, 3, 0), (14, 3, 0), e)
    if e:
        fails.append("N3 clean twin rejected")
    return fails


def main():
    fails = selftest()
    if fails:
        print("check_necessity selftest FAILED:\n  " + "\n  ".join(fails))
        return 1
    if "--selftest" in sys.argv:
        print("check_necessity selftest: OK (planted controls for the parser, N1, N2, N3, N4, conjunct parts)")
        return 0
    errors = []
    try:
        m, tot = parse_map((ROOT / "TRUST_MAP.md").read_text())
    except (ParseError, OSError) as e:
        print(f"check_necessity: FAILED: TRUST_MAP.md: {e}")
        return 1
    bl_path = ROOT / BASELINE
    if not bl_path.exists():
        print(f"check_necessity: FAILED: {BASELINE} missing")
        return 1
    base_lines = parse_baseline(bl_path.read_text(), errors)
    rule_n1(m, base_lines, errors)
    sb_path = ROOT / SHAPE_BASELINE
    if not sb_path.exists():
        print(f"check_necessity: FAILED: {SHAPE_BASELINE} missing")
        return 1
    rule_n4(m, parse_shape_baseline(sb_path.read_text(), errors), errors)
    if "--base" in sys.argv:
        k = sys.argv.index("--base")
        if k + 1 >= len(sys.argv) or sys.argv[k + 1].startswith("-"):
            print("check_necessity: FAILED: --base needs a commit")
            return 1
        b = sys.argv[k + 1]
        old_tm = git_show(b, "TRUST_MAP.md")
        lo = git_show(b, "LEDGER.md")
        if old_tm is None or lo is None:
            print(f"check_necessity: FAILED: cannot read TRUST_MAP.md / LEDGER.md at {b}")
            return 1
        try:
            old_map, old_tot = parse_map(old_tm)
        except ParseError as e:
            if HEAD.search(old_tm):
                print(f"check_necessity: FAILED: TRUST_MAP.md at {b}: {e}")
                return 1
            old_map, old_tot = {}, (0, 0, 0)   # base predates the necessity report
        base_set = {l.strip() for l in lo.splitlines()}
        added = [l for l in (ROOT / "LEDGER.md").read_text().splitlines() if l.strip() and l.strip() not in base_set]
        rule_n2(old_map, m, added, errors)
        rule_n3(old_tot, tot, errors)
        rule_n4_base(git_show(b, SHAPE_BASELINE), sb_path.read_text(), errors)
    nopen = sum(len(v["open"]) for v in m.values())
    full = sum(1 for v in m.values() if v["n"] and not v["open"] and not v["data"] and not v["shape"])
    if errors:
        print("check_necessity: FAILED\n  " + "\n  ".join(errors))
        return 1
    print(f"check_necessity: OK ({len(m)} headlines with hypotheses, {full} fully classified, {nopen} open "
          f"hypotheses, all in {BASELINE}; needed/redundant/no obligation {tot})"
          + (" [with --base]" if "--base" in sys.argv else " [no --base: N2/N3 not run]"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
