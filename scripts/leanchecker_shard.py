#!/usr/bin/env python3
"""Kernel replay of the Checked library with the toolchain's leanchecker, shard I of K (part of the judge,
annex 39.5; run 2026-11-18T1828Z, see LEDGER).

Why: lean-action's leanchecker step ran `lake env leanchecker Checked` inside the checked job on one thread
(LEAN_NUM_THREADS=1); it replays every module of Checked from its imports and took 47 min on 2026-11-12 and
140 min on 2026-11-18 (job 134891775171), putting the checked job at 180-211 min of its 240-min limit and
holding every later checked job pending for 3 h. The same check is now split into K jobs that run in parallel.

What it checks (unchanged): `leanchecker M1 … Mn` replays, for each listed module, every declaration the module
adds into the environment of its imports, with the Lean kernel (LeanChecker.lean, `replayFromImports`), and
fails if any module's olean is missing or any declaration is rejected. The module list of Checked is every
tracked `Checked/**/*.lean` plus `Checked.lean` (the files `lake build Checked` builds; an untracked or
unimported file would have no olean and fail the shard, never pass silently). Shard i takes the modules whose
FNV-1a hash (as in scripts/nanoda/ShardMain.lean) is i mod K, so the K shards partition the module list:
K green shards replay every module the single `leanchecker Checked` call replayed.

Timing (run 2026-11-18T2228Z, annex LIV): the shard's modules are replayed in consecutive groups of GROUP modules
(one leanchecker call per group, same modules, same order), and each group's wall time is printed
(`leanchecker-time <seconds> <modules>`). Why: in branch trial 44373171551 shard 2 replayed for 182 min and shards
0, 1, 3 for 44-48 min (job limit 240 min); olean sizes do not predict the difference, so the partition can only be
balanced on measured times, which one call per shard does not report. Every module of the shard is still replayed and
any failing group fails the shard.

Assignment (run 2026-11-19T0228Z, annex LIV; LEDGER experiment of run 2026-11-18T2228Z): the FNV-1a partition put
modules worth about 3x the replay time of each other shard into shard 2 (2026-11-19, 44424316043: shards 0, 1, 3
replayed in 53, 52, 48 min; shard 2 over 170 min), and nanoda's shards (scripts/nanoda/ShardMain.lean, same hash)
the same way. `scripts/nanoda/shard_assignment.txt` (`<module> <shard>` per line, generated by `--assign` from the
measured per-group times in `scripts/nanoda/shard_times.txt` by a deterministic greedy partition) now decides the
shard of every module it lists, for both judges; a module it does not list keeps its FNV-1a shard. Each module still
has exactly one shard (a function of its name), so the K shards still partition the module list; the selftest checks it.

Exact replay of prefix modules (run 2026-11-19T0628Z, annex LIV, see LEDGER): `leanchecker M` replays every module
whose name has M as a component prefix, so the root module `Checked` passed to leanchecker replayed the whole library
again inside its shard (2026-11-19: 10,159 s of one group of eight; shard 0 of run 44451569867 past 3 h, the other
three 37-49 min). A module whose name is a prefix of another module's (`prefix_modules`, only `Checked`) is now
replayed exactly by scripts/leanchecker_exact.lean, which calls the toolchain's own `replayFromImports` (the function
leanchecker calls per module). The set of modules each shard replays is unchanged; nothing is replayed twice.

Usage:
  python3 scripts/leanchecker_shard.py I K           # run leanchecker on shard I of K (needs `lake build Checked`)
  python3 scripts/leanchecker_shard.py --assign K    # regenerate scripts/nanoda/shard_assignment.txt from the times
  python3 scripts/leanchecker_shard.py --list I K    # print the modules of shard I
  python3 scripts/leanchecker_shard.py --selftest    # the K lists partition the module list, none empty
"""
import subprocess
import sys
import time

GROUP = 8


def modules() -> list[str]:
    out = subprocess.run(["git", "ls-files", "Checked.lean", "Checked/*.lean"], capture_output=True,
                         text=True, check=True).stdout.split()
    mods = []
    for p in out:
        assert p.endswith(".lean"), p
        mods.append(p[: -len(".lean")].replace("/", "."))
    if "Checked" not in mods:
        raise SystemExit("Checked.lean is not tracked")
    return sorted(set(mods))


ASSIGN = "scripts/nanoda/shard_assignment.txt"
TIMES = "scripts/nanoda/shard_times.txt"


def _root():
    return subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True,
                          check=True).stdout.strip()


def assignment() -> dict:
    """module -> assigned shard (read by scripts/nanoda/ShardMain.lean in the same format)"""
    import os
    p = os.path.join(_root(), ASSIGN)
    out = {}
    if not os.path.exists(p):
        return out
    for line in open(p, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(" ")
        if len(parts) != 2 or not parts[1].isdigit():
            raise SystemExit(f"bad line in {ASSIGN}: {line!r}")
        if parts[0] in out:
            raise SystemExit(f"module listed twice in {ASSIGN}: {parts[0]}")
        out[parts[0]] = int(parts[1])
    return out


_ASSIGN = None


def shard_of(name: str, k: int) -> int:
    global _ASSIGN
    if _ASSIGN is None:
        _ASSIGN = assignment()
    if name in _ASSIGN:
        return _ASSIGN[name] % k
    return fnv_shard(name, k)


def fnv_shard(name: str, k: int) -> int:
    h = 14695981039346656037
    for c in name:
        h = ((h ^ ord(c)) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h % k


def prefix_modules(mods=None) -> set:
    """modules whose name is a component prefix of another module's name: `leanchecker M` replays every module
    with prefix M (LeanChecker.lean, checkOlean: `target.isPrefixOf m`), so these must be replayed exactly"""
    mods = modules() if mods is None else mods
    s = set(mods)
    return {m for m in s if any(o.startswith(m + ".") for o in s)}


def shard(i: int, k: int) -> list[str]:
    return [m for m in modules() if shard_of(m, k) == i]


def selftest() -> int:
    mods = modules()
    for k in (1, 2, 4):
        lists = [shard(i, k) for i in range(k)]
        flat = [m for l in lists for m in l]
        if sorted(flat) != mods or len(set(flat)) != len(flat):
            print(f"selftest FAILED: the {k} shards do not partition the {len(mods)} modules")
            return 1
        if any(not l for l in lists):
            print(f"selftest FAILED: an empty shard at k = {k}")
            return 1
    # prefix detection (run 2026-11-19T0628Z): planted controls
    if prefix_modules(["Checked", "Checked.A", "Checked.A.B", "Checked.AB"]) != {"Checked", "Checked.A"}:
        print("selftest FAILED: prefix_modules planted control")
        return 1
    if "Checked" not in prefix_modules(mods):
        print("selftest FAILED: the root module Checked is not detected as a prefix module")
        return 1
    print(f"selftest: {len(mods)} modules; shards of 4: {[len(shard(i, 4)) for i in range(4)]}; "
          f"replayed exactly: {sorted(prefix_modules(mods))}")
    return 0


def assign(k: int) -> int:
    """greedy longest-processing-time partition on the measured times: modules in decreasing time (name breaks
    ties) each go to the shard with the least total so far (lowest index breaks ties); modules with no measured
    time count at the median measured time"""
    import os, statistics
    root = _root()
    times = {}
    for line in open(os.path.join(root, TIMES), encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#"):
            m, t = line.split(" ")
            times[m] = float(t)
    mods = modules()
    med = statistics.median(times.values())
    w = {m: times.get(m, med) for m in mods}
    load = [0.0] * k
    out = {}
    for m in sorted(mods, key=lambda m: (-w[m], m)):
        j = min(range(k), key=lambda j: (load[j], j))
        out[m] = j
        load[j] += w[m]
    with open(os.path.join(root, ASSIGN), "w", encoding="utf-8") as f:
        f.write("# Shard of each Checked module for the leanchecker and nanoda judges (generated by\n"
                "# `python3 scripts/leanchecker_shard.py --assign %d` from scripts/nanoda/shard_times.txt; run 2026-11-19T0228Z; times regenerated run 2026-11-19T0628Z).\n"
                "# Format: <module> <shard>. Modules not listed keep their FNV-1a shard. Predicted replay seconds per shard: %s\n"
                % (k, ", ".join(f"{x:.0f}" for x in load)))
        for m in sorted(out):
            f.write(f"{m} {out[m]}\n")
    print(f"assigned {len(out)} modules to {k} shards; predicted seconds {[round(x) for x in load]}")
    return 0


def main(argv: list[str]) -> int:
    if argv[1:] == ["--selftest"]:
        return selftest()
    if len(argv) == 3 and argv[1] == "--assign":
        return assign(int(argv[2]))
    if len(argv) == 4 and argv[1] == "--list":
        print("\n".join(shard(int(argv[2]), int(argv[3]))))
        return 0
    if len(argv) != 3:
        print(__doc__)
        return 2
    i, k = int(argv[1]), int(argv[2])
    if not (0 <= i < k):
        print("need 0 <= I < K")
        return 2
    mods = shard(i, k)
    if not mods:
        print(f"shard {i} of {k} is empty")
        return 1
    print(f"leanchecker shard {i} of {k}: {len(mods)} of {len(modules())} modules", flush=True)
    pre = prefix_modules()
    exact = [m for m in mods if m in pre]
    rest = [m for m in mods if m not in pre]
    if exact:
        # A module whose name is a prefix of another module's name (only the root `Checked`) is replayed exactly, by
        # the toolchain's own replayFromImports (scripts/leanchecker_exact.lean): `leanchecker Checked` would replay
        # every module of the library (run 2026-11-19T0628Z, see LEDGER).
        t0 = time.monotonic()
        import os
        env = dict(os.environ, LEANCHECKER_EXACT=" ".join(exact))
        r = subprocess.run(["lake", "env", "lean", "scripts/leanchecker_exact.lean"], env=env)
        print(f"leanchecker-time {time.monotonic() - t0:.0f} {' '.join(exact)}", flush=True)
        if r.returncode != 0:
            print(f"leanchecker shard {i} of {k} FAILED (exit {r.returncode}) in the exact replay of {' '.join(exact)}")
            return 1
    for g in range(0, len(rest), GROUP):
        group = rest[g:g + GROUP]
        if any(p in pre for p in group):  # never reached: kept so a later edit cannot pass a prefix module
            print(f"leanchecker shard {i} of {k} FAILED: a prefix module in a leanchecker group")
            return 1
        t0 = time.monotonic()
        r = subprocess.run(["lake", "env", "leanchecker", *group])
        print(f"leanchecker-time {time.monotonic() - t0:.0f} {' '.join(group)}", flush=True)
        if r.returncode != 0:
            print(f"leanchecker shard {i} of {k} FAILED (exit {r.returncode}) in the group {' '.join(group)}")
            return 1
    print(f"leanchecker: Checked shard {i} of {k} passed ({len(mods)} modules)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
